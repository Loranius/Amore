// Родовий відмінок імені — правилами, а не таблицею (ADR-0209 §15).
// ------------------------------------------------------------
// «Бажання Лєни», «Ідеї Олексія». До цього тут була таблиця на два імені
// й повернення називного для решти, тобто зареєстрована пара читала
// «Бажання Олексій» — називний у родовому місці.
//
// ПРАВИЛО ЗАСТОСОВУЄТЬСЯ ЛИШЕ ТАМ, ДЕ ВОНО ВПЕВНЕНЕ. Усе інше
// повертається незміненим — рівно так, як поводилась таблиця. Тобто
// найгірше, що може статись, — те саме, що є сьогодні; а найкраще —
// правильна форма. Вигадувати відмінок навмання гірше за обидва:
// помилка тут не абстрактна, її пара читає власним іменем.
//
// ЧОМУ ЛИШЕ КИРИЛИЦЯ. «Marie» за правилом на «-е» не змінюється взагалі,
// але «Anna» потрапила б під «-а → -и» й стала б «Anni». Латиниця тут не
// українське ім'я, і відмінювати її нема за чим.
// ============================================================

/** Шиплячі: після них «-а» дає «-і», а не «-и» (Саша → Саші). */
const HUSHING = new Set(['ж', 'ч', 'ш', 'щ']);

/**
 * Імена, що не йдуть за правилом свого закінчення.
 *
 * Список короткий і НАЗВАНИЙ навмисно: кожен запис — місце, де правило
 * помиляється, і воно має бути видно очима, а не ховатись у розгалуженні.
 *
 * `Ігор` і `Лазар` мають м'яку основу, хоч закінчуються на «р», як
 * `Назар` із твердою. З самого рядка це не виводиться.
 * `Любов` — жіноче ім'я на приголосний, тобто третя відміна.
 */
const EXCEPTIONS: Readonly<Record<string, string>> = {
  Ігор: 'Ігоря',
  Лазар: 'Лазаря',
  Любов: 'Любові',
  Нінель: 'Нінелі',
};

const CYRILLIC_ONLY = /^[А-Яа-яЄєІіЇїҐґ'’-]+$/;

/**
 * Ім'я в родовому відмінку, або воно ж без змін.
 *
 * `name` очікується вже обрізаним (`asUserName`). Порожній рядок
 * повертається як є.
 */
export function ukrainianGenitive(name: string): string {
  if (name.length === 0) return name;
  const exception = EXCEPTIONS[name];
  if (exception !== undefined) return exception;
  if (!CYRILLIC_ONLY.test(name)) return name;

  const last = name.slice(-1);
  const stem = name.slice(0, -1);
  const beforeLast = stem.slice(-1).toLowerCase();

  // «-ія» → «-ії»: Марія, Софія, Наталія, Юлія.
  if (last === 'я' && beforeLast === 'і') return `${stem}ї`;
  // Решта «-я» → «-і»: Оля, Катя, Настя, Наталя, Ілля.
  if (last === 'я') return `${stem}і`;
  // «-а» → «-и», але після шиплячих → «-і»: Лєна → Лєни, Саша → Саші.
  if (last === 'а') return `${stem}${HUSHING.has(beforeLast) ? 'і' : 'и'}`;
  // «-й» → «-я»: Андрій, Олексій, Сергій.
  if (last === 'й') return `${stem}я`;
  // «-ь» → «-я»: Василь, Віталь.
  if (last === 'ь') return `${stem}я`;
  // «-о» → «-а»: Петро, Дмитро, Павло, Марко.
  if (last === 'о') return `${stem}а`;
  // Тверда приголосна → «-а»: Іван, Олег, Максим, Тарас, Назар.
  if (isConsonant(last)) return `${name}а`;

  /*
   * Усе інше — «-е», «-у», «-и» та решта — лишається як є. Українські
   * імена на ці літери або незмінні, або надто рідкісні, щоб правило
   * було впевненим.
   */
  return name;
}

const VOWELS = new Set(['а', 'е', 'є', 'и', 'і', 'ї', 'о', 'у', 'ю', 'я']);

function isConsonant(letter: string): boolean {
  const lower = letter.toLowerCase();
  return CYRILLIC_ONLY.test(lower) && !VOWELS.has(lower) && lower !== 'ь' && lower !== "'" && lower !== '’';
}
