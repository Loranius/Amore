import { describe, expect, it } from 'vitest';
import { plural } from './plural';

// ============================================================
// Правило, яке в порталі жило чотирма копіями.
// ------------------------------------------------------------
// Кожна копія писала виняток 11–14 своїми словами, і саме на ньому
// «майже правильна» реалізація ламається: 11 і 21 закінчуються
// однаково, але перше — «років», а друге — «рік». Пара, яка разом
// одинадцять років, бачить цей виняток на кожному екрані.
// ============================================================

const years = (n: number) => plural(n, 'рік', 'роки', 'років');

describe('числівник узгоджується з іменником', () => {
  it.each([
    [1, 'рік'], [2, 'роки'], [3, 'роки'], [4, 'роки'], [5, 'років'],
    [10, 'років'], [11, 'років'], [12, 'років'], [13, 'років'], [14, 'років'],
    [15, 'років'], [20, 'років'], [21, 'рік'], [22, 'роки'], [25, 'років'],
    [101, 'рік'], [111, 'років'], [121, 'рік'],
  ])('%i — «%s»', (count, word) => {
    expect(years(count)).toBe(word);
  });

  it('нуль — форма множини, а не однини', () => {
    // «0 років», не «0 рік»: підпис під порожньою смугою це показує.
    expect(years(0)).toBe('років');
  });

  it('одинадцять і двадцять один розходяться', () => {
    expect(years(11)).not.toBe(years(21));
    expect(years(111)).not.toBe(years(121));
  });

  it('від\'ємні й дробові не ламають правило', () => {
    /*
     * Лічильник росту вміє бути від'ємним (`growthSinceLastVisit`), а
     * дроби прилітають із ділення. Обидва мають дати слово, а не
     * `undefined`.
     */
    expect(years(-1)).toBe('рік');
    expect(years(-11)).toBe('років');
    expect(years(2.7)).toBe('роки');
  });
});
