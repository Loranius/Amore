// ============================================================
// Українське узгодження числівника з іменником.
// ------------------------------------------------------------
// Правило одне, а копій у порталі було ЧОТИРИ: `EventDetails.plural`,
// `growthSinceLastVisit.momentPhrase`, `YearStrip.yearsWord` і
// `YearStrip.emptyWord`. Заповнення історії ледь не додало п'яту й
// шосту — і саме тоді стало видно, що це не дрібниця: правило з
// винятком на 11–14 легко написати «майже правильно», а помітити
// «11 частини» замість «11 частин» можна лише очима й лише на тому
// екрані, де саме одинадцять.
//
// Пара, яка разом одинадцять років, бачить цей виняток скрізь.
// ============================================================

/**
 * Форма іменника при числі.
 *
 * @param one  1, 21, 31 … — «рік», «частина», «день»
 * @param few  2–4, 22–24 … — «роки», «частини», «дні»
 * @param many 0, 5–20, 25–30 … — «років», «частин», «днів»
 *
 * Виняток 11–14 стоїть ПЕРЕД розбором останньої цифри навмисно:
 * одинадцять і двадцять один закінчуються однаково, але перше — «років»,
 * а друге — «рік».
 */
export function plural(count: number, one: string, few: string, many: string): string {
  const tail = Math.abs(Math.trunc(count)) % 100;
  if (tail >= 11 && tail <= 14) return many;
  switch (tail % 10) {
    case 1: return one;
    case 2:
    case 3:
    case 4: return few;
    default: return many;
  }
}
