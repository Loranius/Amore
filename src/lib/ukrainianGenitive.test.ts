import { describe, expect, it } from 'vitest';
import { ukrainianGenitive } from './ukrainianGenitive';

// ============================================================
// Родовий відмінок імені (ADR-0209 §15).
// ------------------------------------------------------------
// ВИМОГА. «Бажання Лєни», а не «Бажання Лєна». До цього тут була таблиця
// на два імені, тож будь-яка інша пара читала називний у родовому місці.
//
// ЗАМІР — САМА ТАБЛИЦЯ НИЖЧЕ. Правило без переліку справжніх імен із
// відомими формами не можна ні перевірити, ні спростувати; тому «окрема
// робота з власним заміром», названа межею §11.3, — це і є цей перелік.
// ============================================================

describe('імена цієї пари не зрушені ні на символ', () => {
  it('Діма й Лєна дають ті самі форми, що й таблиця до цього', () => {
    // Інваріант: правило замінило таблицю, а не поведінку.
    expect(ukrainianGenitive('Діма')).toBe('Діми');
    expect(ukrainianGenitive('Лєна')).toBe('Лєни');
  });
});

describe('жіночі імена', () => {
  const table: ReadonlyArray<readonly [string, string]> = [
    ['Анна', 'Анни'],
    ['Марина', 'Марини'],
    ['Оксана', 'Оксани'],
    ['Ольга', 'Ольги'],
    ['Тетяна', 'Тетяни'],
    ['Марія', 'Марії'],
    ['Софія', 'Софії'],
    ['Юлія', 'Юлії'],
    ['Наталія', 'Наталії'],
    ['Наталя', 'Наталі'],
    ['Оля', 'Олі'],
    ['Катя', 'Каті'],
    ['Настя', 'Насті'],
    ['Саша', 'Саші'],
    ['Даша', 'Даші'],
  ];
  for (const [name, genitive] of table) {
    it(`${name} → ${genitive}`, () => expect(ukrainianGenitive(name)).toBe(genitive));
  }
});

