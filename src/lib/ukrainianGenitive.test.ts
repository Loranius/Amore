describe('винятки названі, а не сховані в розгалуженні', () => {
  /*
   * Кожен із них — місце, де правило свого закінчення помиляється.
   * «Ігор» і «Лазар» мають мʼяку основу, хоч кінчаються на «р», як
   * «Назар» із твердою; з рядка це не виводиться. «Любов» — жіноче
   * імʼя на приголосний, тобто третя відміна.
   */
  it('мʼяка основа на «р»', () => {
    expect(ukrainianGenitive('Ігор')).toBe('Ігоря');
    expect(ukrainianGenitive('Лазар')).toBe('Лазаря');
    // І сусід із твердою основою правилом не зачеплений.
    expect(ukrainianGenitive('Назар')).toBe('Назара');
  });

  it('жіноче імʼя на приголосний', () => {
    expect(ukrainianGenitive('Любов')).toBe('Любові');
  });
});

describe('де правило мовчить — там воно й мовчить', () => {
  it('латиниця не відмінюється зовсім', () => {
    // «Anna» під правилом «-а → -и» стала б «Anni». Латиниця тут не
    // українське імʼя, і відмінювати її нема за чим.
    expect(ukrainianGenitive('Anna')).toBe('Anna');
    expect(ukrainianGenitive('Marie')).toBe('Marie');
    expect(ukrainianGenitive('John')).toBe('John');
  });

  it('закінчення без упевненого правила лишаються як є', () => {
    expect(ukrainianGenitive('Уляне')).toBe('Уляне');
    expect(ukrainianGenitive('Бору')).toBe('Бору');
  });

  it('порожній рядок не ламає нічого', () => {
    expect(ukrainianGenitive('')).toBe('');
  });

  it('складене імʼя йде за своїм останнім складником', () => {
    // «Анна-Марія» → «Анна-Марії»: відмінюється кінець, як і має бути.
    expect(ukrainianGenitive('Анна-Марія')).toBe('Анна-Марії');
  });
});
