// ============================================================
// Гроші однією мовою на весь портал.
// ------------------------------------------------------------
// `fmtMoney` жив у `features/piggybank/useBudget.ts` разом із запитами
// скарбнички, і плани імпортували його звідти — тобто модуль планів
// залежав від модуля скарбнички заради одного рядка форматування.
//
// Коли скарбничку видалили, форматер лишився потрібним: у планів є
// власний бюджет, і його теж треба показувати. Тут йому й місце — це
// чиста функція без жодного стану.
// ============================================================

/** Сума → «1 234 ₴». */
export const fmtMoney = (n: number | null | undefined): string =>
  Math.round(Math.abs(Number(n) || 0)).toLocaleString('uk-UA') + ' ₴';
