// Мініатюри: просити в сховища рівно той розмір, який показуємо.
// ------------------------------------------------------------
// **Виміряно на живому порталі, і це найдорожча вада, яку знайшов аудит.**
// Галерея «Спогадів» тягнула 15.83 МБ фотографій, щоб намалювати картки
// розміром 127×127 CSS-пікселів. Тридцять дев'ять файлів, у середньому по
// 416 КБ, найбільший — 11 МБ. Природний розмір знімків 1200×1600, тобто
// завантажувалось приблизно в двадцять разів більше пікселів, ніж
// потрапляло на екран.
//
// Supabase Storage вміє віддавати зменшену копію сам
// (`/storage/v1/render/image/public/…?width=…`), і ця копія кешується на
// його CDN. Виміряно на справжньому файлі 364 КБ:
//
// | ширина | вага   | у скільки разів менше |
// |--------|--------|-----------------------|
// | 128    | 21 КБ  | 17.2                  |
// | 192    | 32 КБ  | 11.5                  |
// | 256    | 44 КБ  |  8.3                  |
// | 512    | 108 КБ |  3.4                  |
//
// Формат вибирає сам сервер за заголовком `Accept`, тож браузер отримує
// WebP без жодного коду з нашого боку.
//
// Модуль чистий: жодного React, жодної мережі. Перевіряється тестом, бо
// зіпсований URL тут не падає — він тихо віддає 404, і на екрані
// з'являється порожня рамка замість фотографії.
// ============================================================

/**
 * Прикмета публічного об'єкта Supabase Storage.
 *
 * Трансформувати можна ЛИШЕ такі адреси. Знімок із Cloudinary, з чужого
 * сайту чи `blob:`-прев'ю з форми мусить лишитись недоторканим: дописаний
 * до нього `?width=` у кращому разі проігнорується, а в гіршому зламає
 * підписаний URL.
 */
const STORAGE_OBJECT = '/storage/v1/object/public/';
const STORAGE_RENDER = '/storage/v1/render/image/public/';

/**
 * Сходинки ширини, які взагалі можна попросити.
 *
 * Округлення обов'язкове, і причина не в естетиці. Кожна унікальна пара
 * (файл, ширина) — окремий запис у кеші CDN; якби ширина бралась із
 * фактичного `clientWidth`, то 127, 128 і 131 пікселя дали б три різні
 * файли на трьох різних телефонах, і жоден із них не влучив би в чужий
 * прогрітий кеш.
 *
 * Верхня сходинка — 1600: це вже повний розмір знімка після стиснення
 * при завантаженні (`compress`, maxSide 1280…1600), просити більше немає
 * сенсу.
 */
const WIDTH_STEPS = [128, 192, 256, 384, 512, 768, 1080, 1600] as const;

/**
 * Стеля щільності пікселів, яку ми готові оплатити трафіком.
 *
 * На екрані з DPR 3 «чесна» ширина була б у 2.25 раза важчою за DPR 2, а
 * різницю на фотографії — не на тексті й не на лінії — побачити майже
 * неможливо. Тому щільність обрізається двійкою: це компроміс на користь
 * того, хто дивиться галерею з мобільного інтернету.
 */
export const MAX_PIXEL_RATIO = 2;

/** Якість JPEG/WebP, яку просимо в сервера. */
const QUALITY = 72;

/**
 * Режим масштабування. **Задавати обов'язково.**
 *
 * Це найдорожча пастка всього ендпойнта, і вона мовчазна. Якщо передати
 * саму `width`, Supabase НЕ масштабує знімок пропорційно — він лишає
 * оригінальну висоту й вирізає вертикальну смугу посередині. Виміряно на
 * справжньому файлі 1200×1600:
 *
 *   ?width=384                  → 384×1600, 75 КБ  (смуга з середини кадру)
 *   ?width=384&resize=contain   → 384×512,  41 КБ  (той самий кадр, менший)
 *
 * Перша редакція цього модуля параметр не ставила, і галерея показала б
 * усі фотографії обрізаними по боках. У коді це виглядало правильно;
 * побачити можна було лише вимірявши, що саме приїхало.
 */
const RESIZE = 'contain';

/** Найменша сходинка, якої вистачає на задану ширину. */
export function stepFor(pixels: number): number {
  const last = WIDTH_STEPS[WIDTH_STEPS.length - 1]!;
  if (!Number.isFinite(pixels) || pixels <= 0) return WIDTH_STEPS[0]!;
  return WIDTH_STEPS.find((step) => step >= pixels) ?? last;
}

/**
 * Щільність пікселів пристрою, обрізана стелею.
 *
 * Поза браузером (тест, збірка) — одиниця: вигадувати екран там нічого.
 */
export function pixelRatio(): number {
  if (typeof window === 'undefined') return 1;
  const raw = window.devicePixelRatio;
  if (!Number.isFinite(raw) || raw <= 0) return 1;
  return Math.min(raw, MAX_PIXEL_RATIO);
}

export interface ThumbOptions {
  /** Готова щільність; за замовчуванням береться з екрана. */
  dpr?: number;
  /** Якість 1…100. Знижується лише там, де кадр іде під затемненням. */
  quality?: number;
}

/**
 * URL зменшеної копії, або той самий URL, якщо зменшити не можна.
 *
 * `cssWidth` — ширина, з якою картинка ляже на екран У CSS-ПІКСЕЛЯХ;
 * щільність домножується всередині. Тобто викликати треба так, як
 * читається розкладка («картка 128 пікселів»), а не так, як думає
 * відеопам'ять.
 *
 * Повертає вихідний рядок без змін, коли:
 *  - це не публічний об'єкт Supabase Storage (чужий CDN, `blob:`, `data:`);
 *  - адреса вже трансформована — щоб не накласти параметри двічі;
 *  - потрібна ширина дорівнює найбільшій сходинці, тобто зменшувати нічого.
 */
export function thumbUrl(
  url: string | null | undefined,
  cssWidth: number,
  options: ThumbOptions = {},
): string {
  if (!url) return '';
  if (url.includes(STORAGE_RENDER)) return url;
  const at = url.indexOf(STORAGE_OBJECT);
  if (at === -1) return url;

  const dpr = options.dpr ?? pixelRatio();
  const width = stepFor(Math.round(cssWidth * dpr));
  const quality = options.quality ?? QUALITY;

  // Власні параметри вихідної адреси (`?t=…` проти кешу) треба зберегти:
  // саме вони роблять URL унікальним після перезавантаження знімка.
  const [path, query = ''] = url.split('?', 2);
  const rendered = path!.replace(STORAGE_OBJECT, STORAGE_RENDER);
  const params = new URLSearchParams(query);
  params.set('width', String(width));
  params.set('resize', RESIZE);
  params.set('quality', String(quality));
  return `${rendered}?${params.toString()}`;
}
