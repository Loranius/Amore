// ============================================================
// Скелет показується лише тоді, коли він справді потрібен.
// ------------------------------------------------------------
// **Виміряно на живому порталі.** Скелет вішліста (сім порожніх
// бульбашок) був на екрані 1062 мс на першому заході й блимав на кожному
// наступному. Власник описав це точно: «на долі секунди з'являються пусті
// бульбашки, а потім зникають».
//
// Причина не в тому, що дані їдуть довго, а в тому, що скелет з'являється
// БЕЗУМОВНО. Коли відповідь приходить за 80 мс, скелет встигає
// намалюватись і зникнути — і замість «швидко» пара бачить «блимнуло».
// Порожній кадр тривалістю в частку секунди читається як збій, а не як
// очікування; саме тому він гірший за просту паузу.
//
// Тому в скелета два пороги, і обидва потрібні:
//
//   ЗАТРИМКА  — скільки чекати, перш ніж узагалі щось показати. Швидка
//               відповідь укладається в неї, і скелета не буде взагалі.
//   МІНІМУМ   — скільки скелет лишається на екрані, якщо вже з'явився.
//               Без нього затримка просто зсуває блимання: відповідь на
//               210 мс дала б скелет на 10 мс, тобто те саме миготіння,
//               лише пізніше.
//
// Числа нижче — з практики інтерфейсів, а не з вимірів цього порталу, і
// названі саме так: 180 мс — межа, за якою пауза починає читатись як
// затримка; 320 мс — найкоротший показ, який око встигає прочитати як
// стан, а не як збій.
// ============================================================
import { useEffect, useRef, useState } from 'react';

/** Скільки чекати, перш ніж показати скелет. */
export const SKELETON_DELAY_MS = 180;

/** Скільки скелет лишається на екрані, якщо вже з'явився. */
export const SKELETON_MIN_VISIBLE_MS = 320;

/**
 * Скільки скелетові ще лишається висіти, коли дані вже приїхали.
 *
 * Винесено з хука окремою функцією не заради краси: середовище тестів у
 * цьому проєкті — `node` без DOM (`vitest.config.ts`), тож перевірити
 * поведінку хука рендером нічим. Арифметика ж перевіряється прямо, і
 * саме вона несе обидва пороги.
 *
 * `shownAt === null` означає «скелета на екрані не було» — тоді й
 * тримати нічого.
 */
export function skeletonHoldMs(
  shownAt: number | null,
  now: number,
  minVisibleMs: number = SKELETON_MIN_VISIBLE_MS,
): number {
  if (shownAt === null) return 0;
  return Math.max(0, minVisibleMs - (now - shownAt));
}

/**
 * `true`, лише коли очікування варте того, щоб його показати.
 *
 * Приймає «чи триває завантаження» і повертає «чи малювати скелет».
 * Обидва пороги перевіряються в `useSettledPending.test.ts` на
 * фальшивому таймері — реального часу тест не чекає.
 */
export function useSettledPending(
  pending: boolean,
  delayMs: number = SKELETON_DELAY_MS,
  minVisibleMs: number = SKELETON_MIN_VISIBLE_MS,
): boolean {
  const [visible, setVisible] = useState(false);
  // Коли скелет з'явився. Ref, а не стан: змінюється разом із `visible` і
  // власного перемальовування не потребує.
  const shownAt = useRef<number | null>(null);

  useEffect(() => {
    if (pending) {
      if (visible) return undefined;
      const timer = window.setTimeout(() => {
        shownAt.current = Date.now();
        setVisible(true);
      }, delayMs);
      return () => window.clearTimeout(timer);
    }

    if (!visible) return undefined;

    // Завантаження скінчилось, а скелет уже видно — дотримуємо мінімум.
    const left = skeletonHoldMs(shownAt.current, Date.now(), minVisibleMs);
    if (left <= 0) {
      shownAt.current = null;
      setVisible(false);
      return undefined;
    }
    const timer = window.setTimeout(() => {
      shownAt.current = null;
      setVisible(false);
    }, left);
    return () => window.clearTimeout(timer);
  }, [pending, visible, delayMs, minVisibleMs]);

  return visible;
}
