// Адреса сторінки гри в порталі (ADR-0239).
/**
 * Адреса гри. GitHub Pages віддає `game.html` з кешем на 10 хвилин, тож зі
 * сталою адресою (`?v=5`) телефон після викладання ще довго показував стару
 * гру (власник, 2026-10-05: «нічого не змінилось на подвір'ї»). Позначка
 * збірки робить адресу новою з кожним викладанням.
 */
export function gameSrc(base: string, build: string): string {
  return `${base}game.html?v=${encodeURIComponent(build)}`;
}
