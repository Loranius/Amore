// ============================================================
// Погріб на подвір'ї Лєни — за планом, який власник сам намалював і
// зберіг (2026-10-05, «План погреба»): «з двох сторін перегородки, а
// прямо стелаж з банками закруток». У клітинках плану:
//
//   погріб              x3–14, y3–9
//   засік · картопля    x3–4,  y3–9  — ліворуч, за перегородкою
//   перегородка         x5,    y3–9
//   стелаж із банками   x6–11, y3–4  — прямо, біля задньої стіни
//   перегородка         x12,   y3–9
//   засік · буряк, морква x13–14, y3–9 — праворуч, за перегородкою
//   сходи               x8–9,  y8–9  — вхід знизу, по сходах
//
// Клітинка плану — півтори клітинки гри (x → 1 + 1.5·(x − 3),
// y → 2 + 1.5·(y − 3)): погріб — 18×10 клітинок землі, над ним — задня
// кам'яна стіна.
// ============================================================
import { MapBuilder } from './build';
import type { GameMap } from './types';

export const CELLAR_ID = 'zhylyntsi:cellar';

let cached: GameMap | null = null;

export function cellarMap(): GameMap {
  if (cached) return cached;
  const W = 20;
  const H = 13;
  const m = new MapBuilder(CELLAR_ID, null, 'Погріб', W, H, 'x', true);
  m.fill(1, 0, 18, 2, 'S'); // задня стіна з бутового каменю
  m.fill(1, 2, 18, 10, 'e'); // утоптана земля

  // Засіки — за перегородками з обох боків.
  m.prop('zasik', 1.1, 2.3, { variant: 0 }).prop('zasik', 15.8, 2.3, { variant: 1 });
  m.prop('partition', 4.3, 2).prop('partition', 15.2, 2);
  // Прямо — стелаж із банками закруток.
  m.prop('jarShelf', 5.5, 2.3);
  m.prop('cellarStairs', 8.5, 9.6, { solid: false });

  m.zone('exit', 9, 11, 2, 1, { type: 'exit' }, 'Вийти на подвір\'я');
  m.zone('jars', 8, 4, 4, 1, { type: 'info', text: 'Закрутки: огірки, помідори, лечо, компот і мамине вишневе варення' }, 'Стелаж із банками');
  m.zone('potatoes', 5, 6, 1, 3, { type: 'info', text: 'Засік із картоплею — до весни вистачить' }, 'Засік · картопля');
  m.zone('roots', 14, 6, 1, 3, { type: 'info', text: 'Засік із буряком і морквою, пересипаними піском' }, 'Засік · буряк, морква');
  m.spawn('door', 10, 9).spawn('default', 10, 9);
  cached = m.build();
  return cached;
}
