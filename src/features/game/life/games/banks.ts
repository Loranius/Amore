export function englishQuestion(rng: Rng, level: number): Question {
  const pool = ENGLISH.filter(([, , min]) => min <= Math.max(2, level));
  const [en, ua] = pickOne(rng, pool);
  const others = sample(rng, pool.filter(([e]) => e !== en).map(([, u]) => u), 3);
  const answers = shuffled(rng, [ua, ...others]);
  return { q: `«${en}» — це…`, answers, correct: answers.indexOf(ua) };
}

