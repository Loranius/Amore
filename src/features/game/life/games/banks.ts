export function factQuestion(rng: Rng, subject: keyof typeof FACTS, level: number): Question {
  const pool = FACTS[subject].filter((f) => f.minLevel <= level);
  const f = pickOne(rng, pool.length ? pool : FACTS[subject]);
  const answers = shuffled(rng, [f.right, ...f.wrong]);
  return { q: f.q, answers, correct: answers.indexOf(f.right) };
}

