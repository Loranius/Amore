export function sentenceTask(rng: Rng, level: number): { words: string[]; order: number[] } {
  const pool = SENTENCES.filter((s) => (level <= 2 ? s.length <= 4 : level <= 5 ? s.length <= 5 : true));
  const words = [...pickOne(rng, pool)];
  const order = shuffled(rng, words.map((_, i) => i));
  return { words, order };
}

