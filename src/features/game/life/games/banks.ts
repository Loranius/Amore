import { intIn, pickOne, sample, shuffled, type Rng } from '../sim/rng';

export interface Question {
  q: string;
  answers: string[];
  correct: number;
  /** Картинка-підказка (для малечі): скільки чого намалювати. */
  picture?: { icon: 'apple' | 'star' | 'heart' | 'ball'; count: number };
}

function choices(rng: Rng, right: number, spread: number, min = 0): { answers: string[]; correct: number } {
  const set = new Set<number>([right]);
  let guard = 0;
  while (set.size < 4 && guard < 50) {
    guard += 1;
    const d = intIn(rng, 1, Math.max(1, spread)) * (rng() < 0.5 ? -1 : 1);
    if (right + d >= min) set.add(right + d);
  }
  const list = shuffled(rng, [...set]);
  return { answers: list.map(String), correct: list.indexOf(right) };
}

/** Математика: формат і складність — за класом (1–11) або курсом (12–15). */
export function mathQuestion(rng: Rng, level: number): Question {
  const kind = rng();
  if (level <= 1) {
    if (kind < 0.35) {
      const n = intIn(rng, 2, 9);
      const icon = pickOne(rng, ['apple', 'star', 'heart', 'ball'] as const);
      return { q: 'Скільки на малюнку?', ...choices(rng, n, 2, 1), picture: { icon, count: n } };
    }
    const a = intIn(rng, 1, 9);
    const b = intIn(rng, 0, 10 - a);
    return kind < 0.7 ? { q: `${a} + ${b} = ?`, ...choices(rng, a + b, 2) } : { q: `${a + b} − ${b} = ?`, ...choices(rng, a, 2) };
  }
  if (level === 2) {
    if (kind < 0.3) {
      const a = intIn(rng, 10, 90);
      const b = intIn(rng, 10, 90);
      const answers = ['>', '<', '='];
      return { q: `${a} ? ${b}`, answers, correct: a > b ? 0 : a < b ? 1 : 2 };
    }
    const a = intIn(rng, 12, 60);
    const b = intIn(rng, 5, 35);
    return kind < 0.65 ? { q: `${a} + ${b} = ?`, ...choices(rng, a + b, 10) } : { q: `${a + b} − ${a} = ?`, ...choices(rng, b, 6) };
  }
  if (level <= 4) {
    if (kind < 0.45) { const a = intIn(rng, 2, 9); const b = intIn(rng, 2, 9); return { q: `${a} × ${b} = ?`, ...choices(rng, a * b, 6) }; }
    if (kind < 0.75) { const b = intIn(rng, 2, 9); const r = intIn(rng, 2, 9); return { q: `${b * r} ÷ ${b} = ?`, ...choices(rng, r, 3, 1) }; }
    const x = intIn(rng, 3, 30);
    const a = intIn(rng, 5, 40);
    return { q: `□ + ${a} = ${x + a}`, ...choices(rng, x, 5) };
  }
  if (level <= 6) {
    if (kind < 0.35) {
      const d = pickOne(rng, [2, 4, 5, 10]);
      const n = intIn(rng, 1, d - 1);
      const whole = d * intIn(rng, 2, 12);
      return { q: `${n}/${d} від ${whole} = ?`, ...choices(rng, (whole / d) * n, 5) };
    }
    if (kind < 0.65) { const a = intIn(rng, 12, 40); const b = intIn(rng, 11, 25); return { q: `${a} × ${b} = ?`, ...choices(rng, a * b, 30) }; }
    const p = intIn(rng, 2, 9);
    const speed = intIn(rng, 40, 90);
    return { q: `Потяг їде ${speed} км/год. Скільки км за ${p} год?`, ...choices(rng, speed * p, 40) };
  }
  if (level <= 9) {
    if (kind < 0.35) { const x = intIn(rng, -9, 15); const a = intIn(rng, 2, 7); const b = intIn(rng, -20, 20); return { q: `${a}x ${b < 0 ? '−' : '+'} ${Math.abs(b)} = ${a * x + b}. x = ?`, ...choices(rng, x, 4, -30) }; }
    if (kind < 0.65) { const base = intIn(rng, 2, 50) * 20; const pct = pickOne(rng, [5, 10, 15, 20, 25, 50]); return { q: `${pct}% від ${base} = ?`, ...choices(rng, (base * pct) / 100, 20) }; }
    const a = intIn(rng, 2, 15);
    return { q: `${a}² = ?`, ...choices(rng, a * a, 12) };
  }
  if (level <= 11) {
    if (kind < 0.35) { const a = intIn(rng, 2, 6); const n = intIn(rng, 2, 4); return { q: `${a}^${n} = ?`, ...choices(rng, a ** n, 10) }; }
    if (kind < 0.7) { const x1 = intIn(rng, -6, 6); const x2 = intIn(rng, -6, 6); return { q: `x² ${-(x1 + x2) < 0 ? '−' : '+'} ${Math.abs(x1 + x2)}x ${x1 * x2 < 0 ? '−' : '+'} ${Math.abs(x1 * x2)} = 0. Сума коренів?`, ...choices(rng, x1 + x2, 4, -20) }; }
    const n = intIn(rng, 1, 5);
    return { q: `log₁₀(${10 ** n}) = ?`, ...choices(rng, n, 2, 0) };
  }
  // ВДПУ: економіка в числах.
  if (kind < 0.35) { const price = intIn(rng, 2, 20) * 50; return { q: `Ціна без ПДВ ${price} ₴. З ПДВ 20%?`, ...choices(rng, price * 1.2, 60) }; }
  if (kind < 0.7) { const rev = intIn(rng, 20, 90) * 1000; const cost = intIn(rng, 10, rev / 1000 - 5) * 1000; return { q: `Виручка ${rev} ₴, витрати ${cost} ₴. Прибуток?`, ...choices(rng, rev - cost, 5000) }; }
  const xs = sample(rng, [4, 6, 7, 8, 9, 10, 12], 4);
  const sum = xs.reduce((a, b) => a + b, 0);
  const avg = Math.round(sum / xs.length);
  return { q: `Середнє з ${xs.join(', ')} (округлено)?`, ...choices(rng, avg, 2) };
}

