import { stableHash32 } from '@/engine/evolution/seed';

// ============================================================
// Геометрія картки спогаду: віяло знімків і пропорція кадру в альбомі.
// ------------------------------------------------------------
// Картка більше не полароїд. Власник дав референс, у якому спогад — це
// сам знімок із заокругленими кутами, а глибину дає ВІЯЛО решти фото,
// що визирає з-за нього. Біла рамка з підписом усередині пішла: вона
// з'їдала третину площі й перетворювала галерею на список карток замість
// галереї фотографій.
//
// Нахилу картки більше немає навмисно. Він існував, щоб сітка полароїдів
// не читалась насипаною; тепер життя дає віяло, а нахилений ПЛЮС віяло —
// це вже дві незалежні неточності на одній картці, і сітка розсипається.
//
// Чистий модуль без React і без CSS: кути перевіряються тестом, а не оком
// на знімку, де 7° від 9° не відрізнити.
// ============================================================

/** Дробове число 0…1 із цілого. Фіналізатор — щоб сусідні `id` не злипались. */
function unit(seed: string): number {
  let value = stableHash32(seed);
  value ^= value >>> 16;
  value = Math.imul(value, 0x21f0aaad) >>> 0;
  value ^= value >>> 15;
  value = Math.imul(value, 0x735a2d97) >>> 0;
  value ^= value >>> 15;
  return (value >>> 0) / 4294967296;
}

// ── Віяло ───────────────────────────────────────────────────

/**
 * Скільки знімків показує віяло, хай би скільки їх було в спогаді.
 *
 * Чотири — це два листи на бік, тобто симетрія референсу. П'ятий лист
 * лягає під уже намальовані й не додає жодного пікселя, зате коштує ще
 * одну картинку на КОЖНУ картку галереї: на архіві з 37 спогадів це
 * різниця в 37 завантажень нізащо.
 */
export const MAX_FAN_LEAVES = 4;

/**
 * Крок повороту між сусідніми листами, у градусах.
 *
 * Число не декоративне — воно впирається в сусідню картку. Лист
 * повертається навколо НИЖНЬОГО краю (50%, 100%), як карти в руці: низи
 * всіх листів сходяться в одну точку, а вбік вони розходяться тим
 * більше, чим вище. Верхній кут виїжджає на
 * `(0.5·cos θ + sin θ − 0.5)` ширини листа.
 *
 * При найбільшому куті 15° це 0.2418 ширини листа; лист — 0.68 клітинки
 * сітки й додатково стиснутий до 0.94, отже виліт = 0.1545 клітинки.
 * Поле, лишене під віяло з кожного боку (`--mm-fan-room` у CSS), — 16%.
 * Тобто 15° уміщається, а 16° уже наїхало б на сусідню картку.
 *
 * Дві попередні редакції не дотягували, і обидві помилки видно лише на
 * живому екрані:
 *
 *  - крок 4.5° і поле 10% дали виліт у 10 пікселів зі 148. Віяла не було
 *    видно взагалі — картка читалась як самотнє фото;
 *  - вісь на 88% висоти лишала листи схованими за головним кадром скрізь,
 *    крім верхніх кутів. У референсі листи видно збоку по всій висоті, і
 *    дає це саме нижня вісь, а не більший кут.
 */
export const FAN_STEP_DEG = 7.5;

export interface FanLeaf {
  /** Поворот у градусах: додатний — вправо, від'ємний — вліво. */
  rotate: number;
  /** Наскільки лист дрібніший за головний кадр (1 — такий самий). */
  scale: number;
}

/**
 * Розкладка віяла для заданої кількості ЗАЙВИХ знімків (без обкладинки).
 *
 * Порядок повернення — порядок МАЛЮВАННЯ: найдальший лист перший, щоб
 * наступні лягали поверх нього без жодного `z-index`. Списку в DOM
 * достатньо, і це на один шар складності менше.
 *
 * Боки чергуються (право, ліво, право, ліво), тому непарна кількість
 * листів дає асиметричне віяло — саме так виглядає й справжня стопка,
 * з якої витягли карту.
 */
export function fanLeaves(extraPhotos: number): FanLeaf[] {
  const count = Math.min(Math.max(0, Math.trunc(extraPhotos)), MAX_FAN_LEAVES);
  const inner: FanLeaf[] = [];
  for (let i = 0; i < count; i += 1) {
    const step = Math.floor(i / 2) + 1; // 1, 1, 2, 2 — пара листів на кожен щабель
    const side = i % 2 === 0 ? 1 : -1; // право, ліво, право, ліво
    inner.push({
      rotate: Number((side * step * FAN_STEP_DEG).toFixed(2)),
      scale: Number((1 - step * 0.03).toFixed(3)),
    });
  }
  // Зібрано зсередини назовні — малювати треба навпаки.
  return inner.reverse();
}

// ── Альбом на сторінці спогаду ──────────────────────────────

/**
 * Пропорції кадру в альбомі спогаду.
 *
 * Три форми, а не одна: бриф просить «різні пропорції фото». Однакові
 * квадрати дають каталог товарів, а не альбом.
 *
 * Значення — це `aspect-ratio`, тобто ширина поділена на висоту. Кадр
 * обрізається по `object-fit: cover`; так само працює будь-який полароїд —
 * рамка має свій формат, і знімок у неї вкладають, а не навпаки.
 */
const ALBUM_SHAPES = [0.78, 1, 1.34] as const;

export function photoAspect(id: number): number {
  return ALBUM_SHAPES[Math.floor(unit(`shape:${id}`) * ALBUM_SHAPES.length)] ?? 1;
}

/**
 * Розкладка альбому в дві колонки.
 *
 * Не `column-count` і не masonry: обидва розкладають ПО ВЕРТИКАЛІ, тобто
 * перше фото опиняється над другим, а не поруч із ним — і хронологія, яку
 * пара щойно склала руками, читається зигзагом.
 *
 * Тому колонки набираються тут, і набираються ЖАДІБНО: наступний кадр іде в
 * ту колонку, яка зараз коротша. Висота кадру відома наперед (це обернена
 * пропорція), тож перебирати нічого не треба.
 */
export function albumColumns<T extends { id: number }>(
  photos: readonly T[],
  columns = 2,
): T[][] {
  const lanes: T[][] = Array.from({ length: Math.max(1, columns) }, () => []);
  const heights = new Array<number>(lanes.length).fill(0);

  for (const photo of photos) {
    let shortest = 0;
    for (let lane = 1; lane < heights.length; lane += 1) {
      if (heights[lane]! < heights[shortest]!) shortest = lane;
    }
    lanes[shortest]!.push(photo);
    // Висота при однаковій ширині — це 1 / (ширина ÷ висота).
    heights[shortest] = heights[shortest]! + 1 / photoAspect(photo.id);
  }

  return lanes;
}
