// ============================================================
// Чиста геометрія карти спогадів: куди дивитись і що показувати.
// ------------------------------------------------------------
// Ні MapLibre, ні React тут немає навмисно. Усе, що нижче, — це
// відповідь на питання «яка ділянка світу зараз має бути в кадрі», і
// відповідь ця має бути передбачуваною: карта, яка щоразу відкривається
// в іншому місці, читається як зламана, а не як жива.
//
// Найтонше місце — ОДНА точка. Межі з однієї точки вироджені (ширина й
// висота нуль), і будь-яка бібліотека карт на таких межах дає або
// нескінченне наближення, або NaN у масштабі. Тому одна точка не
// перетворюється на межі взагалі: для неї є окремий шлях.
// ============================================================

export interface GeoPoint {
  lat: number;
  lng: number;
}

/** Прямокутник у порядку, якого чекає MapLibre: [[захід, південь], [схід, північ]]. */
export type GeoBounds = [[number, number], [number, number]];

/**
 * Куди дивиться карта, коли в пари ще немає жодного місця.
 *
 * Центр Європи й малий масштаб: пара побачить материк, а не сіру пляму
 * океану, і зрозуміє, що карту треба посунути, а не що вона зламалась.
 */
export const WORLD_VIEW = { lng: 20, lat: 48, zoom: 3 } as const;

/**
 * Масштаб, на якому показують ОДНЕ місце.
 *
 * 14 — це квартал: видно вулицю, на якій стоїть мітка, і сусідні. На 16
 * вже не видно, у якій частині міста ти опинився; на 11 мітка губиться
 * серед районів.
 */
export const SINGLE_PLACE_ZOOM = 14;

/**
 * Масштаб, на який ідемо за геолокацією.
 *
 * Дрібніший за `SINGLE_PLACE_ZOOM`: коли пара просить «де я», їй треба
 * впізнати район, а не роздивитись будинок.
 */
export const MY_LOCATION_ZOOM = 13;

/**
 * Скільки пікселів лишити між крайньою міткою й краєм екрана.
 *
 * Мітка — не крапка: це кружечок близько 44 px, який росте вгору від
 * своєї координати. Без відступу верхня мітка наполовину виїжджає за
 * край, і виглядає це як загублена.
 */
export const FIT_PADDING_PX = 64;

/**
 * Межі, що вміщають усі точки, або `null`.
 *
 * `null` повертається у двох випадках, і обидва означають «межами тут не
 * обійтись»:
 *
 *  - точок немає взагалі;
 *  - точка одна, тобто прямокутник вироджений. Карта на таких межах дає
 *    нескінченне наближення; для одного місця є `SINGLE_PLACE_ZOOM`.
 *
 * Точки з нечисловими координатами відкидаються мовчки: одна така
 * розтягнула б межі на весь глобус, і решта міток стала б непомітною.
 */
export function boundsOf(points: readonly GeoPoint[]): GeoBounds | null {
  const clean = points.filter(
    (p) =>
      Number.isFinite(p.lat) && Number.isFinite(p.lng) &&
      Math.abs(p.lat) <= 90 && Math.abs(p.lng) <= 180,
  );
  if (clean.length < 2) return null;

  let west = clean[0]!.lng;
  let east = clean[0]!.lng;
  let south = clean[0]!.lat;
  let north = clean[0]!.lat;
  for (const p of clean) {
    if (p.lng < west) west = p.lng;
    if (p.lng > east) east = p.lng;
    if (p.lat < south) south = p.lat;
    if (p.lat > north) north = p.lat;
  }

  // Усі точки в одному місці (та сама кав'ярня кілька разів) дають ту саму
  // вироджену рамку, що й одна точка.
  if (west === east && south === north) return null;
  return [[west, south], [east, north]];
}

/** Що робити з картою одразу після відкриття. */
export type OpeningView =
  | { kind: 'fit'; bounds: GeoBounds }
  | { kind: 'point'; lng: number; lat: number; zoom: number };

/**
 * Початковий вигляд за наявними місцями.
 *
 * Порядок навмисний: спершу вмістити все, що пара вже назбирала, потім —
 * єдине місце, і лише за відсутності обох — світ. Тобто карта відкривається
 * там, де пара була, а не там, де нуль широти й нуль довготи.
 */
export function openingView(points: readonly GeoPoint[]): OpeningView {
  const bounds = boundsOf(points);
  if (bounds) return { kind: 'fit', bounds };

  const only = points.find(
    (p) => Number.isFinite(p.lat) && Number.isFinite(p.lng),
  );
  if (only) return { kind: 'point', lng: only.lng, lat: only.lat, zoom: SINGLE_PLACE_ZOOM };

  return { kind: 'point', lng: WORLD_VIEW.lng, lat: WORLD_VIEW.lat, zoom: WORLD_VIEW.zoom };
}
