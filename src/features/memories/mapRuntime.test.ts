import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

// ============================================================
// Дві умови, без яких карта не малює НІЧОГО.
// ------------------------------------------------------------
// Обидві знайдені на живому екрані й обидві мовчазні: жодної помилки в
// консолі, стиль і TileJSON по 200, контейнер правильних 412×915 — і
// нескінченне «Завантажую карту…». Саме тому вони стоять тут: помилка,
// яку не видно, мусить падати в тестах.
//
//  1. **Адреса воркера.** MapLibre шукає його рядком, який складається під
//     час виконання: `new URL('./maplibre-gl-worker.mjs', import.meta.url)`.
//     Збирач такого не бачить, файл не потрапляє у збірку, запит дає 404,
//     воркер помирає одразу — а векторні тайли вантажить саме він. Замір:
//     без явної адреси нуль запитів на `.pbf` за 70 секунд, з нею —
//     тринадцять тайлів за п'ять.
//
//  2. **Формат воркера.** MapLibre створює його через
//     `new Worker(url, { type: 'module' })`. За типовим для збирача
//     `format: 'iife'` браузер не розібрав би класичний скрипт як модуль,
//     і карта лишилась би без тайлів рівно так само.
// ============================================================

const read = (path: string) => readFileSync(join(__dirname, path), 'utf8');
const MAP = read('MemoriesMap.tsx');
const VITE = read('../../../vite.config.ts');

describe('карта спогадів: що потрібно її воркеру', () => {
  it('адреса воркера приходить від збирача, а не складається в рантаймі', () => {
    expect(MAP).toMatch(
      /import maplibreWorkerUrl from 'maplibre-gl\/dist\/maplibre-gl-worker\.mjs\?worker&url'/,
    );
    expect(MAP).toMatch(/setWorkerUrl\(maplibreWorkerUrl\)/);
  });

  it('воркери збираються як ES-модулі', () => {
    expect(VITE).toMatch(/worker:\s*\{\s*format:\s*'es'\s*\}/);
  });
});
