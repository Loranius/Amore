// ============================================================
// Кадр стає спогадом (ADR-0253).
// ------------------------------------------------------------
// Відкриваючи спогад, пара торкається кадру на нитці — і саме цей кадр
// виростає в обкладинку на всю ширину, а не зникає разом зі сторінкою.
// Нитка й спогад — одна річ у двох масштабах, і рух це каже.
//
// Механіка — View Transitions: браузер знімає старий кадр і нову
// обкладинку, що мають однакове `view-transition-name`, і перетягує одне в
// друге. Ім'я дістає ЛИШЕ кадр, якого торкнулись, і лише в мить дотику:
// десятки імен на нитці — це десятки знімків на кожен перехід, а два
// однакові імена браузер вважає помилкою й скасовує перехід цілком.
// Обкладинка носить ім'я завжди (`.mm-hero-shot` у CSS).
//
// Браузер без View Transitions просто відкриває спогад — як і раніше.
// ============================================================

export const COVER_MORPH = 'mm-cover';

/**
 * Позначити кадр, що зараз стане обкладинкою.
 *
 * Обкладинка поточної сторінки (коли гортають сусідів) на цей перехід
 * ім'я віддає: інакше в старому знімку їх було б два.
 */
export function markCoverMorphSource(source: Element | null): void {
  if (typeof document === 'undefined') return;
  document.querySelectorAll<HTMLElement>('.mm-hero-shot').forEach((hero) => {
    hero.style.setProperty('view-transition-name', 'none');
  });
  if (source instanceof HTMLElement) source.style.setProperty('view-transition-name', COVER_MORPH);
}
