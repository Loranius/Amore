// ============================================================
// Чому впала сцена — і чому це не одне й те саме питання.
// ------------------------------------------------------------
// Межа падінь ловила будь-яку помилку сцени й показувала одну заглушку:
// «WebGL недоступний. Браузер не дав полотно для тривимірної сцени».
//
// Власник надіслав саме цей екран. У консолі при цьому стояло інше:
//
//   Could not load /models/amore_ruin.glb: fetch … responded with 404
//
// WebGL працював. Не доїхав файл. Пара прочитала повідомлення про
// причину, якої не було, — а перший розбір того знімка пішов шукати
// стелю WebGL-контекстів і витратив на це окрему сесію.
//
// Заглушка має право бути неточною в деталях, але не має права називати
// НЕ ТУ причину: з «браузер не дав полотно» нічого не зробиш, а з «файл
// не доїхав» — оновити сторінку.
// ============================================================

/** Що саме не вдалось. Читає заглушка, щоб не вигадувати причину. */
export type SceneFailureReason = 'asset' | 'scene';

/**
 * Чиста функція від помилки — жодного `window`, тож перевіряється без DOM.
 *
 * Розпізнається САМЕ завантаження ресурсу, а решта лишається загальним
 * «сцена не піднялась». Помилятись у цей бік безпечно: незнайома помилка
 * дістане обережніше формулювання, а не впевнене й хибне.
 */
export function sceneFailureReason(error: unknown): SceneFailureReason {
  const message = error instanceof Error ? error.message : String(error ?? '');
  // `useGLTF`/three кидають «Could not load <url>: fetch for "…" responded
  // with 404»; мережа без відповіді дає «Failed to fetch».
  if (/could not load|failed to fetch|responded with \d{3}|networkerror/i.test(message)) {
    return 'asset';
  }
  return 'scene';
}
