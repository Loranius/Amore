import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';

// ============================================================
// Полотно модуля не малює кадрів під чужим повним екраном.
// ------------------------------------------------------------
// `CrystalScene` і `ReefPreviewScene` поважали `useWorldFrameloop` від
// самого початку, ці два — ні, і це був недогляд, а не рішення. Ціна
// виміряна на живому екрані: коли поверх модуля відкривалась карта
// спогадів, телефон малював дві сцени, з яких одна повністю схована. На
// слабкому GPU головний потік не відповідав жодного разу за 50 секунд і
// карта не встигала попросити ні одного тайла; з паузою вона готова за
// п'ять секунд.
//
// Тест дивиться в текст файлів навмисно: підняти обидві сцени в jsdom
// означає підняти WebGL, якого там немає.
//
// СТЕРЕЖЕТЬСЯ ФАЙЛ ІЗ ПОЛОТНОМ, А НЕ ФАЙЛ ІЗ НАЗВОЮ СЦЕНИ. Дерево свій
// `<Canvas>` переїхало: `EvolutionTreePreviewScene` тягнув за собою Supabase
// (через `useTreeLabPortalPreview`), тож сцену світу винесено в `TreeInWorld`,
// щоб лабораторія могла показати ТЕ САМЕ дерево без бекенда. Інваріант від
// цього не змінився — його адреса змінилась, і список нижче йде за нею.
// ============================================================

const read = (name: string) => readFileSync(join(__dirname, name), 'utf8');

describe('превʼю еволюції: кадри лише коли видно', () => {
  for (const name of ['EvolutionCrystalPreviewScene.tsx', 'TreeInWorld.tsx']) {
    it(`${name} питає про паузу і віддає її полотну`, () => {
      const source = read(name);
      expect(source).toMatch(/const frameloop = useWorldFrameloop\(\)/);
      expect(source).toMatch(/frameloop=\{frameloop\}/);
    });

    it(`${name} кличе гак до будь-якого раннього виходу`, () => {
      /*
       * Регрес, який уже стався. Гак поставили поруч із `<Canvas>` — там,
       * куди його тягне читабельність, — а вище лишились два ранні виходи:
       * заглушка, поки рахується конвеєр, і запасний рендерер при помилці.
       * Тобто на частині рендерів гак не викликався зовсім.
       *
       * React це ловить («Rendered more hooks than during the previous
       * render»), але наслідок на екрані не схожий на помилку: сцена тихо
       * падає в запасний рендерер, і кристал просто виглядає простішим.
       * Знайшов живий екран, не тести — тому перевірка тут.
       */
      const source = read(name);
      const hook = source.indexOf('const frameloop = useWorldFrameloop()');
      expect(hook).toBeGreaterThan(-1);

      // Дивимось лише тіло того компонента, що кличе гак. У файлі є ще й
      // допоміжні функції верхнього рівня (`formatTopology`), і їхні
      // `return` до гака стосунку не мають — тому шукаємо саме компонент,
      // тобто функцію з великої літери.
      const starts = [
        ...source.slice(0, hook).matchAll(/^(?:export )?(?:default )?function [A-Z]\w*/gm),
      ];
      const body = source.slice(starts.at(-1)!.index!, hook);

      // Ранній вихід — `return` з відступом рівно два пробіли, тобто на
      // верхньому рівні тіла компонента. Вкладені `return` усередині
      // колбеків мають більший відступ і гака не стосуються.
      expect(body).not.toMatch(/\n {2}(?:if \([^)]*\) )?return[ (<;]/);
    });
  }
});
