import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const HOOK = readFileSync(
  fileURLToPath(new URL('./useWebglSupport.ts', import.meta.url)),
  'utf8',
);
const FALLBACK = readFileSync(
  fileURLToPath(new URL('../HomeArtifactPreviewFallback.tsx', import.meta.url)),
  'utf8',
);
/** Без коментарів: вони цитують саме ту ваду, що перевіряється. */
const bare = (source: string) =>
  source.replace(/\/\*[\s\S]*?\*\//g, (block) => block.replace(/[^\n]/g, ' '))
    .replace(/^\s*\/\/.*$/gm, '');

const CODE = bare(HOOK);
const VIEW = bare(FALLBACK);

// ============================================================
// Кристал, якого не видно на справжньому телефоні.
// ------------------------------------------------------------
// Власник відкрив портал і побачив «WebGL недоступний». Обставини на
// знімку: 53 вкладки й 12% заряду — тобто браузер стояв на своїй стелі
// живих WebGL-контекстів.
//
// Пісочниця такого не показує НІКОЛИ: у неї одна вкладка й програмний
// растеризатор, який не має стелі контекстів. Тобто це та вада, яку
// живий екран цього проєкту впіймати не може за побудовою, і стерегти
// її може лише читання коду.
// ============================================================

describe('проба WebGL не з’їдає слот, який сама ж перевіряє', () => {
  it('звільняє контекст одразу після відповіді', () => {
    /*
     * Проба створювала `webgl2`-контекст і кидала полотно збирачеві
     * сміття — контекст лишався живим до GC й займав один зі скупих
     * слотів браузера. На пристрої, який уже на стелі, проба САМА могла
     * стати краплею, через яку сцені слота не лишалось.
     */
    expect(CODE).toContain('WEBGL_lose_context');
    expect(CODE).toMatch(/loseContext\?\.\(\)|loseContext\(\)/);
  });

  it('питає контекст рівно один раз на пробу', () => {
    // Два виклики `getContext` підряд на одному полотні поверталися б
    // тим самим контекстом, але саме тут легко випадково створити
    // другий на новому полотні й не звільнити його.
    expect(CODE.match(/createElement\('canvas'\)/g) ?? []).toHaveLength(1);
  });
});

describe('відмова не є вироком назавжди', () => {
  it('портал пробує знову, коли вкладка повертається на очі', () => {
    /*
     * `useState(detectWebgl)` рахує один раз за монтування. Пара, у якої
     * проба не вдалась через тимчасову обставину, бачила заглушку до
     * перезавантаження сторінки — навіть коли обставина вже минула.
     */
    expect(CODE).toContain("addEventListener('visibilitychange'");
    expect(CODE).toContain("addEventListener('focus'");
    expect(CODE, 'слухачі мають зніматись').toContain('removeEventListener');
  });

  it('не перепитує, поки контекст уже є', () => {
    // Повторна проба при живій сцені коштувала б ще одного слота на
    // кожне повернення на вкладку — тобто лікувала б хворобу її ж
    // збудником.
    expect(CODE).toMatch(/if \(supported\) return;/);
  });

  it('віддає назовні спосіб спробувати руками', () => {
    expect(CODE).toContain('retry');
    expect(CODE).toContain('export interface WebglSupport');
  });
});

describe('заглушка каже парі, що сталось і що робити', () => {
  it('не звинувачує пристрій', () => {
    /*
     * Було: «На цьому пристрої браузер не надав 3D-контекст для
     * актуального renderer». Це неправда двічі — причина здебільшого
     * тимчасова, а речення нічого не пропонує зробити.
     */
    expect(VIEW).not.toContain('На цьому пристрої');
    expect(VIEW, 'слово renderer парі нічого не каже').not.toContain('renderer');
  });

  it('називає обидві справжні причини', () => {
    expect(VIEW).toContain('вкладки');
    expect(VIEW).toContain('економі');
  });

  it('має кнопку повтору', () => {
    expect(VIEW).toContain('onRetry');
    expect(VIEW).toContain('Спробувати ще раз');
  });
});
