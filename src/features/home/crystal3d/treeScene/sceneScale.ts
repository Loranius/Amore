// ============================================================
// МЕТР У СЦЕНІ ДЕРЕВА — одна стала, від якої йдуть усі розміри лугу.
// ------------------------------------------------------------
// ЗАПИТ ВЛАСНИКА: «фонова сцена дерева виглядає занадто великою у
// порівнянні з деревом».
//
// Причина виміряна, і вона одна на весь луг: **дерево і те, що навколо
// нього, міряні різними метрами.**
//
// Дерево масштабується законом (`treeFit.ts`): доросле на повному терміні
// дає рівно `TREE_FIT_HEIGHT` одиниць сцени, а молоде — стільки, скільки
// заслужило роками. Виміряно на конвеєрі, профіль «середня»:
//
//   роки     0    1     2     3.7    8     12    20    40
//   висота  0.23  0.49  0.78  1.10   1.80  2.24  2.69  2.70
//
// А трава, каміння, квіти, листовий опад і метелики стояли СТАЛИМИ
// розмірами, підібраними на око під доросле дерево, і в тих розмірах
// одиниця сцени мовчки означала приблизно метр. Двох метрів одразу бути
// не може, і ось що з цього виходило на реальному віці пари (3.7 року,
// дерево 1.10 одиниці):
//
//   камінь        0.70 одиниці заввишки — 64% висоти ДЕРЕВА
//   жмуток трави  0.35 — 32% висоти дерева
//   сухий листок  0.19 завдовжки — з чверть крони завширшки
//   квітка        голівка ⌀0.094 — більша за листок дерева
//   тінь крони    підлога 1.9, тобто пляма 3.8 під кроною 0.89 завширшки
//
// Тобто на знімку стояв не малий сад, а **велетенський луг із сіянцем
// посередині**. Власник назвав це точно.
//
// Тут метр дістає адресу. Anchor рівно один і він названий: доросле дерево
// на повному терміні — дванадцять метрів. Усе інше на лузі описується в
// метрах через `metres()`, і жодне число сцени більше не має права бути
// «підібраним на око проти дорослого дерева».
//
// ЧОМУ ПРЕДМЕТИ НЕ РОСТУТЬ РАЗОМ ІЗ ДЕРЕВОМ. Спокуса зробити траву
// часткою висоти дерева велика — вона одразу прибирає скаргу на всіх
// віках. Але саме тоді зникає ріст: якщо трава завжди по коліно дереву,
// дерево ніколи не переростає траву, і роки стають невидимі. Трава має
// лишатись травою, а дерево — проходити повз неї вгору. Це та сама догма
// `PRODUCT.md` §6, лише з іншого боку.
// ============================================================
import { TREE_FIT_HEIGHT } from '@/engine/renderer/three';

/**
 * Висота дорослого дерева в метрах — ЄДИНЕ метричне твердження сцени.
 *
 * Дванадцять, а не двадцять і не шість: рід дерева тут не названий, і
 * дванадцять метрів на сороковому році — це і не дуб-велетень, і не
 * яблуня. Змінити масштаб усього лугу — це змінити одне це число.
 */
export const TREE_MATURE_HEIGHT_METRES = 12;

/** Скільки одиниць сцени в одному метрі. */
export const TREE_SCENE_UNITS_PER_METRE = TREE_FIT_HEIGHT / TREE_MATURE_HEIGHT_METRES;

/**
 * Метри в одиниці сцени.
 *
 * Пишеться в кожному розмірі лугу навмисно: `metres(0.35)` читається як
 * «трава по коліно», а 0.079 не читається ніяк, і саме через це попередні
 * числа й розійшлись із деревом.
 */
export function metres(value: number): number {
  return value * TREE_SCENE_UNITS_PER_METRE;
}
