import { describe, expect, it } from 'vitest';
import { rockGrainAt } from './rockGrainTexture';

/*
 * Зерно каменю печери. Полотно — ресурс браузера, і його тут немає; але
 * САМА функція зерна чиста, і перевіряється саме вона.
 *
 * Навіщо воно є: виміряно, що до нього стіна вкладалась у 39–61 з 255, а
 * підлога — у 18–28. Розкид граней там був, але на рівні 18 дев'ять
 * відсотків це півтора рівня, тобто нижче за поріг видимості. Камінь
 * читався аркушем не через брак граней, а через брак деталі, дрібнішої
 * за грань.
 */
describe('зерно каменю печери', () => {
  it('замикається по обох осях — інакше на стіні буде шов', () => {
    /*
     * Стіна намотана на повне коло, тож права межа розгортки лягає на
     * ліву. Ґратка шуму береться по модулю саме заради цього; без того
     * на кожному повороті стояла б вертикальна смуга.
     */
    for (let step = 0; step <= 16; step += 1) {
      const t = step / 16;
      expect(rockGrainAt(0, t), `v=${t}`).toBeCloseTo(rockGrainAt(1, t), 10);
      expect(rockGrainAt(t, 0), `u=${t}`).toBeCloseTo(rockGrainAt(t, 1), 10);
    }
  });

  it('тримається оголошеної смуги 0.62–1', () => {
    // Карта може лише ЗАТЕМНЮВАТИ: текстура не буває яскравіша за
    // одиницю. Вихід за смугу означав би, що палітру компенсовано не на
    // ту ціну.
    for (let y = 0; y < 32; y += 1) {
      for (let x = 0; x < 32; x += 1) {
        const value = rockGrainAt(x / 32, y / 32);
        expect(value).toBeGreaterThanOrEqual(0.62);
        expect(value).toBeLessThanOrEqual(1);
      }
    }
  });

  it('має справжній розкид, а не рівний сірий', () => {
    /*
     * Найважливіше тут. Зерно, що коливається на кілька відсотків, коштує
     * пам'яті й вибірки й не дає нічого — а виглядає в коді точно так
     * само, як робоче.
     */
    let low = 1;
    let high = 0;
    let sum = 0;
    let count = 0;
    for (let y = 0; y < 64; y += 1) {
      for (let x = 0; x < 64; x += 1) {
        const value = rockGrainAt(x / 64, y / 64);
        low = Math.min(low, value);
        high = Math.max(high, value);
        sum += value;
        count += 1;
      }
    }
    expect(high - low).toBeGreaterThan(0.2);
    // Середнє тримається біля 0.81: саме на цю ціну піднято палітру
    // каменю, і зсув середнього означав би, що печера потемніла або
    // висвітлилась мовчки.
    expect(sum / count).toBeGreaterThan(0.74);
    expect(sum / count).toBeLessThan(0.88);
  });

  it('детермінований: та сама точка дає те саме число', () => {
    expect(rockGrainAt(0.37, 0.61)).toBe(rockGrainAt(0.37, 0.61));
  });
});
