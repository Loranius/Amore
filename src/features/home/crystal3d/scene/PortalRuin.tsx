// ============================================================
// Сцена кристала — руїна замість процедурного храму.
// ------------------------------------------------------------
// ЩО ЦЕ ЗАМІНЮЄ. Храм будувався кодом: `portalPlatformMesh.ts`,
// `portalColonnadeMesh.ts`, `portalRelicPedestal.ts`, `portalSceneDecor.ts`
// плюс процедурні текстури — разом близько двох тисяч рядків, які
// описували підлогу, вісімнадцять колон, арки, полотнища, лози, чотири
// світильники й релікварій. Кожен із них колись довелось налаштовувати
// окремо, і кожен мав власні числа.
//
// Власник обрав інший шлях: одна авторська руїна замість зібраного з
// частин храму. Це не оптимізація — це зміна того, ДЕ стоїть кристал.
//
// ЧОМУ ЯКІР — ВЕРХ ПІДСТАВКИ, А НЕ ПІДЛОГА. У руїни є власна геометрія
// п'єдесталу, і кристал мусить рости саме з неї, а не висіти над нею.
// Тому асет позиціюється так, щоб верхня площина `Stand` лягла точно на
// `PORTAL_GROUND_Y` — ту саму площину, на якій стоять усі кристали
// сьогодні. Жоден інший файл про заміну сцени не дізнається.
//
// ВИМІРЯНО НА САМОМУ АСЕТІ (не «на око» — розібраний GLB):
//
//   світові межі      2.72 × 3.06 × 2.71
//   верх `Stand`      Y = 1.224, і це найвища точка підставки
//   радіус тієї площини 0.158 … 0.376
//   колони            від Y 0.2 до 1.402, і В РАДІУСІ 0.35 ВІД ОСІ ЇХ НЕМАЄ
//
// Останній рядок — причина, чому центр вільний: кристал росте по осі й
// не перетинається з колонадою, хай як високо він виросте.
// ============================================================
import { useLayoutEffect, useMemo, useRef } from 'react';
import { useGLTF } from '@react-three/drei';
import * as THREE from 'three';
import { PORTAL_GROUND_Y } from './portalScene';

export const RUIN_MODEL_URL = '/models/amore_ruin.glb';

/** Верхня площина п'єдесталу у власних одиницях асета. Виміряно. */
export const RUIN_PEDESTAL_TOP_Y = 1.224;
/** Радіус тієї площини. Кристалу є де стояти рівно до цього числа. */
export const RUIN_PEDESTAL_TOP_RADIUS = 0.376;

/**
 * Руїна — це МІСЦЕ, і місце не змінює розміру під те, що в ньому стоїть.
 * ------------------------------------------------------------
 * Перша редакція масштабувала камінь під радіус друзи — тим самим
 * правилом, що знятий `portalDaisScale`. На знімку це дало кадр, у якому
 * від руїни лишились дві кам'яні плити по краях екрана, а п'єдестал під
 * кристалом зник зовсім.
 *
 * Причина — у пропорціях самого асета, і вона виміряна: верх п'єдесталу
 * стоїть на Y=1.224, а колони закінчуються на 1.402. Тобто над площиною,
 * де росте кристал, колонада підіймається лише на **0.178** — решта
 * руїни лежить НИЖЧЕ. Розтягни її втричі, щоб умістити широку друзу, — і
 * єдине, що лишиться в кадрі, це підніжжя колон.
 *
 * Тому масштаб сталий. Наслідок названий прямо: підганяти під місце
 * тепер мусить КРИСТАЛ, а не навпаки — і це те саме, чого просив
 * власник, кажучи «кристал росте по центру, з жеоди».
 */
const RUIN_SCALE = 1;

export function portalRuinScale(): number {
  return RUIN_SCALE;
}

/** Радіус площини, у яку кристал мусить вміститись разом із дітьми. */
export const RUIN_CRYSTAL_FOOTPRINT = RUIN_PEDESTAL_TOP_RADIUS * RUIN_SCALE;

/** Висота, на яку треба опустити асет, щоб верх підставки сів на базову площину. */
export function portalRuinOffsetY(scale: number): number {
  return PORTAL_GROUND_Y - RUIN_PEDESTAL_TOP_Y * scale;
}

export interface PortalRuinProps {
  /** Тепло каменю різниться між ніччю й полуднем, композиція — ні. */
  theme: 'light' | 'dark';
  quality: 'high' | 'balanced' | 'low' | 'fallback';
}

export function PortalRuin({ theme, quality }: PortalRuinProps) {
  const { scene } = useGLTF(RUIN_MODEL_URL);
  const group = useRef<THREE.Group>(null);

  const scale = RUIN_SCALE;
  const offsetY = useMemo(() => portalRuinOffsetY(scale), [scale]);

  /*
   * Копія графа, а не сам `scene`.
   *
   * `useGLTF` кешує розібраний файл на весь застосунок, і мутація його
   * матеріалів дісталась би кожного, хто завантажить той самий URL. У
   * цьому проєкті таких споживачів поки один, але ціна помилки —
   * матеріал, який змінюється «сам собою» при переході між маршрутами,
   * а знайти таке потім майже неможливо.
   */
  const model = useMemo(() => scene.clone(true), [scene]);

  useLayoutEffect(() => {
    const cheap = quality === 'low' || quality === 'fallback';
    model.traverse((object) => {
      if (!(object instanceof THREE.Mesh)) return;
      // Камінь відкидає тінь тільки там, де тіні взагалі рахуються.
      object.castShadow = false;
      object.receiveShadow = false;
      const material = object.material;
      if (!(material instanceof THREE.MeshStandardMaterial)) return;
      /*
       * Ніч і полудень різняться ТЕПЛОМ каменю, а не його кольором.
       * Перефарбувати камінь означало б зробити з нього два різні
       * матеріали; тут змінюється лише те, скільки світла він тримає.
       */
      material.envMapIntensity = theme === 'light' ? 1 : 0.62;
      /*
       * Карта нормалей — перше, що вимикається на слабкому профілі:
       * вона коштує вибірки в кожному фрагменті, а на руїні, яку видно
       * загальним планом, її внесок найменший із трьох карт.
       */
      if (cheap && material.normalMap) {
        material.normalMap = null;
        material.needsUpdate = true;
      }
    });
  }, [model, theme, quality]);

  return (
    <group ref={group} position={[0, offsetY, 0]} scale={scale}>
      <primitive object={model} />
    </group>
  );
}

useGLTF.preload(RUIN_MODEL_URL);
