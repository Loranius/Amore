// ============================================================
// Як виглядає фото бажання всередині кристала.
// ------------------------------------------------------------
// Власник описав ваду точно: фотографії в маленьких кристалах занадто
// контрастні й чужорідні, «наче вставлена картинка», і тягнуть увагу на себе
// поперед самого каменю. Ієрархія має бути зворотною — монарх, потім кристали
// бажань, і аж потім те, що в них усередині.
//
// Тому прев'ю в сцені проходить стилізацію: менша насиченість, стиснутий
// контраст, тонування в палітру світу й часткова прозорість. Різкість не
// втрачена — вона перенесена туди, де на неї справді дивляться: у картку
// бажання, і частково в сам кристал, коли його відкривають (§30).
//
// Числа живуть тут, а не в тексті шейдера, бо шейдер їх лише підставляє: одне
// джерело правди, яке можна перевірити тестом, і яке не можна випадково
// перевернути.
// ============================================================

export interface WishPreviewStyle {
  /** 0 — сірий тон, 1 — колір оригіналу. */
  saturation: number;
  /** 0 — рівна заливка середнього тону, 1 — контраст оригіналу. */
  contrast: number;
  /** Наскільки прев'ю перекриває камінь: 1 — повністю. */
  opacity: number;
  /** Наскільки прев'ю зводиться в колір світу. */
  tint: number;
}

/** Спокій: бажання просто висить у сцені. */
export const WISH_PREVIEW_CALM: WishPreviewStyle = {
  saturation: 0.55,
  contrast: 0.88,
  opacity: 0.86,
  tint: 0.4,
};

/**
 * Відкрите бажання — «зображення може ставати трохи чіткішим».
 *
 * «Трохи» лишається трохи: навіть тут прев'ю не доходить до сирого фото, бо
 * повне фото пара бачить у картці, а не крізь камінь.
 */
export const WISH_PREVIEW_CLEAR: WishPreviewStyle = {
  saturation: 0.92,
  contrast: 0.96,
  opacity: 0.94,
  tint: 0.14,
};

/**
 * Точна на кінцях форма інтерполяції.
 *
 * `from + (to - from) * amount` при amount = 1 дає 0.9000000000000001 замість
 * 0.9 — на екрані байдуже, але тоді «повністю відкрите» перестає дорівнювати
 * опублікованій сталій, і це вже не байдуже.
 */
function mix(from: number, to: number, amount: number): number {
  return from * (1 - amount) + to * amount;
}

/**
 * Стан прев'ю на шляху від спокою до відкритого бажання.
 *
 * Той самий рух фокуса, що виводить тіло вперед і збільшує його (§30), веде й
 * це — одна величина на всі вияви, тож розійтись вони не можуть.
 */
export function wishPreviewStyle(focus: number): WishPreviewStyle {
  const amount = Number.isFinite(focus) ? Math.min(1, Math.max(0, focus)) : 0;
  return {
    saturation: mix(WISH_PREVIEW_CALM.saturation, WISH_PREVIEW_CLEAR.saturation, amount),
    contrast: mix(WISH_PREVIEW_CALM.contrast, WISH_PREVIEW_CLEAR.contrast, amount),
    opacity: mix(WISH_PREVIEW_CALM.opacity, WISH_PREVIEW_CLEAR.opacity, amount),
    tint: mix(WISH_PREVIEW_CALM.tint, WISH_PREVIEW_CLEAR.tint, amount),
  };
}
