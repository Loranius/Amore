// ============================================================
// portalGlowBillboard — вершини, повернуті до ока (ADR-0170).
// ------------------------------------------------------------
// НАВІЩО. Світіння навколо артефакта мусить читатись з будь-якого боку:
// пара крутить острів пальцем, і плаский чотирикутник у світових
// координатах показав би ребро — тобто зник би саме тоді, коли на нього
// дивляться збоку.
//
// Розвернути його можна двома способами: щокадру писати матрицю групи з
// боку JavaScript або зсунути вершину у вершинному шейдері. Другий тут
// строго кращий, і не лише швидкістю: диски світіння лежать В ОДНОМУ
// МЕШІ з кільцем, бо в них те саме додавальне змішування, а кільце
// повертати до ока НЕ МОЖНА — воно кільце, а не наліпка. Матриця групи одна
// на весь меш; атрибут — свій на кожну вершину.
//
// ЩО САМЕ РОБИТЬ ШЕЙДЕР. `portalGlow` — це зсув [праворуч, угору] в
// одиницях меша. Напрямки «праворуч» і «вгору» беруться зі СТОВПЦІВ
// матриці modelView, тобто це осі камери, виражені в місцевих
// координатах тіла. Зсув застосовується ДО `modelViewMatrix`, тому
// масштаб групи діє на нього рівно один раз — світіння росте разом з
// артефактом, а не окремо від нього.
//
// Вершина з нульовим зсувом лишається на місці. Саме так у цьому меші
// живе кільце: один матеріал, один прохід, два різні тіла.
// ============================================================
import type * as THREE from 'three';

/**
 * `onBeforeCompile` для матеріалу, меш якого несе `portalGlow`.
 *
 * Ставиться беззастережно: меш без атрибута просто не має чого зсувати,
 * а `finish` не ставить атрибут там, де всі зсуви нульові
 * (`portalIsland.ts`). Тобто вмикач тут — сама геометрія.
 */
export function portalGlowBillboard(shader: { vertexShader: string }): void {
  shader.vertexShader = `attribute vec2 portalGlow;\n${shader.vertexShader}`.replace(
    '#include <begin_vertex>',
    `#include <begin_vertex>
    {
      vec3 portalRight = normalize( vec3( modelViewMatrix[0][0], modelViewMatrix[1][0], modelViewMatrix[2][0] ) );
      vec3 portalUp = normalize( vec3( modelViewMatrix[0][1], modelViewMatrix[1][1], modelViewMatrix[2][1] ) );
      transformed += portalRight * portalGlow.x + portalUp * portalGlow.y;
    }`,
  );
}

/**
 * Той самий шейдер, але прив'язаний до конкретного матеріалу.
 *
 * Три.js кешує програми за рядком шейдера, тож обгортка потрібна лише
 * для того, щоб типи збіглися з тим, що чекає `onBeforeCompile`.
 */
export type PortalGlowBillboard = (shader: THREE.WebGLProgramParametersWithUniforms) => void;
