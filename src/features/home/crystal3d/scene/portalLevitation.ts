// ============================================================
// Левітація малих островів — і чому вона живе у вершинному шейдері.
// ------------------------------------------------------------
// Прохання власника: «додай легеньку левітацію на маленькі острови навколо
// основного острова, вони повільно піднімаються вверх і вниз не на велику
// дистанцію, основний острів не рухається».
//
// ЧОМУ НЕ ТРАНСФОРМАЦІЯ МЕША. Усі брили — один меш, і це не випадковість:
// сцена має рівно чотири draw call'и, і кожна брила окремим об'єктом
// коштувала б ще двадцять чотири. Рухати цей меш цілком означало б, що всі
// камені підіймаються В ОДИН ГОЛОС, а це на екрані читається не левітацією,
// а тремтінням камери.
//
// Тому рух іде у вершинному шейдері, а хто саме рухається — каже атрибут
// `portalFloat` (фаза й темп на кожну брилу, `portalIsland.ts`). Меш, який
// цього атрибута не має, зрушити нічим: острів стоїть нерухомо за
// будовою, а не за домовленістю.
// ============================================================
import type * as THREE from 'three';

/**
 * Розмах, у одиницях острова (радіус острова = 1).
 *
 * «Не на велику дистанцію» власника — це число. 0.038 радіуса острова: на
 * телефоні, де острів займає близько 250 CSS-пікселів, це ±9.5 пікселя —
 * видно, що камінь дихає, і не видно, що він кудись летить.
 *
 * Розмах у одиницях острова, а не сцени, навмисно: уся сцена масштабується
 * разом із кадром (`portalIslandScale`), тож стала в одиницях сцени
 * означала б, що на молодій парі камені гойдаються вдвічі сильніше.
 */
export const PORTAL_DRIFT_LIFT = 0.038;

/**
 * Період на темпі 1, у секундах.
 *
 * «Повільно» — теж число. Сімнадцять секунд на повний цикл при темпі
 * 0.72…1.34 дає 12.7…23.6 секунди на брилу: рух, який помічають боковим
 * зором і не помічають, коли дивляться прямо.
 */
export const PORTAL_DRIFT_PERIOD = 17;

/**
 * Наскільки брила піднялась за `seconds`, у одиницях острова.
 *
 * Та сама формула, що у вершинному шейдері нижче, і саме тому вона тут:
 * шейдер тестом не перевіриш, а це — можна. Якщо вони розійдуться, тест
 * стереже те, чого на екрані немає.
 */
export function portalDriftLift(phase: number, pace: number, seconds: number): number {
  return Math.sin((seconds * 2 * Math.PI * pace) / PORTAL_DRIFT_PERIOD + phase) * PORTAL_DRIFT_LIFT;
}

const DECLARATION = /* glsl */ `
attribute vec2 portalFloat;
uniform float uPortalFloatSeconds;
`;

/**
 * Зсув вершини, як його бачить GLSL.
 *
 * Експортовано заради тесту, і це не витік деталі назовні: формула написана
 * двічі — тут і в `portalDriftLift` вище, — і це найтонше місце всієї
 * зміни. Шейдер тестом не запустиш, тож тест звіряє, що в текст програми
 * підставились ТІ САМІ сталі, якими він перевіряє копію.
 */
export const PORTAL_DRIFT_OFFSET_GLSL = /* glsl */ `
  transformed.y += sin(
    uPortalFloatSeconds * 6.2831853 * portalFloat.y / ${PORTAL_DRIFT_PERIOD.toFixed(1)}
    + portalFloat.x
  ) * ${PORTAL_DRIFT_LIFT.toFixed(4)};
`;

/**
 * Годинник левітації — СПИСОК уніформ, а не одна.
 *
 * `onBeforeCompile` кличеться, коли Three компілює програму, тобто не тоді,
 * коли зручно React'ові. Тому уніформа створюється тут, а посилання на неї
 * лягає в переданий масив: кадр рухає їх напряму, не перемальовуючи дерево.
 * Так само влаштований годинник аврори в рушії.
 *
 * СПИСОК, А НЕ ОДНА, і це не запас на майбутнє — це вже сталося. Той самий
 * рух носять ДВА матеріали: брили й трава, що на них росте (ADR-0163). Поки
 * тут стояло одне посилання, друга компіляція затирала першу, і рухався б
 * рівно один із двох мешів — камінь без трави або трава без каменя.
 */
export function portalLevitation(clocks: { current: { value: number }[] }) {
  return (shader: { vertexShader: string; uniforms: Record<string, { value: number }> }): void => {
    shader.uniforms['uPortalFloatSeconds'] = { value: 0 };
    clocks.current.push(shader.uniforms['uPortalFloatSeconds']!);
    shader.vertexShader = shader.vertexShader
      .replace('void main() {', `${DECLARATION}\nvoid main() {`)
      .replace('#include <begin_vertex>', `#include <begin_vertex>\n${PORTAL_DRIFT_OFFSET_GLSL}`);
  };
}

/** Чи несе цей меш атрибут руху взагалі. */
export function floats(geometry: THREE.BufferGeometry): boolean {
  return geometry.getAttribute('portalFloat') !== undefined;
}
