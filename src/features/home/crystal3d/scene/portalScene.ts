/**
 * Реальна вартість оточення — джерело правди для стелі вище.
 *
 * Будує ті самі геометрії, які малює `PortalEnvironment`, і рахує
 * їхні трикутники. Дорого, і саме тому це функція для тесту, а не для
 * рантайму.
 */
export function measurePortalEnvironmentTriangles(
  seed = 1,
  quality: 'high' | 'balanced' | 'low' | 'fallback' = 'high',
): number {
  const pieces = [
    buildPortalIslandGeometry(seed, PORTAL_ISLAND_RUBBLE[quality]),
    buildPortalTempleGeometry(seed),
    buildPortalDriftGeometry(seed, PORTAL_DRIFT_ROCKS[quality]),
    buildPortalFloraGeometry(seed, quality),
    buildPortalWaterfallGeometry(seed, PORTAL_WATERFALLS[quality]),
  ];
  /*
   * ADR-0210: водоспади малюються ДВІЧІ — стрічкою й світним проходом
   * тієї самої геометрії, — тож і платяться двічі. Аура кристала — спрайт,
   * тобто два трикутники.
   */
  const fallsIndex = 4;
  const AURA_TRIANGLES = 2;
  let total = AURA_TRIANGLES;
  pieces.forEach((piece, index) => {
    const triangles = piece.getAttribute('position').count / 3;
    total += index === fallsIndex ? triangles * 2 : triangles;
    piece.dispose();
  });
  return total;
}

