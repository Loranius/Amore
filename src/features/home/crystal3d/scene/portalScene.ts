// ── Палітра ─────────────────────────────────────────────────

export interface PortalPalette {
  /**
   * Повітряна далечінь.
   *
   * Не імла зали: сцена відкрита, і туман тут робить те, що робить
   * повітря — з'їдає дальні брили й корінь острова, лишаючи різким те,
   * що поруч. Хмари туману не беруть узагалі (див. `portalIsland.ts`):
   * вони стоять за п'ятдесят одиниць і стали б рівно його кольором.
   */
  fog: string;
  /* ── Літаючий острів (ADR-0141) ───────────────────────────
     Камінь плато, камінь храму й брили в небі. Кожна роль є в обох порах
     доби, бо тема міняє світло, а не продукт.

     Світла тема — той самий острів удень: сонце над хмарами, вапняк
     храму теплий, камінь плато світлий. Темна — ніч над морем хмар, де
     єдине сильне світло на острові — сам артефакт. */
  /** Камінь плато й кореня острова. */
  islandRock: string;
  /**
   * Колір відбитого від плато світла — окрема роль, а не колір каменю.
   *
   * Плато НАМАЛЬОВАНЕ, а заливка знизу — справжнє світло, тож брати одне
   * замість іншого означає плутати колір середовища з кольором джерела,
   * а це вже одного разу коштувало чорного екрана (ADR-0065). І число
   * тут інше не з естетики: виміряно на кадрі. Коли заливка взяла тон
   * самого плато (`#b0a4b8` замість `#8b8098`), різниця сусідніх граней
   * кристала на одинадцятому році впала нижче 10% — тобто артефакт
   * перестав читатись кристалом рівно від того, що знизу стало світліше.
   */
  groundBounce: string;
  /**
   * Камінь храму — світліший за плато, і це не примха.
   *
   * Храм тесаний, плато — злам породи. Один тон на обидва зробив би храм
   * горбом на острові; різниця в тоні і є те, що каже «це зроблене
   * руками», ще до того, як око розбере колони.
   */
  templeStone: string;
  /** Брили, що висять у повітрі. Той самий камінь, але далі й тьмяніше. */
  driftRock: string;
  /**
   * Рослинність на островах (ADR-0163).
   *
   * ЄДИНИЙ ЗЕЛЕНИЙ У СЦЕНІ, і він тут за дозволом `DESIGN.md`: Rare Colour
   * стосується поверхонь порталу — ґрунту, картки, канта, — а світ артефакта
   * живе за іншим законом, бо він не інтерфейс, а предмет. «Життя навколо
   * них — середовище, і воно кольорове тому, що кораловий риф кольоровий.»
   *
   * Напрямок контрасту РІЗНИЙ у двох порах доби, і це не недогляд симетрії,
   * а те саме «тема міняє світло, а не продукт». Уночі камінь темний
   * (L 0.129), і трава ловить місяць — вона світліша (L 0.288). Удень
   * камінь блідий (L 0.392), і трава темніша за нього (L 0.218). В обидві
   * пори вона видима, і в обидві вона МЕНШ насичена за камінь, тож зелень
   * не виходить із приглушеного світу острова.
   */
  flora: string;
  /** Море хмар унизу. Не туман: це тіло, і воно має власний тон. */
  cloudSea: string;
  /** Наскільки хмари щільні. Уночі це натяк, удень — підлога світу. */
  cloudOpacity: number;
  /** Небо над островом — колір джерела, з якого падає ключ. */
  skyLight: string;
  /** Сила світла, яке падає з неба вниз. */
  skyIntensity: number;
  /* ── Світло сцени ─────────────────────────────────────────
     Позиції ключа й заливки спільні на обидві пори доби
     (`PORTAL_KEY_LIGHT`, `PORTAL_RIM_LIGHT`): §10 каже, звідки падає
     ключ, і це композиція сцени, а не властивість пори доби. */
  ambient: number;
  hemisphere: number;
  keyIntensity: number;
  keyColour: string;
  rimIntensity: number;
  rimColour: string;
  /**
   * Слабке світло від кореня артефакта (§10 брифу).
   *
   * Називалось `daisLight`, поки під кристалом стояв подіум. Подіуму
   * немає (ADR-0117), а світло лишилось — воно й було не про подіум, а
   * про те, що жила світиться знизу.
   */
  rootLight: string;
  rootLightIntensity: number;
}

