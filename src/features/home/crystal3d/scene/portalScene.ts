/**
 * Скільки draw call'ів додає оточення. Приймальний тест перевіряє, що
 * кристал лишається збатчений (draw call'и ≈ кількість матеріалів, а не
 * тіл), тож він мусить знати внесок сцени — інакше довелось би просто
 * послабити межу й перевірка втратила б сенс.
 *
 * Сім мешів: острів (разом з уламками — камінь той самий, тож окремий
 * прохід коштував би draw call і не давав нічого), храм, брили в небі,
 * рослинність, море хмар, водоспади й світляне кільце.
 *
 * 4 → 5 (ADR-0163), і платимо ми цей call за КОЛІР, а не за геометрію.
 * Вершинний колір у `meshBasicMaterial` МНОЖИТЬСЯ на колір матеріалу, тож
 * трава, покладена в меш каменю, вийшла б кольору «камінь × зелень».
 * Пофарбувати її можна лише власним матеріалом, а власний матеріал і є
 * draw call. Зате меш ОДИН на обидва місця — і плато, і летючі брили.
 *
 * 5 → 6 (ADR-0167) — водоспади, і цей call платиться за ПРОЗОРІСТЬ. Вода
 * малюється без запису глибини й напівпрозорою; у меші каменю це означало б
 * напівпрозорий острів. Власник дозволив +3 call'и разом із бюджетом
 * трикутників (ADR-0164), тож це другий із трьох.
 *
 * 6 → 7 (ADR-0168) — світляне кільце, і сьомий call платиться за
 * ДОДАВАННЯ: кільце малюється `AdditiveBlending`, тобто іншим режимом
 * змішування, а режим змішування — властивість матеріалу. Третій із
 * трьох дозволених; вільних більше немає.
 *
 * 7 → 8 (ADR-0210). Море хмар пішло в намальоване небо (−1). Прийшли
 * аура кристала — спрайт, бо світло мусить дивитись у камеру з будь-якого
 * боку (+1), — і світний прохід водоспадів, бо та сама стрічка потрібна
 * вдруге в режимі ДОДАВАННЯ (+1). Конверт ADR-0164 перевищено на один
 * call заради прохання власника «максимально наближено до еталона», і
 * це записано тут, а не сховано. Якщо call доведеться повернути, першим
 * знімається світний прохід водоспадів: аура важить у кадрі більше.
 *
 * 8 → 7 (ADR-0211). Світляне кільце прибрано на прохання власника
 * («прибери кільце сяйва навколо кристала») разом із дисками світіння в
 * тому самому меші. Конверт ADR-0164 знову дотримано.
 */
