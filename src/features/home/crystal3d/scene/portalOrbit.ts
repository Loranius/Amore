// ============================================================
// Наскільки кристал слухається пальця.
// ------------------------------------------------------------
// Власник: «свайп кристала по осі занадто повільний і важкий на
// телефоні». Причина не в силі повороту, а в ЗГАСАННІ, і вона
// рахується, а не вгадується.
//
// `OrbitControls` із `enableDamping` працює так: рух пальця додається
// до накопиченого зсуву, і на КОЖНОМУ КАДРІ до камери застосовується
// лише `dampingFactor` частка того зсуву, а решта множиться на
// `(1 - dampingFactor)`. Тобто після `n` кадрів пройдена частка —
// `1 - (1 - dampingFactor)ⁿ`.
//
// Із колишніми 0.08 це давало:
//
//   | кадрів | пройдено |
//   |---|---|
//   | 1 | 8% |
//   | 6 | 39% |
//   | 12 | 63% |
//
// Шість кадрів — це 100 мс на шістдесяти кадрах і **200 мс на
// тридцяти**, які й дає телефон під цією сценою. Палець уже зупинився,
// а кристал пройшов менше половини — це й є «важкий».
//
// І головне: згасання рахується НА КАДР, а не на секунду, тож на
// повільнішому пристрої воно стає вдвічі повільнішим саме там, де вже
// й так важче. Три цього не виправляє, тож єдина ручка — сама частка.
// ============================================================

/**
 * Частка накопиченого зсуву, яку камера проходить за кадр.
 *
 * 0.26 обрано за таблицею вище: 26% за перший кадр, 80% за шість,
 * 96% за дванадцять. Палець веде предмет, а не тягне його крізь
 * в'язке; інерція після відпускання лишається, але коротка.
 *
 * Вище 0.4 згасання перестає бути помітним узагалі, і рух починає
 * смикатись на пропущених кадрах — саме тому це не одиниця.
 */
export const PORTAL_ORBIT_DAMPING = 0.26;

/**
 * Швидкість повороту пальцем.
 *
 * `OrbitControls` міряє поворот у частках ВИСОТИ полотна: повний оберт
 * — це проведення на висоту екрана. На телефоні полотно високе й
 * вузьке, тож горизонтальний свайп через увесь екран дає заледве
 * третину оберта. Тому на дотику швидкість вища, ніж на миші, — щоб
 * однаковий жест давав однаковий поворот.
 */
export const PORTAL_ORBIT_ROTATE_SPEED = 1;
export const PORTAL_ORBIT_TOUCH_ROTATE_SPEED = 1.7;

/**
 * Яку частку зсуву пройдено за `frames` кадрів.
 *
 * Існує заради тесту: інакше таблиця вище — просто коментар, який
 * ніхто не перевіряє.
 */
export function orbitCatchUp(dampingFactor: number, frames: number): number {
  const factor = Math.min(1, Math.max(0, dampingFactor));
  return 1 - (1 - factor) ** Math.max(0, frames);
}

/**
 * Швидкість повороту для конкретного пристрою й режиму.
 *
 * `OrbitControls` має одну ручку швидкості на всі види вводу, тож
 * розводити мишу з пальцем доводиться тут. Ознака — грубий вказівник
 * (`pointer: coarse`), тобто саме палець, а не розмір екрана: планшет
 * із мишею крутить як настільний, і навпаки.
 *
 * У вільній камері швидкість нижча в обох випадках: там жест не крутить
 * предмет, а веде саму камеру, і різкість там читається зривом.
 */
export function portalOrbitRotateSpeed(coarsePointer: boolean, freeCamera: boolean): number {
  const base = coarsePointer ? PORTAL_ORBIT_TOUCH_ROTATE_SPEED : PORTAL_ORBIT_ROTATE_SPEED;
  return freeCamera ? base * 0.72 : base;
}

/** Чи веде цим пристроєм палець. Поза браузером — ні. */
export function coarsePointerNow(): boolean {
  if (typeof window === 'undefined' || typeof window.matchMedia !== 'function') return false;
  return window.matchMedia('(pointer: coarse)').matches;
}
