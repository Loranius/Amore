// ============================================================
// BloomProbe — повноекранний Bloom. ТІЛЬКИ ДІАГНОСТИКА (`?gfx=bloom`).
// ------------------------------------------------------------
// Другий із двох підозрюваних у білому фоні на пристрої власника (перший —
// карта оточення, render/envMap.ts). У липні їх прибрали ОДНИМ коммітом
// (`ba6ad77`), тож жоден не перевірений поодинці — а `EffectComposer`
// рендерить сцену у власні таргети й потім блітить, тобто саме той клас
// коду, де alpha на мобільних драйверах ламається найчастіше.
//
// Окремим файлом і за `React.lazy` — навмисно: `postprocessing` важить
// сотні кілобайт, і поки Bloom не в дефолті, він не має лежати в головному
// чанку кожної пари. Динамічний імпорт лишає його окремим чанком, який
// вантажиться лише коли в URL є прапорець.
// ============================================================
import { Bloom, EffectComposer } from '@react-three/postprocessing';

export default function BloomProbe() {
  return (
    <EffectComposer>
      {/* Поріг високий: світитись має вістря монарха й золото віх, а не
          вся маса. Значення підбирати після того, як пристрій скаже, чи
          Bloom узагалі дозволений. */}
      <Bloom intensity={0.6} luminanceThreshold={0.72} luminanceSmoothing={0.25} mipmapBlur />
    </EffectComposer>
  );
}
