import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DEFAULT_GFX, parseGfxProfile } from './gfxProfile';

// ============================================================
// Чи діагностика ДІСТАЄ до екрана, який бачить пара (ADR-0171).
// ------------------------------------------------------------
// ВАДА, ЯКУ ЦЕ ЗАМИКАЄ. `?gfx=` читався в `CrystalScene`, і це було
// правдою рівно доти, доки портал малювала вона. З переходом на Evolution
// стара сцена лишилась АВАРІЙНИМ ФОЛБЕКОМ — на головній її не монтує
// ніхто, — а прапорець ніхто не переніс. Тобто інструмент, на якому
// тримається все питання «чи можна повернути Bloom», не діяв на єдиному
// екрані, де його треба міряти.
//
// Власник відкрив три посилання й не побачив нічого. Він був правий, а я
// послав його вимірювати те, що не могло виміритись.
//
// Перевіряється ДЖЕРЕЛО, а не поведінка, і це свідомо: поведінку тут дає
// WebGL, якого в тестах немає, а вада була саме структурною — «читається
// не там». Тест, який ловить її, мусить питати те саме.
// ============================================================

const scene = readFileSync(
  fileURLToPath(new URL('../evolution/EvolutionCrystalPreviewScene.tsx', import.meta.url)),
  'utf8',
);

describe('діагностичний профіль дістає до порталу (ADR-0171)', () => {
  it('сцена порталу читає прапорець із адреси', () => {
    expect(scene).toContain('gfxProfileFromLocation');
  });

  it('сцена порталу вміє показати обидва підозрювані', () => {
    // Bloom — повноекранний прохід; карта оточення — PMREM із HalfFloat
    // render target. Обидва прибрали в липні ОДНИМ коммітом, тож жоден не
    // перевірений поодинці; сцена мусить уміти ввімкнути кожен окремо.
    expect(scene).toContain('BloomProbe');
    expect(scene).toContain('buildStudioEnvMap');
    expect(scene).toContain('envMap={envMap}');
  });

  it('сцена порталу показує значок профілю', () => {
    /*
     * Без значка помилка набору (`?gfx=blomo`) мовчки дає дефолтний
     * профіль: власник побачить сцену без білого фону й зробить ХИБНИЙ
     * висновок, що Bloom безпечний. Значок — єдине, що відрізняє
     * «перевірено» від «не ввімкнулось».
     */
    expect(scene).toContain('crystal-gfx-badge');
    /*
     * Умова — «в адресі щось просили», а не «профіль не дефолтний»
     * (ADR-0173). Відколи Bloom у дефолті на потужних пристроях,
     * `?gfx=bloom` дорівнює дефолту, і значок, прив'язаний до
     * відмінності, зник би саме під час діагностики.
     */
    expect(scene).toContain('isGfxRequested');
  });

  it('значок стоїть ВИЩЕ за нижню навігацію', () => {
    /*
     * Він стояв на `bottom: 6px`, тобто рівно під доком, який на телефоні
     * закриває його наполовину. Для значка, який власник мусить
     * ПРОЧИТАТИ з телефона, це те саме, що його не мати.
     */
    const css = readFileSync(
      fileURLToPath(new URL('../../../../index.css', import.meta.url)),
      'utf8',
    );
    const rule = css.slice(css.indexOf('.crystal-gfx-badge {'));
    const bottom = /bottom:\s*(\d+)px/.exec(rule.slice(0, rule.indexOf('}')));
    expect(bottom, 'у значка немає відступу знизу').not.toBeNull();
    expect(Number(bottom![1])).toBeGreaterThan(80);
  });

  it('порожня адреса лишає дефолт, а не вмикає підозрюваних', () => {
    // Звичайний перегляд пари не має наближатись до баґа, доки триває
    // бісекція.
    expect(parseGfxProfile('')).toEqual(DEFAULT_GFX);
    expect(DEFAULT_GFX.bloom).toBe(false);
    expect(DEFAULT_GFX.env).toBe(false);
  });
});
