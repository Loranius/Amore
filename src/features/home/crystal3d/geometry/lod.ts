// ============================================================
// lod — рівні деталізації геометрії (Volume V, §17).
// ------------------------------------------------------------
// Нормативно: `V5-REQ-009`, `V5-REQ-016`, `CAI-REQ-011`.
//
// Що тут LOD і чому саме такий. Класичний LOD за відстанню тут не має
// сенсу: кристал — один невеликий об'єкт, який завжди стоїть приблизно на
// однаковій відстані від камери (орбіта фіксованого радіуса). Тому рівень
// обирається ОДИН раз під можливості пристрою, а не щокадру під дистанцію.
// Це і є «representative mobile LODs» з §8 профілю.
//
// Скорочується ЛИШЕ кількість граней тіла. Тіла не викидаються навмисно:
//   • дитина, чий господар зник би на дрібному рівні, стала б сиротою —
//     пряме порушення `CAI-REQ-004`/`011`, і саме той клас багів, який ми
//     ловили в Phase 2 (`orphan core-2`);
//   • «younger yields» і відчуття append-only тримаються на тому, що набір
//     тіл не залежить від пристрою: пара не має бачити менший кристал на
//     слабшому телефоні.
// Зменшення граней такого ризику не несе взагалі — множина тіл і всі
// кріплення лишаються ті самі.
//
// Детермінізм (`V5-REQ-009`): множник застосовується ПІСЛЯ всіх звертань до
// shapeRng, тож потік випадковості не зсувається. Рівень 'high' дає
// побайтово ту саму геометрію, що й до появи LOD.
// ============================================================

export type LodLevel = 'high' | 'medium' | 'low';

/** Усі публіковані рівні — саме їх зобов'язана перевіряти валідація. */
export const LOD_LEVELS: readonly LodLevel[] = ['high', 'medium', 'low'] as const;

export interface LodPolicy {
  readonly id: LodLevel;
  /** Множник кількості граней тіла. */
  readonly segmentScale: number;
  /** Нижня межа: менше 4 граней — це вже не тіло обертання, а трикутник. */
  readonly minSegments: number;
}

const POLICIES: Record<LodLevel, LodPolicy> = {
  high: { id: 'high', segmentScale: 1, minSegments: 4 },
  medium: { id: 'medium', segmentScale: 0.72, minSegments: 4 },
  low: { id: 'low', segmentScale: 0.5, minSegments: 4 },
};

export const lodPolicy = (level: LodLevel): LodPolicy => POLICIES[level];

/** Кількість граней тіла на заданому рівні. */
export function lodSegments(baseSegments: number, level: LodLevel): number {
  const policy = POLICIES[level];
  return Math.max(policy.minSegments, Math.round(baseSegments * policy.segmentScale));
}

/**
 * Рівень, який застосунок реально показує.
 *
 * Автовибору під пристрій тут НЕМАЄ, і це висновок із вимірювання, а не
 * недоробка. Заміри на реальній масі (seed 1A2B, 48 тіл):
 *
 *   рівень   вершин   трикутників   draw calls
 *   high      2728        1915           34
 *   medium    2112        1773           37
 *   low       1920        1771           42
 *
 * Тобто дрібніший рівень ріже пам'ять (−30% вершин), але трикутників майже
 * не зменшує і draw calls ЗБІЛЬШУЄ. Причина не випадкова: чим грубіші тіла,
 * тим більші їхні грані, тим рідше грань цілком уміщається в сусіда — і тим
 * менше знімає прибирання прихованих граней (на 'high' повністю ховаються
 * 14 тіл, на 'low' лише 6). Два механізми працюють один проти одного.
 *
 * А вузьке місце на мобільному GPU тут саме draw calls: 48 окремих мешів.
 * Тому автоматично «знижувати якість» означало б робити гірше. Рівні
 * генеруються й валідуються всі три (`CAI-REQ-011`, `V5-REQ-009`), але
 * застосунок показує 'high', доки не з'явиться важіль, що б'є по draw calls
 * (об'єднання мешів за матеріалом) — це вже наступна задача, і вона
 * конфліктує з подихом кожного тіла окремо, тож потребує окремого рішення.
 */
export const RENDERED_LOD: LodLevel = 'high';
