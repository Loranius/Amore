// Власник, 2026-09-29: «додай після вибору об'єкта … можливість
// переглядати лише обраний об'єкт, вікно вибору кристал дерево риф
// (вулкан) зверху прибери, зроби це для усіх користувачів окрім мене».
//
// Пара обирає вид один раз — при реєстрації — і далі живе з ним. Перемикач
// лишається тільки власнику порталу: він дивиться всі види, бо їх розробляє.
//
// Власника впізнаємо за `users.id`, а не за поштою: пошта в коді сайту
// лежала б у публічному бандлі, а id нічого не розкриває. `id = 1` звірено
// з базою за поштою власника (2026-09-29).
// ============================================================

/** `users.id` власника порталу (Діма). */
export const ARTIFACT_EXPLORER_USER_ID = 1;

/** Чи бачить людина перемикач видів і чи слухає портал `?artifact=` в адресі. */
export function canSwitchArtifact(userId: number | null | undefined): boolean {
  return userId === ARTIFACT_EXPLORER_USER_ID;
}
