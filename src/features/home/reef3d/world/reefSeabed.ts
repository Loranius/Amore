// ============================================================
// Піщане дно: дюни, брижі й колір, що йде за рельєфом.
// ------------------------------------------------------------
// Було коло з 48 сегментів — рівна тарілка, на якій лежить риф. На
// референсах власника дно ЖИВЕ: його переорано хвилями в дрібні брижі,
// а під ними лежать довгі пологі дюни. Саме вони й дають масштаб: без
// них не видно, велика перед тобою брила чи маленька.
//
// ТРИ РІШЕННЯ, ЯКІ ТУТ ВАРТО ЗНАТИ.
//
// 1. СІТКА ЗГУЩУЄТЬСЯ ДО ЦЕНТРУ. Дно тягнеться на тридцять радіусів
//    каменя, але роздивляються з нього перші два. Рівномірна сітка
//    витратила б на далеке вісімнадцять з двадцяти тисяч вершин —
//    туди, де все одно самий туман. Радіус іде степенем 2.2, тож
//    щільність біля рифа вища вдесятеро.
//
// 2. НОРМАЛЬ БЕРЕТЬСЯ З ПОХІДНОЇ, А НЕ З СУСІДНІХ ГРАНЕЙ. Висота
//    задана формулою, тож нахил можна порахувати точно замість
//    усереднювати трикутники. Дешевше й без швів на стику кілець.
//
// 3. КОЛІР ЖИВЕ У ВЕРШИНАХ. Гребінь брижі світліший за западину — це
//    те, що робить пісок піском, і воно не коштує ані текстури, ані
//    другого виклику малювання.
// ============================================================
import { BufferAttribute, BufferGeometry } from 'three';

/**
 * Кільця й сегменти.
 *
 * **46×56 → 38×40 (ADR-0193), і це не економія заради економії.**
 *
 * Дно малюється ДВІЧІ: сам пісок і каустика поверх тієї самої сітки
 * (другий прохід, додаванням). Тому кожен трикутник тут коштує вдвічі, і
 * на живому розкладі сцени ці два проходи разом важили **10 304
 * трикутники — 38% усього рифа**, тоді як сам риф із каменем важив 2 640.
 *
 * Детальність при цьому лежала там, де її не видно: колір множиться на
 * серпанок і сходить у нуль на 0.55 радіуса, а розподіл кілець степенем
 * 2.2 кладе за цю межу майже чверть усіх кілець. Тобто одинадцять кілець
 * із сорока шести малювали двічі те, чого ніхто не бачить.
 *
 * 38×40 лишає біля рифа ту саму густину (кільця й далі згущені степенем
 * 2.2, кутовий крок 9° замість 6.4° на колі, якого ніхто не обводить
 * оком) і повертає **4 224 трикутники на двох проходах** — рівно ту суму,
 * якою сплачено згладження купола й коралів.
 */
const RINGS = 38;
const SEGMENTS = 40;

/** Наскільки щільніша сітка біля рифа: радіус іде цим степенем. */
const RADIAL_BIAS = 2.2;

/** Довгі пологі дюни: висота в частках опорного розміру. */
const DUNE_HEIGHT = 0.085;

/**
 * Брижі: висота й крок.
 *
 * Перша редакція мала висоту 0.016 при кроці 5.5 — на знімку дно
 * вийшло рівним. Причина рахується: така хвиля дає нахил близько двох
 * градусів, а двома градусами світло не малює нічого. Брижі мусять
 * бути помітними геометрично, інакше їх немає взагалі.
 */
const RIPPLE_HEIGHT = 0.055;
const RIPPLE_PITCH = 3.2;

/** Де брижі згасають, у частках повного радіуса дна. */
const RIPPLE_FADE = 0.5;

/**
 * Де дно розчиняється у воді, у частках свого радіуса.
 *
 * Туман сам по собі цього не робить: каустика малюється ДОДАВАННЯМ, і
 * туман на ній не гасить, а навпаки — додає свій колір, тож удалині все
 * дно засвічувалось у суцільну білу стіну.
 *
 * **Числа лишились, місце змінилось (ADR-0195, крок 6).** Доти згасання
 * писалось у вершини — і саме там ставало блідою багатокутною терасою
 * навколо рифа, бо сітка радіальна й там, де згасання найкрутіше, кільця
 * стоять найрідше. Тепер його рахує піксель (`applyReefHaze`), а межі
 * експортуються звідси, щоб у піску й каустики вони не розійшлись.
 */
export const HAZE_FROM = 0.16;
export const HAZE_TO = 0.55;

/**
 * НАМЕТ ПІСКУ, ЯКИЙ ХОВАЄ ПЛАСКИЙ ОБІД КАМЕНЯ.
 *
 * ЩО САМЕ ВІН ХОВАЄ, і як це знайдено. Навколо рифа на кожному кадрі
 * лежала бліда БАГАТОКУТНА ТЕРАСА з прямими краями. Три гіпотези поспіль
 * були хибні — намет піску, серпанок дна, каустика, — і всі три
 * спростовано бісекцією: сцену знімали з вимкненим шаром, а тоді з
 * тілом, пофарбованим у червоне.
 *
 * Червоне сказало: тераса — це САМ КАМІНЬ. Він півеліпсоїд із
 * відношенням радіуса до висоти 3.15, тож його зовнішня третина лежить
 * майже горизонтально, а обід — це 36-кутник, обрізаний по піску. Тобто
 * риф стоїть на ТАРІЛЦІ.
 *
 * `PRODUCT.md` §5 забороняє це прямо: «Артефакт росте з чогось. Гладка
 * суцільна поверхня під ним читається п'єдесталом, хай як її формувати».
 * Кристал колись заплатив за цей самий урок купою битого каменю під
 * собою.
 *
 * ЧОМУ ПІСКОМ, А НЕ ЗМІНОЮ КАМЕНЯ. Камінь має власну роботу: він ховає
 * нижню кришку купола, і його ширина — розв'язок рівняння, а не смак
 * (`reefStaging.ts`). Пісок же робить рівно те, що робить у природі:
 * течія несе його й кладе там, де перешкода її гальмує. Намет підмінює
 * пласку тарілку схилом, не чіпаючи жодної гарантії.
 *
 * Висота — у частках радіуса каменя; 0.16 накриває обід приблизно до
 * 0.85 його радіуса, тобто рівно ту частину, яка лежить пласко.
 */
const SKIRT_HEIGHT = 0.16;
const SKIRT_FALL = 0.5;

/**
 * Висота піску в точці.
 *
 * Дюни — дві синусоїди під різними кутами: одна дає напрям, друга
 * ламає його регулярність. Брижі — третя, дрібна й майже поперечна до
 * дюн, як воно й буває на справжньому дні.
 */
function sandRelief(x: number, z: number, scale: number, radius: number): number {
  const dune = Math.sin(x / (scale * 2.6) + 0.7) * Math.cos(z / (scale * 3.4) - 0.3)
    + 0.45 * Math.sin((x + z) / (scale * 1.7));
  const distance = Math.hypot(x, z) / radius;
  const fade = Math.max(0, 1 - distance / RIPPLE_FADE);
  const ripple = Math.sin((x * 0.82 + z * 0.57) / scale * RIPPLE_PITCH)
    * Math.sin((x * 0.3 - z * 0.95) / scale * RIPPLE_PITCH * 0.35);
  return scale * (DUNE_HEIGHT * dune * 0.55 + RIPPLE_HEIGHT * ripple * fade);
}

/**
 * Повна висота піску: рельєф плюс намет при камені.
 *
 * РОЗДІЛЕНІ ВОНИ НЕ РАДИ ОХАЙНОСТІ. Тон піску йде за висотою — гребінь
 * брижі світліший за западину, — і намет, потрапивши в ту саму величину,
 * зробив би навколо каменя СВІТЛЕ КІЛЬЦЕ, якого на дні немає: намет не
 * гребінь, він просто насипаний пісок. Виміряно власним тестом: ближні
 * вершини виходили 1.08 проти 0.96 у далеких.
 */
function sandHeight(x: number, z: number, scale: number, radius: number): number {
  /*
   * Усередині обводу намет тримається сталим, а не росте далі: там його
   * однаково не видно — накриває сам камінь, — а росла б там висота, вона
   * підняла б і `lowest`, на якому камінь стоїть.
   */
  const toRock = Math.hypot(x, z) / Math.max(1e-6, scale);
  const skirt = SKIRT_HEIGHT * (toRock <= 1 ? 1 : Math.exp(-(toRock - 1) / SKIRT_FALL));
  return sandRelief(x, z, scale, radius) + scale * skirt;
}

export interface ReefSeabed {
  geometry: BufferGeometry;
  /** Найнижча точка дна — камінь має сісти не вище за неї. */
  lowest: number;
}

/**
 * Дно як сітка з рельєфом і кольором у вершинах.
 *
 * @param scale опорний розмір сцени — рельєф міряється ним, а не числами зі стелі
 * @param radius як далеко тягнеться дно
 */
export function buildReefSeabed(scale: number, radius: number): ReefSeabed {
  const positions: number[] = [];
  const normals: number[] = [];
  const colours: number[] = [];
  const uvs: number[] = [];
  const indices: number[] = [];
  let lowest = 0;

  const step = scale * 0.02;
  for (let ring = 0; ring <= RINGS; ring += 1) {
    const distance = radius * (ring / RINGS) ** RADIAL_BIAS;
    for (let segment = 0; segment < SEGMENTS; segment += 1) {
      const angle = (segment / SEGMENTS) * Math.PI * 2;
      const x = Math.cos(angle) * distance;
      const z = Math.sin(angle) * distance;
      const y = sandHeight(x, z, scale, radius);
      lowest = Math.min(lowest, y);
      positions.push(x, y, z);
      // Розгортка згори: каустика — це тінь від поверхні води, і лягати
      // вона мусить по горизонталі, а не по схилу.
      uvs.push(x / (radius * 2) + 0.5, z / (radius * 2) + 0.5);

      // Нахил із похідної: точний і без швів на стику кілець.
      const slopeX = (sandHeight(x + step, z, scale, radius) - y) / step;
      const slopeZ = (sandHeight(x, z + step, scale, radius) - y) / step;
      const length = Math.max(1e-9, Math.hypot(-slopeX, 1, -slopeZ));
      normals.push(-slopeX / length, 1 / length, -slopeZ / length);

      /*
       * Гребінь світліший за западину. Множник малий навмисно: пісок,
       * у якого смуги видно здалеку, читається килимом.
       */
      /*
       * Тон береться з РЕЛЬЄФУ, а не з повної висоти: намет при камені в
       * нього не входить (див. `sandHeight`), інакше навколо каменя лягло
       * б світле кільце.
       */
      const relief = sandRelief(x, z, scale, radius);
      const lift = 0.5 + 0.5 * Math.max(-1, Math.min(1, relief / (scale * RIPPLE_HEIGHT * 1.6)));
      const tone = 0.82 + 0.26 * lift;
      /*
       * СЕРПАНОК ЗВІДСИ ПІШОВ (ADR-0195, крок 6).
       *
       * Він тут і був причиною блідої багатокутної тераси навколо рифа:
       * сітка радіальна з `RADIAL_BIAS`, тож саме там, де згасання
       * найкрутіше, кільця стоять найрідше, і плавна величина, покладена
       * в такі вершини, інтерполюється великими трикутниками в сходинки.
       *
       * Тепер його рахує піксель (`applyReefHaze`), а у вершині лишився
       * тільки тон дюн — величина, яка справді належить геометрії.
       */
      colours.push(tone, tone, tone);
    }
  }

  for (let ring = 0; ring < RINGS; ring += 1) {
    const low = ring * SEGMENTS;
    const high = low + SEGMENTS;
    for (let segment = 0; segment < SEGMENTS; segment += 1) {
      const next = (segment + 1) % SEGMENTS;
      /*
       * ОБХІД ПРОТИ ГОДИННИКОВОЇ, і це не смак.
       *
       * Перша редакція мала (low, high, low+next) — і дна не було видно
       * ЗОВСІМ. Вимірювання спершу показало, що сцена потемніла на 38%,
       * і два кроки бісекції дали однакове число з дном і без нього:
       * дно ніколи й не малювалось.
       *
       * Причина рахується, а не вгадується. Для A=(d₁cosθ, y, d₁sinθ),
       * B=(d₂cosθ, …), C=(d₁cosθ′, …) вертикальна складова AB×AC
       * дорівнює −(d₂−d₁)·d₁·sin(Δθ), тобто НЕГАТИВНА: нормаль грані
       * дивилась униз, і відсікання зворотних граней прибирало все дно.
       * Нормалі у вершинах при цьому дивились угору — саме тому
       * освітлення виглядало б правильним, якби грані взагалі малювались.
       */
      indices.push(low + segment, low + next, high + segment);
      indices.push(low + next, high + next, high + segment);
    }
  }

  const geometry = new BufferGeometry();
  geometry.setAttribute('position', new BufferAttribute(new Float32Array(positions), 3));
  geometry.setAttribute('normal', new BufferAttribute(new Float32Array(normals), 3));
  geometry.setAttribute('color', new BufferAttribute(new Float32Array(colours), 3));
  geometry.setAttribute('uv', new BufferAttribute(new Float32Array(uvs), 2));
  geometry.setIndex(new BufferAttribute(new Uint32Array(indices), 1));
  geometry.computeBoundingSphere();
  return { geometry, lowest };
}
