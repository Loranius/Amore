// ============================================================
// Коли рифу дозволено дрейфувати самому.
// ------------------------------------------------------------
// ЧОМУ ЦЕ ОКРЕМИЙ ФАЙЛ, А НЕ ДВА РЯДКИ В СЦЕНІ. Через ваду, яку вони
// виправляють: власник сказав, що риф «прокручується дуже важко», і
// причина виявилась не в згасанні, а в тому, що дрейф камери
// ЗАТИРАВ жест пальця.
//
// Механіка точна, і її варто знати, бо на око вона невидима:
//
//   1. `OrbitControls` від drei оновлюється у власному кадровому
//      виклику з пріоритетом −1, тобто ПЕРЕД будь-яким іншим;
//   2. `setAzimuthalAngle(value)` у three-stdlib не додає крок, а
//      ПЕРЕЗАПИСУЄ `sphericalDelta.theta` різницею до потрібного кута;
//   3. отже дрейф щокадру викидав усе, що палець устиг накопичити, і
//      лишав замість нього свій крок у соту частку градуса.
//
// Тобто під час свайпу шістдесят разів на секунду скасовувався сам
// свайп. Ніяке налаштування згасання цього не полагодило б.
// ============================================================

/** Оберт за скільки секунд, коли сцену не чіпають. */
export const DRIFT_PERIOD_SECONDS = 190;

/**
 * Скільки дрейф мовчить після того, як палець відпустив сцену.
 *
 * Не нуль: після відпускання лишається інерція згасання, і дрейф,
 * увімкнений одразу, перехопив би її на півдорозі — рух обірвався б,
 * і це читалося б поштовхом.
 */
export const DRIFT_RESUME_MS = 4200;

/**
 * Крок дрейфу в радіанах, або нуль, поки сцена належить пальцю.
 *
 * @param deltaSeconds тривалість кадру
 * @param heldUntilMs до якого моменту дрейф мовчить; `Infinity` — палець ще веде
 */
export function reefDriftStep(
  deltaSeconds: number,
  heldUntilMs: number,
  nowMs: number,
): number {
  if (!Number.isFinite(deltaSeconds) || deltaSeconds <= 0) return 0;
  if (nowMs < heldUntilMs) return 0;
  return (Math.PI * 2 * deltaSeconds) / DRIFT_PERIOD_SECONDS;
}
