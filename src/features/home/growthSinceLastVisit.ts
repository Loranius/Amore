// ============================================================
// Що виросло з минулого разу — чисті правила.
// ------------------------------------------------------------
// **Знайдено критикою Головної.** Механізм «щось виросло»
// (`useClusterGrowthFlash`) у порталі вже був — і був підключений РІВНО
// до одного місця: `CrystalScene.tsx`, тобто до застарілого рендерера,
// який `EvolutionCrystalPreviewScene` вантажить лише всередині
// `if (error)`. Іншими словами, відповідь на головне питання продукту
// («чи змінилось наше життя?») з'являлась тільки тоді, коли основний
// рендерер падав.
//
// А `PRODUCT.md` визначає успіх дослівно: «пара відкриває головну й
// бачить, що кристал змінився, бо змінилось їхнє життя».
//
// Тут — самі правила, без React і без сховища: що вважати приростом, як
// його підписати й коли мовчати. Саме вони мусять бути під тестом, бо
// помилка тут не падає, а тихо бреше парі про її ж історію.
// ============================================================
import { plural } from '@/lib/plural';
import { HOME_ARTIFACT_LOCATIVE, type HomeArtifact } from './homeArtifact';

/** Подія рушія, звужена до того, що потрібно для «виросло». */
export interface GrowthEvent {
  id: string;
  /** Хто це приніс. `null`, коли джерело не записало автора. */
  actorId: number | null;
}

export interface GrowthSummary {
  /** Скільки подій з'явилось із минулого візиту. */
  newCount: number;
  /** Автори приросту, без повторів і без `null`. */
  actorIds: readonly number[];
  /**
   * Перший візит: бачених ключів ще немає.
   *
   * Тоді приріст НЕ показуємо, і це свідома розбіжність зі старим
   * `useClusterGrowthFlash`, який на першому візиті повертав `grew`.
   * Для тривимірного спалаху це доречно — світ вперше збирається на
   * очах. Для підпису «2 нові миті» — ні: першого разу нове геть усе, і
   * рядок сказав би парі «ваша історія щойно почалась», що просто
   * неправда.
   */
  firstVisit: boolean;
}

/** Порожньо: ні приросту, ні авторів. */
const NOTHING: GrowthSummary = { newCount: 0, actorIds: [], firstVisit: false };

/**
 * Скільки подій з'явилось із минулого разу і хто їх приніс.
 *
 * `seen === null` означає, що сховище порожнє (перший візит або
 * очищені дані).
 */
export function summariseGrowth(
  events: readonly GrowthEvent[],
  seen: ReadonlySet<string> | null,
): GrowthSummary {
  if (seen === null) return { ...NOTHING, firstVisit: true };

  const actors = new Set<number>();
  let newCount = 0;
  for (const event of events) {
    if (seen.has(event.id)) continue;
    newCount += 1;
    if (event.actorId !== null) actors.add(event.actorId);
  }
  if (newCount === 0) return NOTHING;

  // Порядок авторів стабільний: множина ітерується в порядку вставки, а
  // він залежить від порядку подій. Сортування робить підпис однаковим
  // при однакових даних — тій самій вимозі, що й решта детермінізму.
  return {
    newCount,
    actorIds: [...actors].sort((a, b) => a - b),
    firstVisit: false,
  };
}

/**
 * «N нових митей» українською, узгоджено за кількістю.
 *
 * **Одиниця тут — не геометрія, і це виправлення після живого екрана.**
 * Перша редакція писала «Кристал виріс на 309 шарів». На знімку під тим
 * рядком стояв кристал із ВОСЬМИ тіл: рушій обмежує тіла приблизно
 * одним на рік, скільки б подій пара не принесла. Тобто підпис називав
 * число, якого на екрані немає й ніколи не буде, — рівно та мовчазна
 * неправда, яку `CLAUDE.md` забороняє.
 *
 * «Мить» нічого не обіцяє про форму. Вона рахує те, що справді
 * порахували: події пари, які дійшли до рушія.
 *
 * Узгодження обов'язкове разом із прикметником: «3 нові миті», але «5
 * нових митей». «3 нових митей» читається як машинний переклад і одразу
 * коштує тому теплу, заради якого підпис і додається.
 */
export function momentPhrase(count: number): string {
  return plural(count, 'нова мить', 'нові миті', 'нових митей');
}

/**
 * Підпис під лічильником, або `null`, коли казати нічого.
 *
 * Форма «+2» без підмета була першою редакцією й платила за рядок
 * змістом: під числом днів разом вона читалась як ще одна метрика, а
 * підпис існує заради єдиного питання, яке `PRODUCT.md` ставить
 * головній — «чи змінилось наше життя?».
 *
 * Друга редакція, «Кристал виріс на N шарів», підмет повернула, але
 * збрехала числом — див. `momentPhrase`. Ця говорить про вміст, а не
 * про форму: в артефакті справді стало на N подій більше.
 *
 * Партнер іменується лише тоді, коли ВЕСЬ приріст приніс саме він.
 * Змішаний внесок лишається без імені навмисно: назвати Лєну під
 * подіями, половину яких додав Діма, — це неправда, сказана заради
 * теплоти, а такі неправди помічають найшвидше.
 *
 * **Ім'я стоїть у називному, і прийменника перед ним немає.** Перша
 * редакція писала «від {ім'я}» — і одразу дала «від Лєна» замість «від
 * Лєни»: «від» вимагає родового відмінка. Відмінювати довільне ім'я
 * надійно портал не вміє (Лєна→Лєни, але Настя→Насті, Олег→Олега), а
 * зіпсоване ім'я партнера — саме та дрібна неправильність, яка в
 * інтимному застосунку ріже найдужче. Тому крапка-роздільник замість
 * прийменника: працює з будь-яким іменем і в жодному не помиляється.
 *
 * Дієслів немає взагалі, і це теж не випадково: «додала»/«додав»
 * залежать від роду, а рід партнера портал не зберігає.
 *
 * Поле навмисно зветься `displayName`, а не `name`: шапка каже ПІДПИС
 * із профілю, а не ім'я-ключ із `users` (ADR-0180). Обидва рядки, і
 * якби поле звалось `name`, сюди роками ходило б не те — мовчки й
 * правильно на вигляд.
 *
 * **Вид називає той, хто звітував (ADR-0188).** Іменник тут був зашитий
 * — «У кристалі» — і це трималось рівно доти, доки звітував один вид.
 * Щойно риф під'єднали до каналу, живий кадр показав над рифом «У
 * кристалі 435 нових митей»: число правдиве, підмет чужий. Та сама
 * порода помилки, що й дві попередні редакції цього рядка (див. вище):
 * підпис називав те, чого на екрані немає.
 */
export function growthCaption(
  summary: GrowthSummary,
  partner: { id: number; displayName: string } | null,
  species: HomeArtifact,
): string | null {
  if (summary.firstVisit || summary.newCount === 0) return null;

  const where = HOME_ARTIFACT_LOCATIVE[species];
  const base = `У ${where} ${summary.newCount} ${momentPhrase(summary.newCount)}`;
  const onlyPartner = partner !== null
    && summary.actorIds.length === 1
    && summary.actorIds[0] === partner.id;

  return onlyPartner ? `${base} · ${partner.displayName}` : base;
}
