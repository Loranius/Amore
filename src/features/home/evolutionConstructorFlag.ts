// **Знайдено критикою Головної.** Умовою було `me.name === 'Діма'` —
// тобто інструмент розробки жив у продакшн-збірці й показувався на
// головній за ІМЕНЕМ користувача. Три окремі вади в одному рядку:
//
//   1. Це не обмеження доступу. Ім'я — не право; будь-хто, кого звати
//      Діма, отримував панель.
//   2. Він стоїть на головній, а `PRODUCT.md` каже про неї «передусім
//      кристал». Плаваюча кнопка з повзунками над артефактом — шум
//      рівно на тому екрані, де його не має бути.
//   3. Панель приносить із собою друге розмиття на екрані й кольорову
//      тінь у `.is-active` — обидва прямо суперечать правилам, які
//      `DESIGN.md` називає своїми («Одне розмиття», «Тінь — це тінь»).
//
// Але просто вимкнути в продакшні було б втратою: власник тестує
// кристал/дерево/риф на СПРАВЖНЬОМУ порталі з телефона, а не на dev-
// сервері. Тому прапорець тієї самої форми, що вже є в порталі для
// діагностики Evolution і лабораторії дерева: за замовчуванням вимкнено,
// вмикається адресою.
// ============================================================

export const EVOLUTION_SANDBOX_QUERY_KEY = 'sandbox';

/**
 * Конструктор доступний у розробці або на явний запит адресою
 * (`?sandbox=1`).
 *
 * Пара звичайним шляхом його не побачить ніколи: щоб опинитись у цій
 * гілці, треба дописати параметр руками.
 */
export function isEvolutionConstructorEnabled(
  search: string = typeof window === 'undefined' ? '' : window.location.search,
  dev: boolean = import.meta.env.DEV,
): boolean {
  if (dev) return true;
  const value = new URLSearchParams(search).get(EVOLUTION_SANDBOX_QUERY_KEY);
  return value === '1' || value === 'true' || value === 'on';
}
