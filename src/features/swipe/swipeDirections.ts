// ============================================================
// Чотири напрями свайпу — один опис на весь модуль.
// ------------------------------------------------------------
// Підпис, колір і значок кожного напряму жили в ТРЬОХ місцях: текст
// оверлея в `SwipeCardView`, `title` кнопки-дублера в `SwipeDeck`, колір
// у CSS. Наслідок було видно на екрані: свайп угору казав «Подивились», а
// кнопка під колодою — «Подивились» із іншим значком, тоді як власник
// називає цю дію «Переглянуто». Три копії розходяться завжди; питання
// лише коли.
//
// Тепер опис один, і саме з нього беруть і картка, і кнопки.
//
// Колір — CSS-змінна, а не літерал: він мусить слухатись теми (у світлій
// і темній «зелений» різний), а тема живе в токенах.
// ============================================================
import type { SwipeDirection } from '@/types';

export interface SwipeVerdict {
  direction: SwipeDirection;
  /** Що пара побачить у центрі картки під час жесту. */
  label: string;
  /** Значок кнопки-дублера під колодою. */
  glyph: string;
  /** Токен кольору вердикту. */
  colourVar: string;
}

/**
 * Порядок тут — порядок КНОПОК під колодою, зліва направо, і він
 * повторює розташування самих жестів: «в планах» ліворуч, «пропустити»
 * донизу, «переглянуто» догори, «дивимось» праворуч.
 */
export const SWIPE_VERDICTS: readonly SwipeVerdict[] = [
  { direction: 'left', label: 'В планах', glyph: '🕐', colourVar: '--swipe-want' },
  { direction: 'down', label: 'Пропустити', glyph: '✕', colourVar: '--swipe-skip' },
  // «Переглянуто», а не «Подивились»: так це називає власник, і так само
  // підписана кнопка. Один жест — одна назва.
  { direction: 'up', label: 'Переглянуто', glyph: '✅', colourVar: '--swipe-done' },
  { direction: 'right', label: 'Дивимось', glyph: '▶', colourVar: '--swipe-watching' },
];

export const VERDICT_BY_DIRECTION: Record<SwipeDirection, SwipeVerdict> =
  Object.fromEntries(
    SWIPE_VERDICTS.map((v) => [v.direction, v]),
  ) as Record<SwipeDirection, SwipeVerdict>;
