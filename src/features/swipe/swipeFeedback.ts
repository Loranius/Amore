// ============================================================
// Що саме показує картка, поки палець її тягне.
// ------------------------------------------------------------
// Раніше вердикт був маленькою пігулкою, прибитою до краю картки
// (`top: 20px`, `left: 16px` …), а прозорість рахувалась просто з
// проєкції на вісь. Дві вади, обидві видно на живому екрані:
//
//  1. **Підпис ішов повз погляд.** Пара дивиться на постер — на центр
//     картки, — а вердикт з'являвся вгорі або збоку. Власник назвав це
//     прямо: «текст десь наверху».
//  2. **Діагональ показувала ДВА вердикти одразу.** Прозорості чотирьох
//     оверлеїв рахувались незалежно, тож рух під 45° підсвічував і
//     «вгору», і «вбік» — двома різними кольорами водночас, хоча
//     відпускання пальця дасть рівно один із них.
//
// Тому напрям тут рахується ТАК САМО, як його рахує відпускання
// (`onDragEnd`): та сама перевага вертикалі над горизонталлю. Один рух —
// один вердикт, і той, який справді станеться.
//
// Модуль чистий: ні React, ні DOM. Числа нижче визначають, як швидко
// картка набирає колір, і саме тому вони перевіряються тестом.
// ============================================================
import type { SwipeDirection } from '@/types';

/**
 * Доки рух вважається випадковим тремтінням.
 *
 * Нижче цього порогу вердикт не проступає взагалі. Без мертвої зони
 * картка блимала кольором від кожного дотику — зокрема від тапу, який
 * відкриває деталі й свайпом не є.
 */
export const VERDICT_DEAD_ZONE_PX = 24;

/**
 * Де колір набирає повну силу.
 *
 * Трохи більше за поріг зриву (`OFFSET_T = 80`): коли картка вже майже
 * зірвалась, колір мусить бути повним, а не «майже повним» — інакше
 * найважливіший кадр жесту показує невпевнений відтінок.
 */
export const VERDICT_FULL_PX = 110;

/**
 * Стеля затемнення кольором.
 *
 * Не одиниця: постер має лишатись видимим під заливкою. На 1.0 картка
 * ставала суцільною плямою, і пара переставала бачити, ЩО саме
 * позначає.
 */
export const VERDICT_MAX_TINT = 0.74;

/**
 * Куди піде картка, якщо відпустити просто зараз.
 *
 * `null`, поки рух не вийшов за мертву зону. Перевага вертикалі — та
 * сама, що в `onDragEnd`: інакше підказка обіцяла б одне, а ставалось би
 * інше.
 */
export function activeVerdict(offsetX: number, offsetY: number): SwipeDirection | null {
  const horizontal = Math.abs(offsetX) > Math.abs(offsetY);
  const along = horizontal ? offsetX : offsetY;
  if (Math.abs(along) < VERDICT_DEAD_ZONE_PX) return null;
  if (horizontal) return along < 0 ? 'left' : 'right';
  return along < 0 ? 'up' : 'down';
}

/**
 * Наскільки сильно проступив вердикт `direction`: 0…1.
 *
 * Нуль для всіх напрямів, крім активного, — саме це й прибирає два
 * кольори на діагоналі.
 */
export function verdictProgress(
  offsetX: number,
  offsetY: number,
  direction: SwipeDirection,
): number {
  if (activeVerdict(offsetX, offsetY) !== direction) return 0;
  const horizontal = direction === 'left' || direction === 'right';
  const along = Math.abs(horizontal ? offsetX : offsetY);
  const span = VERDICT_FULL_PX - VERDICT_DEAD_ZONE_PX;
  const raw = (along - VERDICT_DEAD_ZONE_PX) / span;
  return Math.max(0, Math.min(1, raw));
}

/** Прозорість заливки картки для цього напряму. */
export function verdictTint(
  offsetX: number,
  offsetY: number,
  direction: SwipeDirection,
): number {
  return verdictProgress(offsetX, offsetY, direction) * VERDICT_MAX_TINT;
}
