// ============================================================
// Яку зірку зачепив палець.
// ------------------------------------------------------------
// Не промінь крізь геометрію, і це рішення, а не спрощення.
//
// Силует зірки — чотири тонкі промені: рівно та форма, у яку найважче влучити.
// Промінь крізь неї означав би, що дотик спрацьовує на вістрі й не спрацьовує
// за півмілиметра збоку, і пара звинувачувала б себе. Тому зірки проєктуються в
// екранні координати, а вибір іде за найближчою в межах пальця — тієї самої
// сорокачотирипіксельної цілі, яку портал уже тримає для кнопок.
//
// Наслідок, який варто назвати: у дві зірки, що злились у кадрі, палець влучить
// у ближчу до пальця, а не в ближчу до камери. Це чесніше — пара тицяє в те,
// що бачить, а не в те, що попереду за глибиною.
//
// Чиста функція: проєкцію рахує сцена, сюди приїжджають уже плоскі точки.
// ============================================================

export interface ScreenStar {
  id: number;
  /** Пікселі від лівого краю полотна. */
  x: number;
  /** Пікселі від верхнього краю полотна. */
  y: number;
  /** Видимий радіус зірки в пікселях. Більша зірка ловить із більшої відстані. */
  radius: number;
  /** Чи вона взагалі перед камерою. */
  visible: boolean;
}

/**
 * Мінімальна ціль дотику, пікселі.
 *
 * Сорок чотири — та сама межа, що вже стоїть на кнопках порталу. Зірка, дрібніша
 * за це, все одно ловить палець із цієї відстані; більша ловить зі своєї.
 */
export const TOUCH_TARGET = 22;

/**
 * Наскільки далі за власний радіус зірка ще приймає дотик.
 *
 * Один радіус запасу: сяйво навколо зірки пара сприймає як частину зірки, і
 * влучення в нього мусить рахуватись.
 */
const REACH = 2;

export function pickStar(
  stars: readonly ScreenStar[],
  pointer: { x: number; y: number },
): number | null {
  let bestId: number | null = null;
  let bestDistance = Number.POSITIVE_INFINITY;

  for (const star of stars) {
    if (!star.visible) continue;
    const distance = Math.hypot(star.x - pointer.x, star.y - pointer.y);
    const reach = Math.max(TOUCH_TARGET, star.radius * REACH);
    if (distance > reach) continue;
    // Рівні відстані розв'язує менший `id`: без цього вибір між двома зірками,
    // що злились у кадрі, залежав би від порядку в масиві.
    if (distance < bestDistance || (distance === bestDistance && bestId !== null && star.id < bestId)) {
      bestDistance = distance;
      bestId = star.id;
    }
  }

  return bestId;
}
