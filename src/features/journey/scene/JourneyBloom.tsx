import { Bloom, EffectComposer } from '@react-three/postprocessing';

// ============================================================
// Сяйво розкритої події.
// ------------------------------------------------------------
// Окремим файлом і за `React.lazy` — навмисно й за тим самим взірцем, що
// `render/BloomProbe.tsx`: `postprocessing` важить сотні кілобайт, і поки
// сяйво з'являється лише у focus-режимі, воно не має лежати в головному чанку
// кожної пари.
//
// **Поріг тут високий не з обережності, а з виміру.** Скайбокс закриває весь
// кадр, і його туманність місцями світліша за середину; низький поріг підняв
// би саме її, і замість сяйва сонця пара дістала б молочний серпанок на все
// небо. Світитись мають лише осердя зірок і сам диск події.
//
// Прохід іде тільки на сильному профілі. Це не обережність заради обережності:
// `EffectComposer` рендерить сцену у власні таргети розміром з екран і потім
// блітить, тобто повний прохід читання-запису на кожен кадр — рівно те, чого
// слабкому телефону не вистачає найперше.
// ============================================================

export default function JourneyBloom() {
  return (
    // Нормалі тут не потрібні нікому, а прохід коштує; згладжування вже
    // зроблено на самому полотні, тож і другого разу воно не треба.
    <EffectComposer enableNormalPass={false} multisampling={0}>
      <Bloom
        intensity={0.85}
        // Виміряно на живому екрані: туманність скайбокса тримається нижче 0.6
        // яскравості, диск події й осердя зірок — вище.
        luminanceThreshold={0.68}
        luminanceSmoothing={0.22}
        mipmapBlur
      />
    </EffectComposer>
  );
}
