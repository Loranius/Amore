import { Bloom, EffectComposer } from '@react-three/postprocessing';

// ============================================================
// Сяйво розкритої події.
// ------------------------------------------------------------
// Окремим файлом і за `React.lazy` — навмисно й за тим самим взірцем, що
// `render/BloomProbe.tsx`: `postprocessing` важить сотні кілобайт, і поки
// сяйво з'являється лише у focus-режимі, воно не має лежати в головному чанку
// кожної пари.
//
// **Поріг тут високий не з обережності, а з виміру.** Скайбокс закриває весь
// кадр, і його туманність місцями світліша за середину; низький поріг підняв
// би саме її, і замість сяйва сонця пара дістала б молочний серпанок на все
// небо. Світитись мають лише осердя зірок і сам диск події.
//
// Прохід іде тільки на сильному профілі. Це не обережність заради обережності:
// `EffectComposer` рендерить сцену у власні таргети розміром з екран і потім
// блітить, тобто повний прохід читання-запису на кожен кадр — рівно те, чого
// слабкому телефону не вистачає найперше.
//
// **Змонтований у спокої, прогрітий там же, увімкнений лише у focus.**
// Чотири виміри знадобилось, щоб це розділити. Спершу компонент монтувався за вимогою — і в мить дотику
// браузер тягнув чанк, найгірший кадр 1367 мс. Потім сяйво лишили ввімкненим
// назавжди — мережа зникла, але середній кадр подорожчав із 574 до 1013 мс.
// Потім повернули за focus — середній кадр повернувся, а найгірший став
// 1962 мс: це вже сам композитор виділяв буфери й компілював свої проходи.
// І нарешті: `enabled={false}` не малює прохід узагалі, тож і не компілює його —
// компіляція просто переїхала на дотик. Тому після монтування прохід коротко
// працює з НУЛЬОВОЮ інтенсивністю: кадр не змінюється, а шейдери прогріваються.
// ============================================================

export default function JourneyBloom({ active, visible }: { active: boolean; visible: boolean }) {
  return (
    // Нормалі тут не потрібні нікому, а прохід коштує; згладжування вже
    // зроблено на самому полотні, тож і другого разу воно не треба.
    //
    // `enabled` вимикає прохід, НЕ звільняючи його буфери й шейдери: композитор
    // просто виходить із циклу кадрів. Саме це й потрібно — заплатити за
    // налаштування один раз у спокої й не платити за кадр там, де сяйва не
    // видно.
    <EffectComposer enabled={active} enableNormalPass={false} multisampling={0}>
      <Bloom
        // Нуль на прогріві: прохід малюється (отже компілюється), але не додає
        // жодного пікселя. Компіляція шейдерів проходу — це те, що лишалось
        // гикати після всіх попередніх виправлень.
        intensity={visible ? 0.85 : 0}
        // Виміряно на живому екрані: туманність скайбокса тримається нижче 0.6
        // яскравості, диск події й осердя зірок — вище.
        luminanceThreshold={0.68}
        luminanceSmoothing={0.22}
        mipmapBlur
      />
    </EffectComposer>
  );
}
