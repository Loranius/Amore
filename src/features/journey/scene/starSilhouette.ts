import { Shape } from 'three';

// ============================================================
// Силует зірки події.
// ------------------------------------------------------------
// Чотирипроменева зірка з тонкими перемичками — форма з моделей, які передав
// власник: висота 1.7024, ширина 1.52, внутрішні кути рівно на 42.93 і 57.07
// відсотка кадру. Ці числа не підібрані на око, вони зняті з самих моделей, і
// саме тому лежать тут виписаними, а не десь у розмітці шейдера.
//
// Форма плоска й повертається лицем до камери щокадру. Об'ємної зірки тут
// свідомо немає: на будь-якому ракурсі гострі промені мають лишатись гострими,
// а справжня тривимірна зірка з половини ракурсів показує ребро.
// ============================================================

/** Пропорції вихідної моделі, одиниці. */
const MODEL_WIDTH = 1.52;
const MODEL_HEIGHT = 1.7024;
/** Де сходяться промені — частка кадру від краю. */
const WAIST = 0.0707; // 0.5 − 0.4293

/** Ширина зірки при висоті 1. Вона ж `aspect-ratio` вихідної моделі. */
export const STAR_ASPECT = MODEL_WIDTH / MODEL_HEIGHT;

/**
 * Вісім вершин у координатах із центром у нулі, де верхній промінь сягає 1.
 *
 * Порядок обходу — проти годинникової стрілки від правого променя, щоб
 * трикутники дивились на камеру без вивертання.
 */
export const STAR_POINTS: ReadonlyArray<readonly [number, number]> = (() => {
  const halfWidth = STAR_ASPECT / 2;
  const waistX = (WAIST / 0.5) * halfWidth;
  const waistY = WAIST / 0.5;
  return [
    [halfWidth, 0],
    [waistX, waistY],
    [0, 1],
    [-waistX, waistY],
    [-halfWidth, 0],
    [-waistX, -waistY],
    [0, -1],
    [waistX, -waistY],
  ];
})();

export function createStarShape(): Shape {
  const shape = new Shape();
  const [first, ...rest] = STAR_POINTS;
  shape.moveTo(first![0], first![1]);
  for (const [x, y] of rest) shape.lineTo(x, y);
  shape.closePath();
  return shape;
}
