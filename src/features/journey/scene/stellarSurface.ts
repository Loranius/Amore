// ============================================================
// Поверхня зорі — процедурна, а не запечена.
// ------------------------------------------------------------
// `sun.glb` приїхав із текстурою 1024×512 на шістнадцять кольорів і БЕЗ
// emissive узагалі — це виміряно в самому контейнері, а не припущено. Вона
// працювала яскравістю, і цього вистачало рівно доти, доки власник не назвав
// ваду: «зірки — прості світні кульки».
//
// Запечена текстура не може зробити те, чого він просить, і це не питання
// роздільності. Вона НЕРУХОМА: гранули не течуть, плями не з'являються, зони
// яскравості не дихають. Куля з нею читається як картинка кулі. Тому тут шум,
// а не вибірка: чотири октави тривимірного значеннєвого шуму в ОБ'ЄКТНОМУ
// просторі сфери, дві швидкості течії, плями поверх, Fresnel по краю.
//
// Об'єктний простір, а не екранний, важливий: візерунок мусить обертатись
// РАЗОМ із тілом, інакше сонце виглядає як куля, за якою хтось крутить
// шпалери.
//
// **Насіння входить зсувом координати, а не множником.** Множник змінював би
// масштаб гранул, тобто одна подія мала б дрібнішу поверхню за іншу без
// жодної на те причини; зсув дає інший шматок того самого нескінченного поля.
//
// Ціна названа чесно: це найдорожчий фрагментний шейдер у застосунку. Тому LOD
// тут ДВОРІВНЕВИЙ.
//
//  1. **За розміром.** Повна поверхня працює рівно на одній кулі — на
//     розкритій події. Оглядові зірки лишаються плоскими силуетами з дешевим
//     мерехтінням (`JourneyConstellation`): двадцять пікселів більшого не
//     покажуть.
//  2. **За профілем пристрою.** Повний варіант рахує три поля шуму по чотири
//     октави — це 96 звернень до хеша на фрагмент, і на слабкому телефоні,
//     де сонце й так займає третину екрана, це найдорожче, що є в сцені.
//     Полегшений варіант бере дві октави й виводить плями з уже порахованого
//     поля зон: 24 звернення замість 96, тобто вчетверо дешевше. Візерунок
//     стає грубшим, але лишається тим самим візерунком — це не інша поверхня.
// ============================================================

export const STELLAR_VERTEX = /* glsl */ `
  varying vec3 vLocal;
  varying vec3 vNormal;
  varying vec3 vView;
  void main() {
    // Об'єктний простір: візерунок належить тілу й обертається з ним.
    vLocal = position;
    vNormal = normalize(normalMatrix * normal);
    vec4 viewPosition = modelViewMatrix * vec4(position, 1.0);
    vView = normalize(-viewPosition.xyz);
    gl_Position = projectionMatrix * viewPosition;
  }
`;

/** Наскільки докладно рахувати поверхню. Вибирає профіль пристрою. */
export type StellarDetail = 'full' | 'lite';

const OCTAVES: Record<StellarDetail, number> = { full: 4, lite: 2 };

function fragmentSource(detail: StellarDetail): string {
  const octaves = OCTAVES[detail];
  // Плями на полегшеному профілі виводяться з уже порахованого поля зон, а не
  // з власного: третій прохід шуму — рівно третина всієї ціни шейдера.
  const spotField = detail === 'full'
    ? 'fbm(surface * 3.2 + vec3(uTime * 0.011, uTime * 0.019, 0.0))'
    : 'zones';
  return /* glsl */ `
  uniform vec3 uColour;
  uniform float uOpacity;
  uniform float uTime;
  uniform vec3 uSeed;
  uniform float uSpots;
  uniform float uRim;
  varying vec3 vLocal;
  varying vec3 vNormal;
  varying vec3 vView;

  float hash31(vec3 p) {
    p = fract(p * 0.3183099 + vec3(0.11, 0.17, 0.13));
    p *= 17.0;
    return fract(p.x * p.y * p.z * (p.x + p.y + p.z));
  }

  float noise3(vec3 x) {
    vec3 i = floor(x);
    vec3 f = fract(x);
    f = f * f * (3.0 - 2.0 * f);
    return mix(
      mix(
        mix(hash31(i + vec3(0.0, 0.0, 0.0)), hash31(i + vec3(1.0, 0.0, 0.0)), f.x),
        mix(hash31(i + vec3(0.0, 1.0, 0.0)), hash31(i + vec3(1.0, 1.0, 0.0)), f.x),
        f.y
      ),
      mix(
        mix(hash31(i + vec3(0.0, 0.0, 1.0)), hash31(i + vec3(1.0, 0.0, 1.0)), f.x),
        mix(hash31(i + vec3(0.0, 1.0, 1.0)), hash31(i + vec3(1.0, 1.0, 1.0)), f.x),
        f.y
      ),
      f.z
    );
  }

  float fbm(vec3 p) {
    float amplitude = 0.5;
    float total = 0.0;
    for (int octave = 0; octave < ${octaves}; octave += 1) {
      total += amplitude * noise3(p);
      p *= 2.03;
      amplitude *= 0.5;
    }
    return total;
  }

  void main() {
    vec3 surface = normalize(vLocal) + uSeed;

    // Дві швидкості течії. Одна повільна — вона рухає великі зони яскравості;
    // друга вдвічі швидша й дрібніша — це самі гранули. Одна швидкість дає
    // рівне «повзання» шпалер, дві дають кипіння.
    float zones = fbm(surface * 2.1 + vec3(0.0, uTime * 0.035, uTime * 0.017));
    float grain = fbm(surface * 6.4 + vec3(uTime * 0.09, 0.0, uTime * 0.06));

    // Плями — темніші ділянки, які повільно наростають і зникають. Поріг
    // м'який: різкий дав би дірки з рівним краєм, тобто наліпки, а не пляму.
    float spotField = ${spotField};
    float spot = smoothstep(0.52, 0.78, spotField) * uSpots;

    // Поля шуму входять ВІДЦЕНТРОВАНІ, і це виміряно, а не виведено.
    //
    // Перша редакція складала їх як є: 0.52 + zones*0.62 + grain*0.36.
    // Значеннєвий шум має середнє 0.5, тож середина поверхні виходила рівно на
    // одиниці — і на живому екрані сонце було суцільно білим диском, на якому
    // не читалось нічого, крім кількох плям. Тепер середнє задає перший
    // доданок, а шум лише хитає його в обидва боки.
    float brightness = 0.55 + (zones - 0.5) * 0.85 + (grain - 0.5) * 0.45 - spot * 0.38;
    brightness = clamp(brightness, 0.1, 1.0);

    // Гарячіші ділянки біліші — так поводиться будь-яке розжарене тіло. Це не
    // домішування білого «для краси»: без зсуву температури поверхня читається
    // як пофарбована, а не як така, що світиться.
    //
    // Яскравість входить РІВНО ОДИН раз — як частка змішування між тінню й
    // жаром. Перша редакція множила на неї ще й результат, тобто двічі, і на
    // живому екрані золоте сонце вийшло сірувато-бежевим місяцем: середина
    // поверхні падала до 0.45 від власного кольору, і тон разом із нею.
    //
    // Частка білого в жарі стримана — 0.25, а не половина. Причина в
    // тонмапінгу: полотно йде через ACES, а він гасить насиченість саме у
    // світлих значеннях. Виміряно на живому екрані: із часткою 0.45 золоте
    // сонце виходило вершковим, майже без тону.
    vec3 cool = uColour * 0.38;
    vec3 hot = mix(uColour, vec3(1.0), 0.25);
    vec3 body = mix(cool, hot, brightness);

    // Край яскравіший за середину — так світиться тіло, у якого світло йде
    // зсередини, і саме цього бракує рівній кулі. Він же дає сяйву за що
    // зачепитись: поріг проходу — 0.68, і саме край його переходить першим.
    float rim = pow(1.0 - clamp(dot(normalize(vNormal), normalize(vView)), 0.0, 1.0), 2.0);

    vec3 colour = body + uColour * rim * uRim;
    gl_FragColor = vec4(colour, uOpacity);
  }
`;
}

/**
 * Тексти шейдера на обидва профілі, побудовані раз.
 *
 * Раз, а не на кожен матеріал: рядок шейдера — ключ, за яким three вирішує,
 * чи компілювати програму заново. Новий рядок на кожен показ події означав би
 * нову компіляцію на кожен дотик, тобто рівно той ривок, який ми вже чотири
 * рази виганяли з цієї сцени.
 */
export const STELLAR_FRAGMENT: Record<StellarDetail, string> = {
  full: fragmentSource('full'),
  lite: fragmentSource('lite'),
};

/** Скільки додає світний край понад тіло. */
export const RIM_GAIN = 0.85;

/**
 * Насіння зорі в три координати зсуву й силу плям.
 *
 * Три числа з одного — свідомо: окремі хеші на кожну вісь коштували б трьох
 * викликів там, де вистачає розкидання одного значення по колу. Множники
 * взаємно прості, тож зсуви не збігаються ні для якого насіння.
 */
export function stellarSignature(seed: number): { offset: [number, number, number]; spots: number } {
  return {
    offset: [seed * 37.13, seed * 61.7, seed * 91.31],
    // Від 0.5 до 1.0: поверхня без плям узагалі виглядає штучно рівною, а
    // суцільно плямиста — брудною.
    spots: 0.5 + seed * 0.5,
  };
}

/** Назви уніформ, які читає шейдер — рівно ті, що має віддати фабрика. */
export function declaredUniforms(): string[] {
  const names = new Set<string>();
  for (const source of [STELLAR_VERTEX, STELLAR_FRAGMENT.full, STELLAR_FRAGMENT.lite]) {
    for (const match of source.matchAll(/uniform\s+\w+\s+(\w+)\s*;/g)) names.add(match[1]!);
  }
  return [...names].sort();
}
