import { stableHash32 } from '@/engine/evolution/seed';
import type { ConstellationLevel } from './constellationRules';

// ============================================================
// Сусіднє небо — місце для чужих сузір'їв, і межа, за яку вони не заходять.
// ============================================================
// Власник просить, щоб пара колись побачила вдалині сузір'я інших пар: не як
// список друзів, а як відчуття, що небо не порожнє. Реалізації тут ще немає —
// є форма даних і контракт компонента, і обидва написані ЗАРАЗ, поки ніхто не
// почав писати запит до бази.
//
// **Це і є вся суть файлу.** Найдешевший спосіб зробити такий шар — узяти
// готовий `ConstellationEvent[]` сусідів і намалювати його тим самим кодом.
// Це і найгірший: у ньому лежать `id`, дати й вага подій, тобто хронологія
// чужих стосунків із точністю до дня. Через кадр із сузір'ям сусідів можна
// було б прочитати, коли вони одружились і скільки в них важливих подій.
//
// Тому `NeighbourSky` НЕ здатний нести особисте — не «не несе», а не здатний:
// у ньому немає жодного поля, куди його можна покласти. Ані назв, ані текстів,
// ані фото, ані дат, ані `id` подій. Лише кількість зірок, розподіл за
// рівнями, протяжність у роках і насіння розкладки — рівно те, з чого
// малюється абстрактний силует на далекому плані.
//
// Тест поруч перевіряє саме це, і він не про поведінку: він перевіряє, що
// форма лишилась вузькою. Якщо колись сюди додадуть `title`, він упаде — і це
// його єдина робота.
// ============================================================

/**
 * Абстрактний силует сузір'я іншої пари.
 *
 * Кожне поле тут — число або перелічуване значення. Рядків немає взагалі, і
 * це не збіг: рядок — найкоротший шлях, яким особисте потрапляє в кадр.
 */
export interface NeighbourSky {
  /**
   * Насіння розкладки.
   *
   * Не `id` пари й не будь-що, що можна повернути назад до людей: сюди йде
   * НЕЗВОРОТНИЙ хеш, і сусід лишається впізнаваним лише як «те саме сузір'я,
   * що й учора».
   */
  seed: number;
  /** Скільки зірок у чужому небі. */
  size: number;
  /** Скільки років охоплює їхній шлях. Роки, не дати. */
  years: number;
  /** Скільки зірок кожного рівня. Суму дає `size`. */
  levels: Record<ConstellationLevel, number>;
}

/**
 * Стеля розміру сусіднього сузір'я.
 *
 * Не оптимізація. Точна кількість подій — це теж відомість про пару, і
 * «у них 147 подій» каже про них більше, ніж хотілося б віддати. Понад стелю
 * всі сузір'я виглядають однаково великими.
 */
export const NEIGHBOUR_MAX_STARS = 60;

/** Так само зі стажем: понад це всі шляхи однаково довгі. */
export const NEIGHBOUR_MAX_YEARS = 25;

export interface NeighbourSource {
  /** Що завгодно стабільне й неособисте — з нього робиться незворотне насіння. */
  key: string;
  /** Скільки зірок кожного рівня. */
  levels: Record<ConstellationLevel, number>;
  /** Скільки років охоплює шлях. */
  years: number;
}

/**
 * Будує силует із того, що дозволено взяти.
 *
 * Приймає РІВНО дозволене, а не подієвий масив із фільтром усередині: фільтр
 * усередині означав би, що особисте вже перетнуло межу модуля й було відкинуте
 * — а відкинути можна забути. Сюди воно просто не заходить.
 */
export function neighbourSky(source: NeighbourSource): NeighbourSky {
  const clamp = (value: number, ceiling: number) => Math.max(
    0,
    Math.min(ceiling, Math.round(Number.isFinite(value) ? value : 0)),
  );

  const levels: Record<ConstellationLevel, number> = {
    key: clamp(source.levels.key, NEIGHBOUR_MAX_STARS),
    important: clamp(source.levels.important, NEIGHBOUR_MAX_STARS),
    regular: clamp(source.levels.regular, NEIGHBOUR_MAX_STARS),
  };
  const size = Math.min(
    NEIGHBOUR_MAX_STARS,
    levels.key + levels.important + levels.regular,
  );

  return {
    // Хеш, а не сам ключ: назад до пари з нього не дійти, а стабільність
    // лишається — те саме небо на будь-якому пристрої й завтра.
    seed: stableHash32(`neighbour:${source.key}`) / 4294967296,
    size,
    years: Math.max(0, Math.min(NEIGHBOUR_MAX_YEARS, source.years)),
    levels,
  };
}

/**
 * Контракт компонента далекого плану.
 *
 * Компонента ще немає. Але коли він з'явиться, він дістане САМЕ це і нічого
 * більше — і жоден дотик по ньому не веде нікуди: сусіднє небо не клікабельне,
 * бо клік означав би «показати чуже», а показувати там нічого.
 */
export interface NeighbourSkyLayerProps {
  /** Кого показати вдалині. Порожній масив — небо без сусідів. */
  skies: readonly NeighbourSky[];
  /** Наскільки далеко за власним сузір'ям, в одиницях сцени. */
  distance: number;
  /** Пара просила спокою — сусіди стоять. */
  reducedMotion: boolean;
}
