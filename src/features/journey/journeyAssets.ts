// саме це.
//
// Порівняно три варіанти на однаковому застиглому кадрі: PNG 8.51 МБ, WebP q92
// 1.61 МБ, WebP q80 0.71 МБ. Колір помітно бідніє вже на q92. WebP без втрат
// важить 7.98 МБ, тобто не виграє нічого.
//
// Зменшувати роздільність не можна тим паче: на 1536 px точкові зірки
