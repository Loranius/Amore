import { describe, expect, it } from 'vitest';
import { partWord } from './SweepSpecies';

// ============================================================
// Число частин артефакта — і слово поруч із ним.
// ------------------------------------------------------------
// Обидва вже коштували вади. Смуга років писала «4 роки разом» парі,
// яка разом три роки й вісім місяців (ADR-0077), і перша редакція
// цього екрана повторила б те саме — тому рядок каже про ЧАСТИНИ, а не
// про роки: частин справді стільки, скільки років, включно з поточним.
//
// А слово поруч робить різницю між «4 частини» і «4 частин»: друге
// читається як машинний переклад, і саме таких дрібниць у порталі
// найбільше видно.
// ============================================================

describe('слово «частина» узгоджується з числом', () => {
  it.each([
    [1, 'частина'],
    [2, 'частини'],
    [3, 'частини'],
    [4, 'частини'],
    [5, 'частин'],
    [11, 'частин'],
    [12, 'частин'],
    [14, 'частин'],
    [21, 'частина'],
    [22, 'частини'],
    [25, 'частин'],
    [101, 'частина'],
  ])('%i — «%s»', (count, word) => {
    expect(partWord(count)).toBe(word);
  });

  it('одинадцять–чотирнадцять — виняток, а не правило', () => {
    /*
     * Найчастіша помилка в українських лічильниках: 11 і 21 закінчуються
     * однаково, але 11 — це «частин», а 21 — «частина». Пара, яка разом
     * одинадцять років, побачила б саме цей випадок.
     */
    expect(partWord(11)).not.toBe(partWord(21));
  });
});
