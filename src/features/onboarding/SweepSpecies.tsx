// ============================================================
// «У чому ви хочете, щоб це росло?» — вибір виду в кінці проходу.
// ------------------------------------------------------------
// ЧОМУ САМЕ В КІНЦІ. Рішення власника: вибирати вид треба «на своїй
// історії», а не на порожньому екрані з трьома картинками. Тут це не
// метафора: сцена стоїть ПОЗАДУ сторінки модуля (`worldDim.css`), тож
// дотик по виду перемальовує справжній артефакт пари з їхніми
// справжніми роками — тими самими, які щойно заповнювали вище.
//
// ЧОМУ ПЕРЕМИКАЧ ТОЙ САМИЙ. `HomeArtifactSwitcher` уже вміє ці три
// варіанти, знає, що риф ще в розробці, і має ролі вкладок. Другий
// такий самий віджет розійшовся б із першим тихо — рівно так, як
// розійшлись би два запити портальних джерел (ADR-0077) чи дві копії
// правил геокодера (ADR-0079).
//
// ЧОМУ ЖОДНОГО НОВОГО СТАНУ. Вибір живе в `ArtifactWorldProvider` і
// переживає маршрут (ADR-0020). Якби прохід зберігав його СВОЇМ ключем,
// пара, яка обрала дерево тут, повернулась би на головну до кристала.
// ============================================================
import { HomeArtifactSwitcher } from '@/features/home/HomeArtifactSwitcher';
import { HOME_ARTIFACT_LABELS, type HomeArtifact } from '@/features/home/homeArtifact';
import { useArtifactWorld } from '@/features/world/artifactWorldContext';
import { plural } from '@/lib/plural';

/**
 * Чим види РІЗНЯТЬСЯ, одним рядком кожен.
 *
 * Спільне сказано окремо й один раз: рік стає одиницею в будь-якому з
 * них (виміряно — 4 роки дають 4, 12 років дають 12). Тому тут лише те,
 * що справді відрізняється: як ці одиниці стоять разом.
 */
const SHAPE: Readonly<Record<HomeArtifact, string>> = {
  crystal: 'Роки стають окремими кристалами й сідають кільцями навколо головного.',
  tree: 'Роки стають гілками одного стовбура — знизу вгору, від першого до цьогорічного.',
  reef: 'Роки стають колоніями коралів навколо спільної голови рифу.',
};

interface SweepSpeciesProps {
  /** Скільки років уже має пара — те саме число, що й у смузі. */
  yearCount: number;
}

export function SweepSpecies({ yearCount }: SweepSpeciesProps) {
  const { artifact, selectArtifact } = useArtifactWorld();

  return (
    <section className="sweep-step">
      <h2 className="sweep-question">У чому ви хочете, щоб це росло?</h2>
      <p className="sweep-hint">
        {/*
          * НЕ «у вас N років». Смуга вище навмисно каже «3 роки позаду ·
          * іде 4-й», бо рік, який триває, ще не прожитий, — і перша
          * редакція цього рядка приписала б парі зайвий рік рівно так,
          * як це вже робила смуга (ADR-0077). Частин справді N: рушій
          * робить одиницю на кожен рік, включно з поточним.
          */}
        {yearCount > 0
          ? `У вашій історії ${yearCount} ${partWord(yearCount)} — по одній на кожен рік,
             разом із тим, що триває зараз. Кожна буде окремою, хай який вид ви оберете;
             різниця в тому, як вони стоять разом.`
          : `Кожен ваш рік стане окремою частиною артефакта — хай який вид ви оберете.
             Різниця в тому, як вони стоять разом.`}
      </p>

      <HomeArtifactSwitcher value={artifact} onChange={selectArtifact} />

      <p className="sweep-said">
        <strong>{HOME_ARTIFACT_LABELS[artifact]}.</strong> {SHAPE[artifact]}
        {artifact === 'reef' && ' Риф ще в розробці — його форма змінюватиметься.'}
      </p>

      <p className="sweep-hint">
        {/*
          * Сказано прямо, бо інакше вибір читався б як остаточний і
          * страшний. Він не остаточний: той самий перемикач стоїть на
          * головній, і історія від зміни виду не зникає — вона в
          * порталі, а не в артефакті.
          */}
        Вибрати можна будь-коли — цей самий перемикач є на головній. Історія від
        цього не змінюється: вона лежить у порталі, а артефакт лише читає її.
      </p>
    </section>
  );
}

/** «частина / частини / частин» — правило спільне, слова свої. */
export const partWord = (count: number) => plural(count, 'частина', 'частини', 'частин');
