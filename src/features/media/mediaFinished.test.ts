import { describe, expect, it } from 'vitest';
import { nextFinishedAt } from './mediaConstants';

// ============================================================
// Дата завершення: коли ставити, коли скидати й коли НЕ чіпати.
// ------------------------------------------------------------
// Колонка з'явилась 2026-09-01 (ADR-0080), і до неї рушій датував
// переглянуте днем створення рядка — через що всі 194 позиції власника
// лежали в одному році стосунків. Тепер дата щось означає, і саме тому
// правило, за яким вона змінюється, більше не можна тримати в голові.
// ============================================================

const NOW = '2026-09-01T12:00:00.000Z';
const now = () => NOW;

describe('дата завершення змінюється разом зі статусом', () => {
  it('щойно стало «переглянуто» — дата це мить натискання', () => {
    expect(nextFinishedAt('done', null, now)).toBe(NOW);
  });

  it('уже переглянуто й дата є — НЕ чіпаємо', () => {
    /*
     * Перша редакція ставила `new Date()` щоразу, коли статус лишався
     * `done`. Тобто виправлення друкарської помилки в назві переносило
     * перегляд 2024 року на сьогодні — тихо, без жодного натяку на
     * екрані. `PRODUCT.md`: минуле не переписується.
     */
    expect(nextFinishedAt('done', '2024-03-11T20:15:00.000Z', now))
      .toBe('2024-03-11T20:15:00.000Z');
  });

  it.each(['want', 'watching', 'dropped'] as const)('статус «%s» скидає дату', (status) => {
    /*
     * Скидання не косметика. Адаптер читає лише рядки в `done`, тож
     * застаріла дата на кинутому серіалі рушієві не завадила б — але
     * колонка почала б означати «колись була done», і наступний читач
     * повірив би підпису.
     */
    expect(nextFinishedAt(status, '2024-03-11T20:15:00.000Z', now)).toBeNull();
  });
});
