// ============================================================
// Спільний підпис дати.
// ------------------------------------------------------------
// Інваріант, який тут стережеться: дата — календарний факт, а не мить у
// часі. Той самий рядок мусить дати той самий підпис у будь-якому
// часовому поясі. Цей клас багів уже кусав календар («22 травня» ставало
// «21 травня» в Нью-Йорку), тому регресія на пояси тут обов'язкова.
// ============================================================
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { formatDateUA } from './month';

const originalTZ = process.env.TZ;
beforeEach(() => { process.env.TZ = 'Europe/Kyiv'; });
afterEach(() => { process.env.TZ = originalTZ; });

describe('formatDateUA', () => {
  it('підписує родовим відмінком, як у живій мові', () => {
    expect(formatDateUA('2026-07-14')).toBe('14 липня 2026');
    expect(formatDateUA('2024-05-01')).toBe('1 травня 2024');
  });

  it('без року — короткий підпис для картки', () => {
    expect(formatDateUA('2026-07-14', { year: false })).toBe('14 липня');
  });

  it('день без провідного нуля', () => {
    // «01 травня» в підписі виглядає як машинний вивід, а не як дата.
    expect(formatDateUA('2024-05-01')).toBe('1 травня 2024');
  });

  it.each(['Europe/Kyiv', 'America/New_York', 'America/Los_Angeles', 'Pacific/Kiritimati'])(
    'не залежить від часового поясу (%s)',
    (tz) => {
      process.env.TZ = tz;
      expect(formatDateUA('2022-05-22')).toBe('22 травня 2022');
      expect(formatDateUA('2026-01-01')).toBe('1 січня 2026');
    },
  );

  it('приймає повний timestamp, беручи з нього лише дату', () => {
    expect(formatDateUA('2026-07-14T20:41:00Z')).toBe('14 липня 2026');
  });

  it('порожній чи несправний рядок дає порожній підпис, а не «Invalid Date»', () => {
    // Картка місця без дати мусить просто не показати рядок дати.
    for (const bad of ['', 'не дата', '2026-13-01', '2026-02-30', '2026-00-10']) {
      expect(formatDateUA(bad)).toBe('');
    }
  });

  it('29 лютого існує лише у високосному році', () => {
    expect(formatDateUA('2024-02-29')).toBe('29 лютого 2024');
    expect(formatDateUA('2025-02-29')).toBe('');
  });
});
