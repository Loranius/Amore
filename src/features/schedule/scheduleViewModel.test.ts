import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { fmtLongDate, nextMark, statusText } from './scheduleViewModel';

// ============================================================
// Тести вигляду «Графіка» (ADR-0208, варіант A).
// Кожен називає інваріант, який перевіряє (.claude/rules/tests.md).
// ============================================================

describe('nextMark — що робить дотик по дню', () => {
  it('порожній день стає ВИХІДНИМ', () => {
    // Позначати варто те, заради чого сюди заходять.
    expect(nextMark('')).toBe('Х');
  });

  it('між роботою й вихідним — чистий перемикач', () => {
    expect(nextMark('Х')).toBe('Р');
    expect(nextMark('Р')).toBe('Х');
  });

  it('перемикач САМ СОБІ скасування', () => {
    /*
     * Головний інваріант варіанта A: режим правки прибрано, тож від
     * випадкового дотику рятує не модальність, а зворотність. Для обох
     * заповнених станів другий дотик повертає перший.
     */
    expect(nextMark(nextMark('Х'))).toBe('Х');
    expect(nextMark(nextMark('Р'))).toBe('Р');
  });

  it('порожнє — названий виняток, а не недогляд', () => {
    /*
     * `'' → Х → Р`, тобто до порожнього дотиком не повернутись. Це
     * свідомо: у базі пари 184 мітки за три місяці й ЖОДНОГО порожнього
     * дня, а очищення живе в пакетних інструментах.
     */
    expect(nextMark(nextMark(''))).not.toBe('');
  });
});

describe('fmtLongDate — день тижня в називному відмінку', () => {
  /*
   * ВАДА, ЯКОЇ ЦЕЙ ТЕСТ ПОБАЧИТИ НЕ МОЖЕ, і тому він дивиться в ТЕКСТ.
   *
   * Один виклик `toLocaleDateString` із днем тижня у складі дати дає
   * різне в різних ICU — виміряно обома:
   *
   *   Chromium : «неділю, 20 вересня» · «суботу, 26 вересня»
   *   Node     : «неділя, 20 вересня» · «субота, 26 вересня»
   *
   * Пара бачить браузер, а цей набір іде на Node. Тобто перевірка
   * результату тут зелена і до, і після виправлення — вона не доводить
   * нічого. Доводить інше: що день тижня форматується ОКРЕМИМ викликом,
   * бо саме самостійна форма дає називний і в Chromium.
   */
  const source = readFileSync(join(__dirname, 'scheduleViewModel.ts'), 'utf8');
  const body = source.slice(source.indexOf('export function fmtLongDate'));
  const fn = body.slice(0, body.indexOf('\n}') + 2);

  it('день тижня форматується окремо від числа й місяця', () => {
    expect(fn).toContain("{ weekday: 'long' }");
    expect(fn).toContain("{ day: 'numeric', month: 'long' }");
  });

  it('жоден виклик не просить день тижня РАЗОМ із числом', () => {
    // Саме це поєднання і вмикає в ICU форму «у неділю».
    expect(fn).not.toMatch(/weekday:[^}]*day:/);
  });

  it('сторож дивиться в потрібне місце', () => {
    // Без цього дві перевірки вище зелені й на порожньому рядку.
    expect(fn.length).toBeGreaterThan(80);
    expect(fn).toContain('toLocaleDateString');
  });

  it('формат лишається «день тижня, число місяць»', () => {
    // На Node форма й так називна, тож це перевірка СКЛАДУ, не відмінка.
    expect(fmtLongDate('2026-09-24')).toBe('четвер, 24 вересня');
  });
});

describe('statusText — імена пари, без роду й відмінка (ADR-0209)', () => {
  /*
   * ВИМОГА. Рядок про день називає людей так, як їх зовуть у `users`, і не
   * узгоджується ні в роді, ні у відмінку — бо з рядка `users.name` рід не
   * виводиться, а вгадувати його означало б звертатись до пари неправильно
   * її ж іменем.
   *
   * ВАДА, ЗА ФАКТОМ ЯКОЇ НАПИСАНО: тут стояло «Лєна вільна, Діма працює» —
   * два зашитих імені й два узгоджених прикметники. Зареєстрована пара
   * прочитала б на своєму екрані чужі імена.
   */
  const pair = { lena: 'Лєна', dima: 'Діма' };

  it('спільний вихідний не називає нікого — і не мусить', () => {
    expect(statusText('both-off', pair)).toBe('Ви обоє вільні');
  });

  it('називає того, хто відпочиває, і того, хто працює', () => {
    expect(statusText('lena-off', pair)).toBe('Тільки Лєна відпочиває, Діма працює');
    expect(statusText('dima-off', pair)).toBe('Тільки Діма відпочиває, Лєна працює');
  });

  it('працює для будь-яких імен, бо не узгоджується', () => {
    // Саме це було неможливо з прикметником: «Олексій вільна» або
    // «Marie вільний» — і жодна підстановка цього не лікує.
    const other = { lena: 'Marie', dima: 'Олексій' };
    expect(statusText('lena-off', other)).toBe('Тільки Marie відпочиває, Олексій працює');
    expect(statusText('dima-off', other)).toBe('Тільки Олексій відпочиває, Marie працює');
  });

  it('без списку користувачів не вигадує імені', () => {
    const empty = { lena: undefined, dima: undefined };
    expect(statusText('lena-off', empty)).toBe('Вільний лише один із вас');
    expect(statusText('none', empty)).toBe('Спільного вихідного немає');
  });
});

describe('слот доріжки визначає ПОРЯДОК, і порядок цієї пари не переставлено (ADR-0209)', () => {
  /*
   * ВАДА, ЗА ФАКТОМ ЯКОЇ НАПИСАНО, І ВОНА МАЙЖЕ ВІДПРАВИЛАСЬ. Пошук члена
   * пари за іменем (`users.find((u) => u.name === 'Лєна')`) замінено на
   * порядок — і перша редакція написала `const [lena, dima] = users`, бо
   * так підказував алфавіт. У базі ж **id 1 — Діма, id 2 — Лєна**
   * (перевірено запитом), тож ця редакція поміняла б місцями обидві
   * доріжки Й обидва підписи на живому екрані власника.
   *
   * Типізація тут згодна на будь-який порядок: обидва — `AppUser`. Тому
   * перевірка дивиться в ТЕКСТ сторінки: перший член пари мусить лягати в
   * слот `dima` (`--him`), другий — у `lena` (`--her`).
   */
  /*
   * КОМЕНТАРІ ЗНІМАЮТЬСЯ, І ЦЕ ВИМОГА, А НЕ ЗРУЧНІСТЬ. Перша редакція цього
   * сторожа впала на власному пояснювальному коментарі в `SchedulePage`,
   * бо той ЦИТУЄ ваду дослівно. Сторож, який не вміє відрізнити код від
   * розповіді про код, забороняє описувати правило там, де воно живе. Той
   * самий прийом і з тієї ж причини стоїть у `noLocaleCompare.test.ts`.
   */
  const page = readFileSync(join(__dirname, 'SchedulePage.tsx'), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, (match) => match.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (_match, lead: string) => lead);

  it('розбір масиву називає позиції, а не імена', () => {
    expect(page).toContain('const [firstMember, secondMember] = users;');
    // Саме цей рядок і був вадою.
    expect(page).not.toContain('const [lena, dima] = users');
  });

  it('перший за порядком лягає в слот him, другий — у her', () => {
    expect(page).toMatch(/const dima = firstMember;/);
    expect(page).toMatch(/const lena = secondMember;/);
  });

  it('за іменем члена пари більше не шукають', () => {
    expect(page).not.toMatch(/name === '(Лєна|Діма)'/);
  });

  it('сторож справді дивиться в потрібний файл', () => {
    // Без цього три перевірки вище зелені й на порожньому рядку.
    expect(page).toContain('secondMember');
    expect(page.length).toBeGreaterThan(2000);
  });
});
