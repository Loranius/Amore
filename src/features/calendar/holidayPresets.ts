// ============================================================
// Типові свята — заготовки для порожньої вкладки «🎉 Свята».
// ------------------------------------------------------------
// Вкладка існувала з першого дня модуля й не набрала жодної події: щоб
// побачити в застосунку Новий рік, його треба було завести вручну, як
// власну річницю. Заготовки прибирають цю роботу.
//
// ВАЖЛИВО: список пропонується, а не встановлюється. Кілька дат
// переїхали з календарною реформою 2023 року (Різдво, День захисників і
// захисниць, День Святого Миколая), тож екран показує кожну дату поруч
// із назвою й дає зняти галочку до запису. Помилитись у чужому
// календарі мовчки — гірше, ніж не запропонувати нічого.
// ============================================================
import { ymd } from '@/features/_shared/month';
import { localDateFromISO } from '@/lib/utils';
import type { EventRow } from '@/types';

export interface HolidayPreset {
  /** 'MM-DD' — свято щорічне, рік підставляється при додаванні. */
  md: string;
  title: string;
}

/**
 * Лише свята з ФІКСОВАНОЮ датою.
 *
 * Великдень, Трійця й День матері рухомі: перші два рахуються від
 * пасхалії, третій — «друга неділя травня». Підставити їм сталу дату
 * означало б записати в календар пари неправду, тож їх тут немає.
 */
export const HOLIDAY_PRESETS: readonly HolidayPreset[] = [
  { md: '01-01', title: 'Новий рік' },
  { md: '02-14', title: 'День закоханих' },
  { md: '03-08', title: 'Міжнародний жіночий день' },
  { md: '05-08', title: 'День памʼяті та перемоги над нацизмом' },
  { md: '06-28', title: 'День Конституції України' },
  { md: '07-28', title: 'День Української Державності' },
  { md: '08-24', title: 'День Незалежності України' },
  { md: '10-01', title: 'День захисників і захисниць України' },
  { md: '12-06', title: 'День Святого Миколая' },
  { md: '12-25', title: 'Різдво Христове' },
];

/**
 * Дата найближчого настання свята — 'YYYY-MM-DD'.
 *
 * Рік беремо той, у якому свято ще попереду: інакше щойно додане свято
 * одразу лягло б у минуле й показувало «через −200 днів».
 */
export function presetDate(md: string, today: Date = new Date()): string {
  const [month, day] = md.split('-').map(Number);
  const thisYear = today.getFullYear();
  const candidate = new Date(thisYear, (month ?? 1) - 1, day ?? 1);
  const midnight = new Date(today.getFullYear(), today.getMonth(), today.getDate());
  const year = candidate < midnight ? thisYear + 1 : thisYear;
  return ymd(year, month ?? 1, day ?? 1);
}

/**
 * Заготовки, яких у календарі ще немає.
 *
 * Звіряємось за днем і місяцем, а не за назвою: власник міг завести
 * «Незалежність» своїми словами, і пропонувати йому 24 серпня вдруге —
 * це створити дубль у списку, який він потім видалятиме вручну.
 *
 * Разові події теж рахуються: подія 24 серпня цього року займає той день
 * так само, як щорічна.
 */
export function missingPresets(
  events: readonly EventRow[],
  presets: readonly HolidayPreset[] = HOLIDAY_PRESETS,
): HolidayPreset[] {
  const taken = new Set<string>();
  for (const ev of events) {
    const d = localDateFromISO(ev.date);
    if (Number.isNaN(d.getTime())) continue;
    taken.add(`${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`);
  }
  return presets.filter((p) => !taken.has(p.md));
}
