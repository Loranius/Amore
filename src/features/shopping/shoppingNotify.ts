// ============================================================
// Перемикач «сповіщати в Telegram» у покупках (ADR-0262).
// ------------------------------------------------------------
// Вибір цього пристрою: вимкнув — товари додаються й купуються тихо, доки
// не ввімкне знову. Сховище — лише зручність пристрою: без нього (приватний
// режим) перемикач поводиться як досі, тобто сповіщає.
// ============================================================

/** Де пристрій пам'ятає перемикач сповіщень покупок (ADR-0262). */
export const SHOPPING_NOTIFY_KEY = 'amore:shoppingNotify';

/** Типово — сповіщати, як було досі; лише явне «0» вимикає. */
export function readShoppingNotify(): boolean {
  try {
    return window.localStorage.getItem(SHOPPING_NOTIFY_KEY) !== '0';
  } catch {
    // Приватний режим або заблоковане сховище: поводимось як досі.
    return true;
  }
}

export function writeShoppingNotify(on: boolean): void {
  try {
    window.localStorage.setItem(SHOPPING_NOTIFY_KEY, on ? '1' : '0');
  } catch {
    /* сховище недоступне — вибір проживе до кінця візиту */
  }
}
