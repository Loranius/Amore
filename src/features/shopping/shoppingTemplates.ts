// ============================================================
// Шаблон покупок — базові домашні товари у два дотики.
// ------------------------------------------------------------
// Власник: «під полем додай кнопку шаблон… коли акардеон з шаблону
// відкривається, вся продукція там вже розсортована по категоріям (їжа, побут,
// хотілки)… при натисканні на потрібний продукт він одразу додається в
// активний список».
//
// ТУТ ДВІ РІЗНІ КАТЕГОРІЇ, і плутати їх не можна.
//
// 1. `TemplateGroup.title` — «Їжа», «Побут», «Хотілки». Це полиці ШАБЛОНА:
//    вони існують, щоб знайти товар пальцем за секунду, і ніде більше не
//    з'являються.
// 2. `TemplateItem.category` — категорія, з якою товар лягає в БАЗУ, і вона
//    строго з `SHOPPING_CATEGORIES`. Саме за нею список групується на екрані.
//
// Тому «Морозиво» стоїть на полиці «Хотілки», а в списку опиняється в «Інше».
// Це не недогляд: набір категорій бази синхронізований з Edge Function
// `shopping-parse` і з БД, і трьох полиць шаблона в ньому немає. Додати їх —
// це міграція плюс правка функції розбору, окрема зміна.
//
// **Категорії нижче списані з правил самого розбирача**, не вигадані:
//
//   «Молочка, крупи, хліб, бакалія, солодощі, заморозка — це "Інше", якщо не
//    підходить жодна точніша категорія. Побутова хімія, засоби для
//    прибирання, лампочки — "Побут". Мило, шампунь, зубна паста — "Гігієна".»
//
// Причина буквальна: той самий товар має лягати в ту саму групу незалежно від
// того, вписали його рукою чи взяли з полиці. Якби «Молоко» з шаблона йшло в
// «Напої», а надруковане — в «Інше», список показував би два молока в різних
// місцях. `shoppingTemplates.test.ts` тримає цю відповідність.
// ============================================================
import type { ShoppingCategory } from '@/types';

export interface TemplateItem {
  /** Назва так, як вона ляже в список — називний відмінок, з великої. */
  title: string;
  /** Категорія БАЗИ (не полиці шаблона). Тільки з `SHOPPING_CATEGORIES`. */
  category: ShoppingCategory;
}

export interface TemplateGroup {
  /** Стабільний ключ: заголовок — текст, який колись перепишуть. */
  id: 'food' | 'home' | 'treats';
  title: string;
  items: readonly TemplateItem[];
}

