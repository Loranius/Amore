/**
 * Ключ для порівняння назв.
 *
 * Регістр і зайві пробіли не роблять товар іншим товаром: «молоко» з поля
 * вводу і «Молоко» з полиці — та сама покупка, і полиця має показати її як уже
 * додану. Порівняння по цьому ключу, а не по сирому рядку.
 *
 * `toLowerCase()` без локалі — навмисно: `toLocaleLowerCase` дає різний
 * результат під різними локалями (турецька «I»), а канонічний ключ мусить бути
 * однаковим скрізь.
 */
export function templateKey(title: string): string {
  return title.trim().toLowerCase().replace(/\s+/g, ' ');
}

/**
 * Набір ключів того, що вже лежить в активному списку.
 *
 * Потрібен, щоб полиця не давала додати друге молоко мовчки: дотик по вже
 * доданому товару нічого не робить, а сам товар підписаний як доданий.
 */
export function listedKeys(titles: readonly string[]): ReadonlySet<string> {
  return new Set(titles.map(templateKey));
}
