// ============================================================
// Кристалічна грань картки плану.
// ------------------------------------------------------------
// Власник попросив «цю кристалічну обводку навколо планів збоку» — окрему
// 2.5D-модельку, а не смужку кольору. Тут вона і є: не фото й не тривимірна
// сцена, а огранка, зібрана з площин, які самі себе затінюють.
//
// Чому SVG, а не CSS-градієнт. Грань складається з ЛАМАНИХ площин: паралельні
// градієнти дають гладку трубу, а огранка потребує ребер — місць, де світло
// обривається. Полігони їх дають, градієнт — ні.
//
// Чому елемент, а не фонове зображення в `background-image`. Колір грані —
// колір категорії плану (`--plan-color`), а картинку в `url(data:…)`
// параметризувати неможливо: довелось би вбудувати одинадцять копій, по одній
// на категорію, і кожну правити окремо. Тут колір приходить через
// `currentColor`, а блиск і тінь лишаються нейтральними накладками поверх.
//
// `preserveAspectRatio="none"` навмисно: грань тягнеться на всю висоту
// картки, якою б та не була. Кут ребер від цього трохи гуляє — і це видно
// лише поруч, а поруч карток різної висоти й не буває.
// ============================================================

/** Висота полотна огранки. Близька до реальної картки, щоб розтяг був малим. */
const H = 104;

export function PlanCrystalEdge() {
  return (
    <span className="pm-tile-edge" aria-hidden="true">
      <svg viewBox={`0 0 12 ${H}`} preserveAspectRatio="none" focusable="false">
        {/* Тіло грані — колір категорії, зі своєю глибиною: згори світліше,
            донизу насиченіше. Плоский колір читався б наліпкою. */}
        <rect x="0" y="0" width="12" height={H} fill="currentColor" />
        <rect x="0" y="0" width="12" height={H} fill="url(#pm-edge-body)" />

        {/* Дві поздовжні площини: ліва йде в тінь, права ловить світло. Саме
            вони роблять із смужки об'єм — ребро між ними видно як лінію. */}
        <polygon points={`0,0 4.6,0 4.6,${H} 0,${H}`} fill="#000" opacity="0.38" />
        <polygon points={`8.4,0 12,0 12,${H} 8.4,${H}`} fill="#fff" opacity="0.14" />

        {/* Поперечні грані: кристал не суцільний, він росте сегментами. Ламані
            навмисно нерівні — рівні читаються як насічка лінійки. */}
        <polygon points={`0,6 12,0 12,9 0,15`} fill="#fff" opacity="0.1" />
        <polygon points={`0,28 12,22 12,26 0,32`} fill="#000" opacity="0.24" />
        <polygon points={`0,47 12,41 12,51 0,57`} fill="#fff" opacity="0.08" />
        <polygon points={`0,70 12,63 12,67 0,74`} fill="#000" opacity="0.22" />
        <polygon points={`0,86 12,80 12,90 0,96`} fill="#fff" opacity="0.07" />

        {/* Відблиск по ребру — тонка лінія там, де дві площини сходяться. */}
        <rect x="8.1" y="0" width="0.7" height={H} fill="#fff" opacity="0.32" />

        {/* Верх і низ гасяться: грань виходить із картки, а не приклеєна до
            її країв. */}
        <rect x="0" y="0" width="12" height="10" fill="url(#pm-edge-top)" />
        <rect x="0" y={H - 12} width="12" height="12" fill="url(#pm-edge-bottom)" />

        <defs>
          <linearGradient id="pm-edge-body" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0" stopColor="#fff" stopOpacity="0.16" />
            <stop offset="0.45" stopColor="#fff" stopOpacity="0" />
            <stop offset="1" stopColor="#000" stopOpacity="0.22" />
          </linearGradient>
          <linearGradient id="pm-edge-top" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0" stopColor="#fff" stopOpacity="0.2" />
            <stop offset="1" stopColor="#fff" stopOpacity="0" />
          </linearGradient>
          <linearGradient id="pm-edge-bottom" x1="0" y1="0" x2="0" y2="1">
            <stop offset="0" stopColor="#000" stopOpacity="0" />
            <stop offset="1" stopColor="#000" stopOpacity="0.32" />
          </linearGradient>
        </defs>
      </svg>
    </span>
  );
}
