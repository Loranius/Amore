import { ukrainianGenitive } from '@/lib/ukrainianGenitive';

/**
 * «Бажання Лєни», «Ідеї Олексія».
 *
 * ТУТ БУЛА ТАБЛИЦЯ НА ДВА ІМЕНІ й повернення називного для решти. Поки
 * портал належав одній парі, це було чесно; із появою реєстрації стало
 * видно ціну: пара з іменем «Олексій» читала «Бажання Олексій» —
 * називний у родовому місці, у чотирьох місцях вішліста.
 *
 * Тепер форму дає правило (`lib/ukrainianGenitive.ts`), і воно
 * застосовується ЛИШЕ там, де впевнене: латиниця й незнайомі закінчення
 * повертаються незміненими — рівно як поводилась таблиця. Тобто
 * найгірший випадок лишився тим самим, що був, а типовий став
 * правильним. Замір — таблиця справжніх імен у тесті поруч із правилом.
 */
export function partnerGenitive(name: string): string {
  return ukrainianGenitive(name);
}

export function partnerWishlistTitle(name: string): string {
  return `Бажання ${partnerGenitive(name)}`;
}
