import { describe, expect, it } from 'vitest';
import { partnerGenitive, partnerWishlistTitle } from './partnerLabel';

describe('partner wishlist title', () => {
  it('uses Лєна when Діма is signed in', () => {
    expect(partnerWishlistTitle('Лєна')).toBe('Бажання Лєни');
  });

  it('uses Діма when Лєна is signed in', () => {
    expect(partnerWishlistTitle('Діма')).toBe('Бажання Діми');
  });

  it('незнайоме імʼя тепер відмінюється правилом (ADR-0209 §15)', () => {
    /*
     * ЗМІНЕНО СВІДОМО, І ОСЬ ЩО САМЕ ЗМІНИЛОСЬ У ЗМІСТІ.
     *
     * Було: `partnerGenitive('Олексій')` → `'Олексій'`, і перевірка
     * вимагала саме цього. Вимога була ПРАВИЛЬНОЮ для свого часу —
     * таблиця знала два імені, а вигадувати відмінок для третього
     * означало б помилитись у звертанні до пари її ж іменем. Показати
     * називний було чесніше за здогад.
     *
     * Змінилось не правило ввічливості, а наявність правила мови. З
     * реєстрацією (ADR-0209) чужі імена перестали бути гіпотетичними, і
     * ціна старої поведінки стала видимою: «Бажання Олексій» у чотирьох
     * місцях вішліста. Тепер форму дає `lib/ukrainianGenitive.ts`, чий
     * замір — таблиця справжніх імен із відомими формами в тесті поруч.
     *
     * Обіцянка «не вигадувати» ЗБЕРЕЖЕНА: правило мовчить там, де не
     * впевнене — латиниця й незнайомі закінчення повертаються як є,
     * рівно як поводилась таблиця. Перевірка нижче тримає обидві
     * половини: там, де правило знає, воно відмінює; там, де ні, —
     * лишає.
     */
    expect(partnerGenitive('Олексій')).toBe('Олексія');
    expect(partnerWishlistTitle('Олексій')).toBe('Бажання Олексія');

    // А обіцянка мовчати там, де невпевнено, лишилась обіцянкою.
    expect(partnerWishlistTitle('Marie')).toBe('Бажання Marie');
  });
});
