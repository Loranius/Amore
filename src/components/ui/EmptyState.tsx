// ============================================================
// EmptyState — коли показувати нічого, але сказати треба.
// ------------------------------------------------------------
// Порожні екрани в порталі були рядком тексту з емодзі на кінці:
// «Натисни «Пошук подій» 🔎», «Картки скінчились 🎬», «Спершу обери
// місто 📍». На повний екран телефона це виглядало як збій — сторінка
// ніби не догрузилась.
//
// Порожній стан насправді несе три різні речі, і рядок тексту здатен
// нести лише одну:
//
//   ЗНАЧОК   — миттєво каже, що екран цілий, просто ще без вмісту;
//   НАЗВА    — що саме тут буде;
//   ПІДКАЗКА — що зробити, щоб воно з'явилось (необов'язкова).
//
// Дія слотом, а не текстом у підказці: «натисни кнопку вгорі» — це опис
// інтерфейсу словами замість самої кнопки.
// ============================================================
import type { ReactNode } from 'react';
import './emptyState.css';

export interface EmptyStateProps {
  /** Мальований значок із набору — не емодзі. */
  icon?: ReactNode;
  title: string;
  hint?: string;
  /** Кнопка, яка виводить із порожнечі. */
  action?: ReactNode;
}

export function EmptyState({ icon, title, hint, action }: EmptyStateProps) {
  return (
    <div className="empty-block">
      {icon && <span className="empty-block__icon" aria-hidden="true">{icon}</span>}
      <p className="empty-block__title">{title}</p>
      {hint && <p className="empty-block__hint">{hint}</p>}
      {action && <div className="empty-block__action">{action}</div>}
    </div>
  );
}
