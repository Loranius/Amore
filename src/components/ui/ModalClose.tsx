import { CloseIcon } from '@/components/icons/UiIcon';

// ============================================================
// Хрестик модалки — один на портал.
// ------------------------------------------------------------
// Власник попросив «додай/заміни хрестик у правому верхньому кутку
// модалки, стиль візьми як у редагуванні покупки». Стан на той момент:
//
//  - `shopping-edit-close` — коло 38px, заливка, справжній значок;
//  - `gift-memory-close` — квадрат 40px із рамкою, текстовий «×» 25px,
//    п'ять модалок вішліста;
//  - і ЖОДНОГО хрестика у дванадцяти інших модалках: подія календаря,
//    страва, рецепт, деталі медіа, відгук, редагування медіа, спогад,
//    новий план, аркуші плану, налаштування, свайп, вибір міста.
//
// Тобто в половині модалок єдиним виходом угорі був тап повз аркуш —
// жест, якого ніхто не показував.
//
// **Позиція абсолютна, а не в потоці.** У покупках хрестик був
// елементом власної шапки з `justify-content: space-between`; повторити
// це в дванадцяти модалках означало б переписати дванадцять розкладок.
// Кут аркуша не залежить від того, що в нього поклали.
// ============================================================

/**
 * Хрестик у куті аркуша.
 *
 * `label` варто задавати там, де закриття означає щось конкретніше за
 * «закрити»: скасувати редагування, вийти з перегляду. Читає його лише
 * зчитувач екрана — намальовано скрізь однаково.
 *
 * `disabled` потрібен там, де аркуш уже зберігає: вішліст вимикав свій
 * хрестик на час запису, і закрити модалку посеред завантаження фото
 * означало б лишити бажання без нього.
 */
export function ModalClose({ onClose, label = 'Закрити', disabled = false }: {
  onClose: () => void;
  label?: string;
  disabled?: boolean;
}) {
  return (
    <button
      type="button"
      className="modal-close"
      onClick={onClose}
      aria-label={label}
      disabled={disabled}
    >
      <CloseIcon size={19} />
    </button>
  );
}
