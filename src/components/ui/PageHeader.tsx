// ============================================================
// PageHeader — одні двері для всіх модулів.
// ------------------------------------------------------------
// **Виміряно знімками всіх маршрутів.** Портал мав п'ять різних способів
// почати сторінку й чотири модулі, які не починали її ніяк:
//
//   «Спогади»     — `mm-head`: заголовок 25px Nunito + рядок лічильників;
//   «Графік»      — `sched-hero`: надзаголовок акцентом + 38px FREDOKA +
//                   речення-опис;
//   «Вотчліст»    — `media-head`: заголовок розміру h1 і кнопка праворуч;
//   «Скарбничка»  — `budget-title` схований для екранного диктора, а видима
//                   назва живе всередині картки;
//   Плани, Покупки, «Куди піти», «Кулінарія» — нічого.
//
// Пара, яка ходить між вкладками, щоразу отримувала інші двері. Це не
// дрібниця стилю: заголовок сторінки — єдине, що каже «ти тут», коли док
// показує п'ять іконок, а вміст різний.
//
// Тут — один компонент і одна відповідь. Порядок частин фіксований, бо
// саме сталість порядку й читається як цілісність:
//
//   надзаголовок (необов'язковий) → назва → рядок стану (необов'язковий)
//                                                    ↳ дія (необов'язкова)
//
// **Світові екрани винятки, і це рішення, а не недогляд.** Головна й
// «Вішліст» малюють вміст ПОВЕРХ тривимірної сцени: там заголовок з'їв би
// висоту в артефакта, заради якого екран існує. У них свої двері —
// привітання з лічильником і панель-пігулка відповідно (ADR-0046).
// ============================================================
import type { ReactNode } from 'react';
import './pageHeader.css';

export interface PageHeaderProps {
  /** Назва модуля словом пари — «Спогади», а не «Галерея». */
  title: string;
  /**
   * Категорія над назвою, акцентом. Коротка й без крапки.
   *
   * Не для опису — для приналежності: «Календар пари» над «Графіком».
   */
  eyebrow?: string;
  /**
   * Рядок стану під назвою: скільки всього, від якого року, що далі.
   *
   * Числа тут ідуть `tabular-nums` — див. `pageHeader.css`. Це те саме
   * місце, де жили `mm-sub` і `sched-subtitle`, тож обидва варіанти —
   * і лічильники, і речення — мусять читатись однаково добре.
   */
  meta?: ReactNode;
  /** Одна дія праворуч від назви. Саме одна: «+ Додати», «Карта». */
  action?: ReactNode;
}

export function PageHeader({ title, eyebrow, meta, action }: PageHeaderProps) {
  return (
    <header className="page-head">
      <div className="page-head__text">
        {eyebrow && <span className="page-head__eyebrow">{eyebrow}</span>}
        <h1 className="page-head__title">{title}</h1>
        {meta && <p className="page-head__meta">{meta}</p>}
      </div>
      {action && <div className="page-head__action">{action}</div>}
    </header>
  );
}
