import { describe, expect, it } from 'vitest';
import { childDimensions, yearActivity, yearFill } from './growthModel';

// ============================================================
// Наповненіший рік — товстіший кристал.
// ------------------------------------------------------------
// Власник: «чим наповненіші модулі за нинішній рік, тим нинішній
// дочірній кристал буде більшим І ТОВСТІШИМ, але ніколи не більшим
// ніж монарх».
//
// Висота за наповненістю була й раніше. Стрункість — ні: аспект брався
// навмання зі смуги [3.4, 4.3], тож ПОРОЖНІЙ рік міг вийти товстішим
// за повний — нижчий, але з меншим аспектом. Тобто товщина не просто
// не несла сенсу, вона іноді казала протилежне.
//
// Тест міряє саме товщину (`radialScale`), а не висоту: висоту стерегли
// й до того, і саме тому вада прожила стільки часу.
// ============================================================

const SEEDS = [0, 7, 41, 128, 999];
const MONARCH = 1;

describe('товщина річного кристала йде за наповненістю', () => {
  /*
   * ЩО ТУТ ВЗАГАЛІ МОЖНА ПЕРЕВІРИТИ — і чого не можна.
   *
   * Перша редакція цього файлу мала п'ять перевірок, і мутація
   * «товщина знову випадкова» завалила рівно ОДНУ. Причина проста й
   * варта запису: за СТАЛОГО насіння аспект однаковий, тож
   * `radialScale = axialScale / (2·аспект)` росте разом із висотою хай
   * там як. Тобто «повніший рік товщий на тому самому насінні» було
   * правдою й до правки — воно міряло висоту, а не товщину.
   *
   * Розрізняє лише порівняння ЧЕРЕЗ НАСІННЯ: чи може щасливий кидок
   * зробити бідніший рік товщим за багатший. Саме це й перевіряється
   * нижче, і саме це мутація валить.
   */

  it('жодне насіння не робить бідніший рік товщим за багатший', () => {
    /*
     * Та сама вада словами продукту: пара додала все, що могла, за цей
     * рік — і отримала тонший кристал, ніж торік, бо монетка лягла
     * інакше. Кільце років при цьому бреше.
     *
     * Смуга наповненості береться з кроком 0.2: менший крок нічого не
     * додає, бо тремтіння насіння свідомо вужче за один щабель.
     */
    const fills = [0.1, 0.3, 0.5, 0.7, 0.9];
    for (let index = 1; index < fills.length; index += 1) {
      const leanestRich = Math.min(...SEEDS.map(
        (seed) => childDimensions(MONARCH, fills[index]!, 1, seed).radialScale,
      ));
      const stoutestPoor = Math.max(...SEEDS.map(
        (seed) => childDimensions(MONARCH, fills[index - 1]!, 1, seed).radialScale,
      ));
      expect(
        leanestRich,
        `найтонший рік на ${fills[index]} (${leanestRich.toFixed(5)}) має бути товщим `
        + `за найтовстіший на ${fills[index - 1]} (${stoutestPoor.toFixed(5)})`,
      ).toBeGreaterThan(stoutestPoor);
    }
  });

  it('роки з однаковою наповненістю все одно не одна форма', () => {
    /*
     * Межа з іншого боку. Прибрати тремтіння зовсім було б найпростішим
     * способом пройти перевірку вище — і повернуло б «зменшений
     * монарх», який прибирали в Pass 9: шість дочірніх однією формою в
     * різному масштабі.
     */
    const same = SEEDS.map((seed) => childDimensions(MONARCH, 0.5, 1, seed).radialScale);
    expect(new Set(same).size, 'усі роки однакової форми').toBeGreaterThan(1);
  });

  it('ніколи не товщий і не вищий за монарха', () => {
    // Стеля, названа власником, і вона не залежить від наповненості.
    for (const seed of SEEDS) {
      for (const fill of [0.1, 0.5, 1]) {
        const child = childDimensions(MONARCH, fill, 1, seed);
        expect(child.axialScale, `насіння ${seed}, наповненість ${fill}`).toBeLessThan(MONARCH);
        expect(child.radialScale).toBeLessThan(MONARCH);
      }
    }
  });

  it('наповненість справді приходить із модулів, а не з годинника', () => {
    // Ланцюг, який робить правило правдою: більше живих модулів і більше
    // подій → більша `activity` → більший `fill` → товстіше тіло.
    const quiet = yearFill(1, yearActivity(1, 2));
    const busy = yearFill(1, yearActivity(6, 60));
    expect(busy).toBeGreaterThan(quiet);
    expect(
      childDimensions(MONARCH, busy, 1, 0).radialScale,
    ).toBeGreaterThan(childDimensions(MONARCH, quiet, 1, 0).radialScale);
  });
});
