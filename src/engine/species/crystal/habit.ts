// ============================================================
// Габітус кристала: яку форму пара носить усе життя.
// ------------------------------------------------------------
// Власник: «кристал має мати різні форми — або гострокінечний, або
// такий, як зараз, тупий, як сталагміт, або ще якийсь третій. Щоб у
// кожної пари була більша варіація».
//
// ЧОМУ ЦЬОГО НЕ БУЛО. Машинерія варіацій у геометрії стояла давно:
// `profileScales`, `shapeTuning`, тупа й зламана верхівка, кут корони.
// Але користувались нею лише ДІТИ, а монарх мав рядок
//
//   const archetype = mother ? 'prismatic' : sourceArchetype;
//
// тобто в кожної пари світу — рівно одна форма. Те, на що дивляться,
// було єдиним, що не різнилось.
//
// ЗВІДКИ ВЗЯТО СЛОВНИК. Не з уяви: це стандартні habits мінералогії —
// призматичний, голчастий, табличний, сталактитовий/сталагмітовий.
// Ними описують реальні мінерали, і кожен має пізнаваний силует, який
// не сплутаєш із сусіднім навіть на екрані телефона.
//
// Готового коду взято НЕ БУЛО. Перебрані відкриті генератори кристалів
// (crystal-machine на Houdini, Procedural-Crystals на Blender, crystalpy)
// або живуть у чужому рушії, або взагалі про інше — crystalpy, попри
// назву, генерує фотонні ґратки. А головне: наш рушій уже ріже
// многогранник перетином півпросторів (`intersectHalfSpaces`), тобто
// саме тим способом, яким огранку будують за нормалями граней. Бракувало
// не механізму, а словника — і словник узято з мінералогії.
// ============================================================
import { stableHash32 } from '../../evolution';
import { coupleTraitStep } from '../shared/relationshipYear';
import type { CrystalArchetype } from './types';

/**
 * Чотири форми, які пара може носити.
 *
 * НАЗВИ ВЗЯТО З КОДУ, А НЕ ПРИДУМАНО ПОРУЧ. `CrystalArchetype` уже мав
 * і `needle`, і `tabular`, і `massive` — і це ті самі мінералогічні
 * габітуси під іншими іменами: `needle` це acicular, `massive` це той
 * тупий стовп, який власник описав як «сталагміт». Заводити п'ятий
 * словник поверх наявного означало б мати два імені на одну річ.
 *
 * `prismatic` — класичний кварц: рівна шестигранна призма з гострою
 *   пірамідою. Те, що уявляють, коли кажуть «кристал».
 * `massive` — те, що стоїть на екрані зараз: товстіший, з тупою
 *   зрізаною верхівкою.
 * `needle` — голчастий: вузький і різкий, з довгим шпилем.
 * `tabular` — табличний: присадкуватий і широкий, майже плита.
 */
export const CRYSTAL_HABITS = ['prismatic', 'massive', 'needle', 'tabular'] as const;

export type CrystalHabit = (typeof CRYSTAL_HABITS)[number];

/*
 * Габітуси — підмножина `CrystalArchetype`, а не паралельний словник.
 * Це твердження перевіряється типом: якби сюди потрапила назва, якої
 * архетипи не знають, файл не зібрався б.
 */
const _habitsAreArchetypes: readonly CrystalArchetype[] = CRYSTAL_HABITS;
void _habitsAreArchetypes;

/**
 * Габітус цієї пари — від дати початку, як і колір.
 *
 * Та сама логіка, той самий розклад, інший малюнок: `coupleTraitStep`
 * розводить риси за назвою, тож форма й колір не тягнуться з одного
 * числа. Інакше всі пари з рожевим кристалом мали б однакову огранку —
 * риса, яка нічого не додає, бо повторює вже сказане.
 *
 * Порожня дата дає призму: вигадувати парі форму, доки вона не сказала,
 * коли почалась, — це не «за замовчуванням», це домисел.
 */
export function coupleCrystalHabit(relationshipStartedAt: string): CrystalHabit {
  const step = coupleTraitStep(
    relationshipStartedAt, CRYSTAL_HABITS.length, stableHash32, 'habit',
  );
  if (step === null) return 'prismatic';
  const index = Math.min(
    CRYSTAL_HABITS.length - 1,
    Math.round(step * (CRYSTAL_HABITS.length - 1)),
  );
  return CRYSTAL_HABITS[index]!;
}
