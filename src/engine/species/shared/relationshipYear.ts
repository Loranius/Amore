// ============================================================
// Рік стосунків — одна модель на всі види.
// ------------------------------------------------------------
// ЧОМУ ЦЕЙ ФАЙЛ З'ЯВИВСЯ. Кристал і риф рахували наповненість року
// **двома окремими копіями** одного й того самого коду:
// `species/crystal/growthModel.ts` і `species/reef/moduleEvolution.ts`.
// Формули збігались дослівно, сталі збігались числом (12, 0.3, 0.5,
// шість модулів), списки модулів збігались складом — і все це трималось
// виключно на тому, що другу копію колись зробили з першої.
//
// Ціна такого збігу видна вже зараз, у дрібному: копія рифа не мала
// захисту від нескінченності й від нечислових лічильників, який у
// кристала є. Тобто дві реалізації ОДНОГО правила вже поводились
// по-різному на поганих даних.
//
// А правило, яке вони обидві виражають, — це `PRODUCT.md`: «минуле не
// переписується». Мати його у двох місцях означає мати два різні
// минулих, і розійдуться вони тихо: жоден тест не порівнював їх між
// собою, бо кожен вид перевіряв лише себе.
//
// ЩО СЮДИ НАЛЕЖИТЬ. Тільки те, що не знає про вид: скільки різних
// частин порталу торкнувся рік, скільки в ньому подій, скільки спільних
// вихідних, і що з цього виходить як «наповненість». Форма, розмір,
// колір і розкладка лишаються за видом — у рифа вони інші за побудовою.
// ============================================================

/**
 * Частини порталу, на які рік може спиратись: календар, плани, вішліст,
 * карта, спогади, медіа.
 *
 * Покупки тут були й немає, медіа не було й тепер є (ADR-0017). Обидва —
 * та сама вада з протилежних кінців: службовий модуль рахувався частиною
 * стосунків, а рік, проведений за спільним переглядом і читанням, не
 * рахувався ніяк.
 *
 * Список, а не число. Кристал тримав саме число з коментарем, риф —
 * список; збіг складу ніхто не перевіряв, бо порівнювати не було з чим.
 */
export const PORTAL_MODULES = [
  'calendar',
  'plans',
  'wishlist',
  'map',
  'memories',
  'media',
] as const;

export type PortalModule = (typeof PORTAL_MODULES)[number];

export const PORTAL_MODULE_COUNT = PORTAL_MODULES.length;

/** Подій в одному модулі, після яких наступні додають мало. */
export const YEAR_DEPTH_HALF_SATURATION = 12;

/** Спільних вихідних, які рахуються повним роком на цій осі. */
export const SHARED_DAYS_OFF_FULL_YEAR = 60;

/** Скільки спільний час може підняти рік, який модулі описали бідно. */
export const TOGETHERNESS_LIFT = 0.5;

/** Що отримує рік, у якому не було нічого. */
export const EMPTY_YEAR_FLOOR = 0.3;

function clamp01(value: number): number {
  return value < 0 ? 0 : value > 1 ? 1 : value;
}

function round6(value: number): number {
  return Math.round(value * 1e6) / 1e6;
}

/**
 * Лічильник, доведений до числа.
 *
 * `Math.max(0, NaN)` це NaN, а `Infinity / (Infinity + 12)` теж NaN, тож
 * лічильник треба ДОВЕСТИ до скінченного, а не просто обрізати знизу.
 * Копія рифа цього не робила — і саме таких відмінностей між двома
 * реалізаціями одного правила цей файл і позбувається.
 */
function counted(value: number): number {
  return Number.isFinite(value) ? Math.max(0, value) : 0;
}

/**
 * Наскільки рік був прожитий, від 0 до 1.
 *
 * Зважено в бік **широти** — скількох частин порталу рік торкнувся, — а
 * не обсягу. Рахунок подій робив із міри майже самий лічильник фото: у
 * найповнішому році справжньої пари 48 з 80 подій були знімками.
 */
export function yearActivity(moduleCount: number, eventCount: number): number {
  const breadth = clamp01(counted(moduleCount) / PORTAL_MODULE_COUNT);
  const events = counted(eventCount);
  const depth = events / (events + YEAR_DEPTH_HALF_SATURATION);
  return round6(0.6 * breadth + 0.4 * depth);
}

/**
 * Скільки часу пара насправді мала разом, із робочого графіка.
 *
 * Рахується пласко проти цілого року, а не проти місяців, які графік
 * покриває, і це вирішили живі дані. Перша редакція нормалізувала за
 * покриттям — на вигляд чесно: два покриті місяці з добрим показником
 * мали б читатись добрим роком. На порталі власника це перетворило 18
 * спільних вихідних за два місяці на **повний** рік по цій осі, бо 18
 * днів за два місяці екстраполюються у 108 за дванадцять.
 */
export function yearTogetherness(sharedDaysOff: number): number {
  return round6(clamp01(counted(sharedDaysOff) / SHARED_DAYS_OFF_FULL_YEAR));
}

/**
 * Наповненість року, від 0 до 1 — частка того максимуму, на який рік має право.
 *
 * Саме ця величина спиняється на річницю. Це НЕ те саме, що незмінність
 * тіла: пара, яка прийшла на портал на третій рік, мусить мати змогу
 * заповнити перші два, і вміст, датований усередині року, належить тому
 * рокові, коли б його не додали. Чого закритий рік більше не робить — це
 * не росте з часом і не росте з того, що сталось поза ним.
 *
 * @param progress скільки року минуло, 0..1
 * @param activity `yearActivity`
 * @param togetherness `yearTogetherness`; 0, коли графік про цей рік мовчить
 */
export function yearFill(progress: number, activity: number, togetherness = 0): number {
  const recorded = clamp01(activity);
  const lived = recorded + (1 - recorded) * TOGETHERNESS_LIFT * clamp01(togetherness);
  return round6(clamp01(progress) * (EMPTY_YEAR_FLOOR + (1 - EMPTY_YEAR_FLOOR) * lived));
}

/**
 * Крок пари на кольоровій дузі свого виду, від 0 до 1.
 *
 * **Спільна тут ІДЕНТИЧНІСТЬ, а не палітра.** Правило власника — «колір
 * у кожної пари індивідуальний і формується від дати початку» — не
 * залежить від того, кристал це чи риф. А от сама дуга залежить:
 * трояндово-аметистова родина кристала не має нічого спільного з тим,
 * у чому має бути риф.
 *
 * Тому спільним стає рівно те, що однакове: детермінований крок від
 * дати, поділений на щаблі. Куди його покласти — вирішує вид.
 *
 * Наслідок, названий вголос: дві різні дати МОЖУТЬ дати той самий крок.
 * Щаблів кілька, дат безліч. «Індивідуальний» означає «свій і
 * незмінний», а не «унікальний у світі».
 *
 * @param steps скільки розрізнюваних щаблів має дуга виду
 * @returns 0..1, або `null` для порожньої дати — вид сам вирішує, що
 *   означає «кольору ще немає», і вигадувати його за нього не можна
 */
export function coupleHueStep(
  relationshipStartedAt: string,
  steps: number,
  hash: (value: string) => number,
): number | null {
  const source = typeof relationshipStartedAt === 'string' ? relationshipStartedAt.trim() : '';
  if (source === '') return null;
  const count = Number.isFinite(steps) ? Math.max(2, Math.floor(steps)) : 2;
  const seed = hash(`couple:tint:${source}`);
  // Той самий розклад, що використовував кристал: рівномірний щабель,
  // а не неперервне значення — сусідні дати мають давати ВИДИМО різні
  // відтінки, інакше «індивідуальність» існує лише в числах.
  const unit = (Math.abs(seed) % 1_000_003) / 1_000_003;
  const step = Math.min(count - 1, Math.floor(unit * count));
  return round6(step / (count - 1));
}
