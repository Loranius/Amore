// Пора року (ADR-0237 §7, п. 4): стан світу, а не ріст.
// ------------------------------------------------------------
// Власник обрав пори року для всіх трьох видів. Вони не змінюють чисел
// моделі й не порушують «ніщо не меншає»: це погода довкола об'єкта —
// осіннє листя дерева, іній на острові кристала, світло у воді вулкана.
// Місяць береться з дати знімка (не з годинника), тож той самий знімок —
// та сама пора. Календар — український: зима — грудень…лютий.
// ============================================================

export type Season = 'winter' | 'spring' | 'summer' | 'autumn';

export function seasonOf(asOf: string): Season {
  const month = Number(asOf.slice(5, 7));
  if (month === 12 || month <= 2) return 'winter';
  if (month <= 5) return 'spring';
  if (month <= 8) return 'summer';
  return 'autumn';
}
