// ============================================================
// Колір коралу: пара дає відтінок, тема дає світлість.
// ------------------------------------------------------------
// Друге з чотирьох правил власника — «колір індивідуальний для кожної
// пари, від дати початку» — діє тут так само, як у кристала. Але дуга
// інша, і вибір дуги тут виміряний, а не вгаданий.
//
// ЧОМУ НЕ БІРЮЗА, ХОЧ СВІТ РИФА БІРЮЗОВИЙ. `DESIGN.md` фіксує пару тем
// рифа: світло на глибині (`#6ba6ff` / `#070a12`) і бірюза на мілині
// (`#0d6e6b` / `#ecf8f8`). Спокуса зробити корал у тій самій родині
// сильна — і хибна. Виміряно контраст кандидатів проти обох ґрунтів:
//
//   родина        vs темне тло   vs світле тло
//   корал 12°         6.55            2.79
//   помаранч 38°     10.09            1.81
//   бірюза 178°      12.79            1.43   ← розчиняється
//
// Темна тема неважлива: ґрунт майже чорний, там читається все. Зв'язує
// СВІТЛА — ґрунт майже білий, і бірюзовий корал на ньому дає 1.43,
// тобто зникає. Тепла коралова родина — найкраща з кандидатів, і вона ж
// збігається з тим, чим корал є насправді.
//
// ЧОМУ СВІТЛІСТЬ ЗА ТЕМОЮ, А НЕ ОДНА НА ОБИДВІ. Два ґрунти тягнуть у
// протилежні боки, і крива це показує: світліший корал читається на
// темному й зникає на світлому, темніший — навпаки. Єдина світлість,
// що влаштовує обидва, — 0.42, і вона дає посередні 3.07 туди й туди.
//
//   світлість   vs світле тло   vs темне тло
//   0.62            1.76            5.60
//   0.42            3.06            3.07   ← єдина спільна
//   0.36            4.03            2.47
//
// `DESIGN.md` уже має відповідь на цю саму задачу: «названий колір
// тримає ґрунт, а `--accent` бере той самий тон на світлості, з якої
// його видно». Тож пара фіксує ВІДТІНОК, а тема — світлість: 5.60 у
// темній і 4.03 у світлій замість 3.07 в обох.
// ============================================================
import { stableHash32 } from '../../evolution';
import { coupleHueStep } from '../shared/relationshipYear';
import { round6 } from './math';

export interface ReefTint {
  /** Лінійний RGB, 0..1. */
  rgb: [number, number, number];
}

export type ReefTheme = 'light' | 'dark';

/**
 * Дуга коралової родини: від троянди через корал до теплого бурштину.
 *
 * Верхній край свідомо не доходить до жовтого. На кристалі повне коло
 * одного разу вже дало пару з бурштиновим тілом замість родини порталу,
 * і межа тут стоїть із тієї самої причини.
 */
const HUE_START = 350;
const HUE_END = 35;
const HUE_STEPS = 6;
const SATURATION = 0.7;

/** Світлість, на якій цей відтінок видно на ґрунті своєї теми. Виміряно. */
const LIGHTNESS: Readonly<Record<ReefTheme, number>> = { dark: 0.62, light: 0.36 };

/** Пара без дати: корал лишається знебарвленим, а не вигаданим. */
const BLEACHED: Readonly<Record<ReefTheme, [number, number, number]>> = {
  dark: [0.78, 0.76, 0.74],
  light: [0.42, 0.41, 0.4],
};

function hslToRgb(hue: number, saturation: number, lightness: number): [number, number, number] {
  const h = ((hue % 360) + 360) % 360;
  const c = (1 - Math.abs(2 * lightness - 1)) * saturation;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = lightness - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0]
    : h < 120 ? [x, c, 0]
      : h < 180 ? [0, c, x]
        : h < 240 ? [0, x, c]
          : h < 300 ? [x, 0, c]
            : [c, 0, x];
  return [round6(r + m), round6(g + m), round6(b + m)];
}

/** Відтінок пари на коральовій дузі, у градусах. Один на все життя. */
export function reefCoupleHue(relationshipStartedAt: string): number | null {
  const step = coupleHueStep(relationshipStartedAt, HUE_STEPS, stableHash32);
  if (step === null) return null;
  // Дуга перетинає нуль (350°→35°), тож іде через 360 і повертається.
  const span = HUE_END + 360 - HUE_START;
  return round6((HUE_START + step * span) % 360);
}

/**
 * Колір коралу цієї пари в цій темі.
 *
 * Відтінок належить парі й не змінюється ніколи; світлість належить
 * темі. Це не два різні кольори — це один колір, показаний так, щоб
 * його було видно на тому ґрунті, який зараз під ним.
 */
export function reefCoupleTint(relationshipStartedAt: string, theme: ReefTheme): ReefTint {
  const hue = reefCoupleHue(relationshipStartedAt);
  if (hue === null) return { rgb: [...BLEACHED[theme]] };
  return { rgb: hslToRgb(hue, SATURATION, LIGHTNESS[theme]) };
}
