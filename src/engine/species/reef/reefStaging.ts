// ============================================================
// Постановка рифа: на чому він стоїть і звідки на нього дивляться.
// ------------------------------------------------------------
// Сцена не має вирішувати нічого з цього сама. Тут — чиста геометрія,
// яку можна перевірити таблицею, а не знімком: розмір каменя під
// головою, наскільки голова в нього втоплена, і кадр камери.
//
// ЧОМУ КАМІНЬ ВЗАГАЛІ ПОТРІБЕН. У голови є нижня кришка на рівні
// основи. Камера рифа опускається під цей рівень, і відкрита знизу
// голова показала б рівний диск — те саме, чим кристал колись світив
// з-під низу, доки під нього не сів камінь руїни. Камінь ховає її
// геометрично.
// ============================================================
import { round6 } from './math';
import type { ReefHeadSize } from './colonyFormations';

/**
 * У скільки разів камінь ширший за голову.
 *
 * Ширший, але не втричі: камінь — виступ, на якому колонія осіла, а не
 * острів. 1.6 — те, за чим голова ще читається головним предметом, а
 * камінь уже читається основою, а не обідком.
 */
const ROCK_SPREAD = 1.6;

/** Яку частку підйому голови має камінь: пласкіший за неї, і помітно. */
const ROCK_RISE_SHARE = 0.42;

/**
 * Запас, на який голова тоне глибше за точний рівень поверхні каменя.
 *
 * Точний рівень зробив би кришку дотичною до поверхні — а дотичне
 * зникання видно на першій же зміні кута камери. Частка підйому каменя,
 * а не абсолютне число: на маленькому рифі абсолютне з'їло б основу.
 */
const HEAD_SINK_MARGIN = 0.08;

export interface ReefStanding {
  rock: ReefHeadSize;
  /** На яку висоту підняти голову над основою каменя. */
  headLift: number;
}

/**
 * Камінь під головою й посадка голови на нього.
 *
 * Рівняння одне: поверхня каменя на відстані `head.radius` від осі має
 * лежати ВИЩЕ за нижнє кільце голови. Для півеліпсоїда це
 * `rise * sqrt(1 - (Rг/Rк)²)`, тобто підйом каменя, зменшений
 * множником, який залежить лише від того, у скільки разів камінь
 * ширший. Тому підйом голови тут — не підібране число, а розв'язок.
 */
export function reefStanding(head: ReefHeadSize): ReefStanding {
  const radius = Math.max(1e-6, head.radius);
  const rise = Math.max(1e-6, head.rise);
  const rock = {
    radius: round6(radius * ROCK_SPREAD),
    rise: round6(rise * ROCK_RISE_SHARE),
  };
  const surfaceAtHeadEdge = rock.rise * Math.sqrt(1 - (1 / ROCK_SPREAD) ** 2);
  return {
    rock,
    headLift: round6(surfaceAtHeadEdge * (1 - HEAD_SINK_MARGIN)),
  };
}

export interface ReefCameraFrame {
  /** Куди дивиться камера — середина того, що є на екрані. */
  target: { x: number; y: number; z: number };
  /** Скільки одиниць від цілі до камери. */
  distance: number;
  /** Наскільки камера піднята над ціллю, у частках відстані. */
  height: number;
}

/**
 * Скільки місця треба лишити навколо рифа.
 *
 * Не «поділити на тангенс половини кута» — це дало б кадр, у якому риф
 * торкається країв екрана. 2.35 виміряно тим самим способом, що й у
 * кристала: беремо найширше й найвище, що є в сцені, і додаємо стільки,
 * щоб на вузькому телефоні лишалась вода навколо.
 */
const FRAME_MARGIN = 2.35;

/**
 * Кадр камери на весь риф.
 *
 * Рахується від КАМЕНЯ, а не від голови: камінь ширший, і саме він
 * визначає, де край картинки. Ціль стоїть на середині висоти голови —
 * так на екрані порівну води зверху й каменя знизу.
 */
export function reefCameraFrame(head: ReefHeadSize, standing: ReefStanding): ReefCameraFrame {
  const widest = Math.max(standing.rock.radius, head.radius);
  const top = standing.headLift + head.rise;
  return {
    target: { x: 0, y: round6(top * 0.5), z: 0 },
    distance: round6(widest * FRAME_MARGIN),
    height: round6(0.42),
  };
}
