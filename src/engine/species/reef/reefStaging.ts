// ============================================================
// Постановка рифа: на чому він стоїть і звідки на нього дивляться.
// ------------------------------------------------------------
// Сцена не має вирішувати нічого з цього сама. Тут — чиста геометрія,
// яку можна перевірити таблицею, а не знімком: розмір каменя під
// головою, наскільки голова в нього втоплена, і кадр камери.
//
// ЧОМУ КАМІНЬ ВЗАГАЛІ ПОТРІБЕН. У голови є нижня кришка на рівні
// основи. Камера рифа опускається під цей рівень, і відкрита знизу
// голова показала б рівний диск — те саме, чим кристал колись світив
// з-під низу, доки під нього не сів камінь руїни. Камінь ховає її
// геометрично.
// ============================================================
import { round6 } from './math';
import type { ReefHeadSize } from './colonyFormations';

/**
 * У скільки разів камінь ширший за голову.
 *
 * Ширший, але не втричі: камінь — виступ, на якому колонія осіла, а не
 * острів. 1.6 — те, за чим голова ще читається головним предметом, а
 * камінь уже читається основою, а не обідком.
 */
const ROCK_SPREAD = 1.42;

/**
 * Яку частку підйому голови має камінь: пласкіший за неї, і помітно.
 *
 * Було 0.42 — і коли дно стало світлим, камінь почав читатись не
 * горбом, а темною ПЛИТОЮ, що стирчить із піску. Виступ рифа мусить
 * мати бік: 0.55 лишає його явно нижчим за голову й водночас дає
 * силует, у якому видно, що це камінь.
 */
const ROCK_RISE_SHARE = 0.55;

/**
 * Запас, на який голова тоне глибше за точний рівень поверхні каменя.
 *
 * Точний рівень зробив би кришку дотичною до поверхні — а дотичне
 * зникання видно на першій же зміні кута камери. Частка підйому каменя,
 * а не абсолютне число: на маленькому рифі абсолютне з'їло б основу.
 */
const HEAD_SINK_MARGIN = 0.08;

export interface ReefStanding {
  rock: ReefHeadSize;
  /** На яку висоту підняти голову над основою каменя. */
  headLift: number;
}

/**
 * Камінь під головою й посадка голови на нього.
 *
 * Рівняння одне: поверхня каменя на відстані `head.radius` від осі має
 * лежати ВИЩЕ за нижнє кільце голови. Для півеліпсоїда це
 * `rise * sqrt(1 - (Rг/Rк)²)`, тобто підйом каменя, зменшений
 * множником, який залежить лише від того, у скільки разів камінь
 * ширший. Тому підйом голови тут — не підібране число, а розв'язок.
 */
export function reefStanding(head: ReefHeadSize): ReefStanding {
  const radius = Math.max(1e-6, head.radius);
  const rise = Math.max(1e-6, head.rise);
  const rock = {
    radius: round6(radius * ROCK_SPREAD),
    rise: round6(rise * ROCK_RISE_SHARE),
  };
  const surfaceAtHeadEdge = rock.rise * Math.sqrt(1 - (1 / ROCK_SPREAD) ** 2);
  return {
    rock,
    headLift: round6(surfaceAtHeadEdge * (1 - HEAD_SINK_MARGIN)),
  };
}

export interface ReefCameraFrame {
  /** Куди дивиться камера — середина того, що є на екрані. */
  target: { x: number; y: number; z: number };
  /** Скільки одиниць від цілі до камери. */
  distance: number;
  /** Наскільки камера піднята над ціллю, у частках відстані. */
  height: number;
}

/** Вертикальний кут камери рифа. Сцена бере його ЗВІДСИ, а не свій. */
export const REEF_CAMERA_FOV_DEG = 44;

/** Скільки води лишається навколо рифа: 1.0 — риф упритул до країв. */
const FRAME_MARGIN = 1.06;

/** Наскільки камера піднята над ціллю, у частках відстані. */
const FRAME_HEIGHT = 0.34;

/**
 * Кадр камери на весь риф.
 *
 * ДВІ ПОМИЛКИ, ОБИДВІ ВИДНО НА ЗНІМКАХ, І ОБИДВІ ТУТ ВИПРАВЛЕНІ.
 *
 * Перша: відстань бралась як «найширше × 2.35», без співвідношення
 * сторін. На телефоні риф вилазив за обидва краї, бо у вертикального
 * кадру горизонтальний кут вужчий за вертикальний рівно в `aspect`
 * разів.
 *
 * Друга, тонша: виправлення першої рахувало риф ПЛОСКИМ — мовляв, він
 * увесь лежить на площині цілі. Для широкого тіла зблизька це неправда:
 * його ближній край на цілий радіус ближчий за центр і проєктується
 * помітно більшим. На широкому екрані камера від того сідала на 2.40
 * там, де радіус голови 1.19, — риф заповнював екран і різався краями.
 *
 * Тому міряється КУТОВИЙ розмір описаної сфери: щоб тіло радіуса `R`
 * вміщалось у півкут `θ`, треба `d ≥ R / sin(θ)`. Синус, а не тангенс:
 * тангенс — це для плоскої мішені на відстані, синус — для тіла, яке
 * має товщину.
 */
export function reefCameraFrame(
  head: ReefHeadSize,
  standing: ReefStanding,
  aspect: number,
): ReefCameraFrame {
  const top = standing.headLift + head.rise;
  const centreY = top * 0.5;
  const safeAspect = Number.isFinite(aspect) && aspect > 0.05 ? aspect : 1;

  /*
   * Радіус описаної сфери — від цілі до найдальшої точки ГОЛОВИ.
   * Каменю дозволено виходити за краї: він основа, як підлога в
   * кімнаті, і вміщувати його означало б зменшити риф у півтора раза
   * заради того, чого ніхто не роздивляється.
   */
  const rim = Math.hypot(head.radius, standing.headLift - centreY);
  const radius = Math.max(rim, top - centreY);

  const halfVertical = (REEF_CAMERA_FOV_DEG * Math.PI) / 360;
  const halfHorizontal = Math.atan(Math.tan(halfVertical) * safeAspect);
  const distance = Math.max(
    radius / Math.sin(halfVertical),
    radius / Math.sin(halfHorizontal),
  ) * FRAME_MARGIN;

  return {
    target: { x: 0, y: round6(centreY), z: 0 },
    distance: round6(distance),
    height: FRAME_HEIGHT,
  };
}
