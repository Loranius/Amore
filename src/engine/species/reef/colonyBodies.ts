// ============================================================
// Коралові тіла однієї річної колонії.
// ------------------------------------------------------------
// Річна колонія — не одне тіло, а купка коралів, що виросла на голові
// за той рік. Цей файл вирішує лише ОДНЕ: де кожне тіло стоїть, яке
// воно завтовшки, яке заввишки й куди нахилене. Меш — окремо.
//
// ЩО РОБИТЬ КУПКУ КОЛОНІЄЮ, а не купою паличок. Три речі, і кожна
// названа нижче правилом:
//
//   1. КУРГАН. Тіла в середині вищі за крайні. Без цього силует
//      читається щіткою: двадцять однакових стовпчиків.
//   2. ЗРОЩЕННЯ. Повний рік дає товсті тіла, які торкаються сусідів і
//      зливаються в суцільну шапку; порожній — тонкі, що стоять
//      нарізно. Саме так наповненість стає видимою, а не «десь у числі».
//   3. ВІЯЛО. Крайні тіла нахилені НАЗОВНІ — корал тягнеться до світла,
//      і від цього колонія розкривається, а не тисне сама себе.
//
// Розкладка — соняшникова (золотий кут + корінь із частки), бо вона
// рівномірна при будь-якій кількості й не має ані шва, ані згустку в
// центрі. Та сама причина, з якої вона стоїть у розкладці колоній на
// голові, тільки там ще й важила сталість між роками.
// ============================================================
import { clamp01, round6, seededUnit } from './math';
import { ANNUAL_DENSITY_FLOOR, type ReefAnnualColonySize } from './colonyFormations';

/** Золотий кут — те саме розсіювання, що й у розкладці колоній. */
const GOLDEN_ANGLE_RAD = Math.PI * (3 - Math.sqrt(5));

/**
 * Товщина тіла: частка від «скільки місця припадає на одне».
 *
 * Ділиться на корінь із кількості, бо площа диска ділиться між тілами:
 * вісімнадцять тіл у тій самій шапці мусять бути тоншими за три,
 * інакше повний рік перетворюється на кулю.
 *
 * ДВА ЧИСЛА, А НЕ ОДНЕ З МНОЖНИКОМ — і це не косметика. Перша редакція
 * писала товщину як «база ± частка густини», і розмах виходив
 * ±31%: при ньому ВСІ роки, від порожнього до повного, однаково
 * зливались у шапку. Тобто закон «наповненість видно» був оголошений і
 * не працював. Тепер кінці задані там, де вони справді стоять — на
 * густині порожнього року й на густині повного, — і між ними виміряна
 * різниця: найближчі сусіди в порожньому році стоять на 1.34 діаметра
 * (нарізно), у повному — на 0.59 (зрощені).
 */
const GIRTH_AT_LEAN_YEAR = 0.46;
const GIRTH_AT_FULL_YEAR = 1.0;

/** Висота кургану в центрі, у частках радіуса колонії. */
const MOUND_RISE = 0.95;

/** Яка частка тієї висоти лишається на самому краю. */
const MOUND_EDGE_SHARE = 0.38;

/** Найбільший нахил крайнього тіла, радіани (≈22°). */
const TILT_MAX_RAD = 0.38;

/** Скільки тремтіння лишає насіння — щоб два тіла поруч не були близнюками. */
const HEIGHT_JITTER = 0.22;
const TILT_JITTER_RAD = 0.16;

export interface ReefCoralBody {
  /**
   * Місце в дотичній площині колонії, в одиницях виду.
   *
   * `u`/`v`, а не `x`/`z`: площина нахилена разом із поверхнею купола,
   * і сцена сама поверне її за нормаллю прив'язки.
   */
  offset: { u: number; v: number };
  /** Радіус основи тіла. */
  radius: number;
  /** Висота над поверхнею колонії. */
  height: number;
  /** Нахил від нормалі колонії, радіани. */
  tiltRad: number;
  /** Куди нахилене — азимут у тій самій дотичній площині. */
  tiltAzimuthRad: number;
}

/**
 * Тіла однієї річної колонії.
 *
 * Насіння сюди йде вже змішане з номером року: два роки з однаковою
 * наповненістю не мають виходити близнюками, але кожен рік мусить
 * лишатись собою назавжди — правило заморозки.
 */
export function reefColonyBodies(
  colony: ReefAnnualColonySize,
  seed: number,
  yearIndex: number,
): ReefCoralBody[] {
  const count = Math.max(0, Math.floor(colony.bodies));
  if (count === 0) return [];

  const colonyRadius = Math.max(0, colony.radius);
  const density = clamp01(colony.density);

  /*
   * Товщина рахується ДО розкладки, бо вона ж і обмежує розліт.
   *
   * Центри стоять не в усьому диску колонії, а в диску, зменшеному на
   * радіус тіла: інакше оголошений радіус колонії був би брехнею, а
   * саме на нього спирається зазор між сусідніми роками.
   */
  const lean = clamp01((density - ANNUAL_DENSITY_FLOOR) / (1 - ANNUAL_DENSITY_FLOOR));
  const girth = GIRTH_AT_LEAN_YEAR + (GIRTH_AT_FULL_YEAR - GIRTH_AT_LEAN_YEAR) * lean;
  const radius = round6((colonyRadius / Math.sqrt(count)) * girth);
  const spread = Math.max(0, colonyRadius - radius);

  return Array.from({ length: count }, (_, index) => {
    const salt = `${yearIndex}:${index}`;
    // Соняшник: корінь із частки дає рівну густину по площі, золотий
    // кут — азимут, який не повторюється й не збирається в промені.
    const share = count === 1 ? 0 : Math.sqrt((index + 0.5) / count);
    const distance = spread * share;
    const azimuth = index * GOLDEN_ANGLE_RAD;
    const u = distance * Math.cos(azimuth);
    const v = distance * Math.sin(azimuth);

    // Курган: висота падає від центру до краю.
    const moundShare = MOUND_EDGE_SHARE + (1 - MOUND_EDGE_SHARE) * (1 - share);
    const jitter = 1 + (seededUnit(seed, `reef:body:height:${salt}`) - 0.5) * HEIGHT_JITTER;
    const height = round6(colonyRadius * MOUND_RISE * moundShare * jitter);

    /*
     * Віяло: нахил росте з відстанню від центру, напрям — НАЗОВНІ.
     *
     * Центральне тіло стоїть строго по нормалі (`share` там нуль), і
     * тремтіння азимуту йому нічого не міняє.
     */
    const tiltJitter = (seededUnit(seed, `reef:body:tilt:${salt}`) - 0.5) * TILT_JITTER_RAD;
    const tiltRad = round6(Math.max(0, TILT_MAX_RAD * share + tiltJitter * share));
    const tiltAzimuth = azimuth
      + (seededUnit(seed, `reef:body:fan:${salt}`) - 0.5) * TILT_JITTER_RAD;

    return {
      offset: { u: round6(u), v: round6(v) },
      radius,
      height,
      tiltRad,
      tiltAzimuthRad: round6(tiltAzimuth - Math.PI * 2 * Math.floor(tiltAzimuth / (Math.PI * 2))),
    };
  });
}
