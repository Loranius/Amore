// ============================================================
// Силует рифа числами — одна мірка на еталон і на генератор.
// ------------------------------------------------------------
// НАВІЩО. У кристала така мірка є (`crystal/crystalProfile.ts`), у
// дерева є (`tree/crownProfile.ts`), у рифа не було жодної. Через це про
// риф не можна було сказати нічого перевірюваного: «схожий на риф» і
// «схожий на брилу в конфеті» однаково не мали числа, яким їх розрізнити.
//
// ЩО САМЕ ТУТ МІРЯЄТЬСЯ І ЧОМУ НЕ ФОРМА ОДНОГО КОРАЛА. Форма одного тіла
// вже виявилась ПРАВИЛЬНОЮ (див. `REEF_REFERENCE` нижче: стрункість
// еталона 1.05, наша медіана 1.13). Це той самий поворот, що кристал уже
// пройшов: коли всі числа одного тіла сходяться, а кадр усе одно
// негарний, невиміряним лишається РОЗКЛАДАННЯ. Тому мірка тут — про
// ціле: скільки в силуеті купола, скільки корала, і яку частку купола
// корали взагалі вкривають.
//
// ЧОМУ ЧАСТКАМИ. Риф росте з роками, еталон лежить у своїх одиницях
// (0.65 × 0.44 після масштабу вузла), і порівнювати можна лише
// безрозмірне. Те саме рішення, що в `crystalProfile.ts`, і з тієї самої
// причини.
//
// ЩО ЦЕ НЕ МІРЯЄ. Колір. Він знімається пікселями з живої сцени, а не з
// плану, і `REEF_REFERENCE.hues` тут лежить як довідка, а не як мірка.
// ============================================================
import type { ReefPlan } from './reefAssembly';

/**
 * ЩО НАСПРАВДІ ЛЕЖИТЬ У `public/models/coral_reef_set_cc0.glb`.
 *
 * Асет лежав у репозиторії з серпня, значився в `scripts/models/README.md`
 * як «каміння й корали ДЕКОРУ» — і жоден рядок коду його не читав. Ці
 * числа дістані з нього розбором GLB; відтворити їх можна командою
 * `node scripts/models/measure-reef.mjs`, і саме тому вони тут числами, а
 * не прозою.
 *
 * ТРИ РЕЧІ, ЯКІ ВІН КАЖЕ, і кожна суперечить тому, що можна припустити:
 *
 *  1. **Вісім «різних» коралів — це одна форма у восьми кольорах.**
 *     Усі вісім мешів мають побайтово однакову рамку
 *     (0.0044 × 0.0063 × 0.0044 до масштабу вузла ×100) і рівно 760
 *     трикутників. Набір продає не морфологію, а ПАЛІТРУ.
 *  2. **Один плаский колір на все тіло.** `COLOR_0` у кожному меші має
 *     рівно ОДНЕ унікальне значення на всі 476–524 вершини. Ні градієнта
 *     від основи до вершка, ні варіації між гілками — нічого.
 *  3. **У кожного кольору один канал притиснутий рівно до 1.0.**
 *     Усі вісім: #2b76ff, #c2ff73, #ffce5d, #aafff5, #dbff0f, #4eff84,
 *     #3fc7ff, #ff8ea6. Це повна яскравість при різній насиченості
 *     (0.33…0.94) — тобто колір НЕ приглушують, його розводять
 *     насиченістю.
 *
 * Плюс матеріал: `alphaMode: OPAQUE`, `emissiveFactor: [1,1,1]` з
 * емісійною текстурою, `shadingModel: Phong`, `isTruePBR: false`. Той
 * самий висновок, що й у кристала з його стилізованих самоцвітів —
 * **референс не освітлюють, його малюють.**
 */
export const REEF_REFERENCE = {
  /** Висота, поділена на більший горизонтальний габарит. */
  bodyAspect: 1.05,
  /** Трикутників на одне коралове тіло. */
  bodyTriangles: 760,
  /** Скільки унікальних кольорів у вершинах одного тіла. */
  coloursPerBody: 1,
  /** Відтінки восьми тіл набору, градуси. */
  hues: [42, 69, 86, 138, 173, 197, 219, 347],
} as const;

export interface ReefSilhouette {
  /** Скільки річних колоній у плані. */
  colonies: number;
  /** Висота купола в одиницях виду. */
  domeRise: number;
  /** Радіус купола, поділений на його висоту. Півкуля = 1.0. */
  domeAspect: number;
  /** Найвище коралове тіло в одиницях виду. */
  tallestCoral: number;
  /**
   * Частка ПОВНОЇ висоти рифа, яку дає найвищий корал.
   *
   * Головне число цього файлу. Воно відповідає на питання, на яке
   * «скільки колоній» не відповідає: риф це корали, що ростуть на
   * камені, чи камінь, на якому щось наросло. Нуль — гола брила.
   */
  coralSilhouetteShare: number;
  /**
   * Яку частку видимої згори площі купола вкривають шапки колоній.
   *
   * Сума площ дисків колоній, поділена на площу диска купола. Саме це
   * число, а не висота корала, вирішує, чи читається камінь підкладкою:
   * гола порода між колоніями — це те, що око бачить першим.
   */
  coverage: number;
  /** Стрункість коралового тіла: висота / ширина. Медіана по всіх тілах. */
  bodyAspect: number;
  /** Найвище тіло, поділене на найнижче. */
  sizeSpread: number;
}

const EMPTY: ReefSilhouette = {
  colonies: 0,
  domeRise: 0,
  domeAspect: 0,
  tallestCoral: 0,
  coralSilhouetteShare: 0,
  coverage: 0,
  bodyAspect: 0,
  sizeSpread: 0,
};

function median(values: readonly number[]): number {
  if (values.length === 0) return 0;
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor(sorted.length / 2)]!;
}

/**
 * Силует рифа з готового плану.
 *
 * Береться ПЛАН, а не меш, і це рішення: план — це те, що вирішує закон
 * росту, і саме його правлять, коли кадр негарний. Мірка по трикутниках
 * дала б ті самі числа плюс шум тріангуляції, а виправляти однаково
 * довелось би план.
 */
export function reefSilhouetteProfile(plan: ReefPlan): ReefSilhouette {
  const rise = Math.max(0, plan.head.rise);
  const radius = Math.max(0, plan.head.radius);
  if (rise <= 0 || radius <= 0) return EMPTY;

  const heights: number[] = [];
  const aspects: number[] = [];
  let colonyArea = 0;
  for (const colony of plan.colonies) {
    colonyArea += Math.PI * colony.size.radius * colony.size.radius;
    for (const body of colony.bodies) {
      heights.push(body.height);
      if (body.radius > 0) aspects.push(body.height / (2 * body.radius));
    }
  }
  if (heights.length === 0) {
    return { ...EMPTY, colonies: plan.colonies.length, domeRise: rise, domeAspect: radius / rise };
  }

  const tallest = Math.max(...heights);
  const smallest = Math.min(...heights);

  return {
    colonies: plan.colonies.length,
    domeRise: rise,
    domeAspect: radius / rise,
    tallestCoral: tallest,
    coralSilhouetteShare: tallest / (rise + tallest),
    coverage: colonyArea / (Math.PI * radius * radius),
    bodyAspect: median(aspects),
    sizeSpread: smallest > 0 ? tallest / smallest : 0,
  };
}
