// ============================================================
// Як дерево росте з роками. Чисті функції, жодного Three.
// ------------------------------------------------------------
// ЧОГО НЕ БУЛО. `buildTreeStructure` брала лише насіння: висота стовбура,
// радіус крони й товщина стояли сталими від першого дня, а з віком
// змінювалась тільки КІЛЬКІСТЬ гілок. Це записано й у самому рендерері:
// «measured across the same pipeline at one, three, five, ten and twenty
// years, the published tree comes out 4.97, 5.10, 5.23, 5.00 and 5.25
// engine units tall. Its size does not answer to the relationship's age
// at all». Саме тому дерево й підганялось під сталу висоту — рости йому
// було нічим.
//
// ЩО ПОПРОСИВ ВЛАСНИК, дослівно: перший рік — росток; другий — видно
// маленький стовбур, що тягнеться догори; третій — з'являються гілки, і
// стовбур грубшає; четвертий — грубшають і стовбур, і гілки; п'ятий —
// дерево вже добре окріпло; і так до сорока, коли воно високе, з багатьма
// гілками, товстим стовбуром і густим листям.
//
// ЯК РОСТЕ СПРАВЖНЄ ДЕРЕВО, і чому крива саме така:
//
//  * висота набирається ШВИДКО замолоду й сповільнюється — річний приріст
//    падає, коли дерево більше не бореться за світло;
//  * товщина стовбура, навпаки, тягнеться далі за висоту: дерево додає
//    кільце щороку й тоді, коли вгору вже не йде. Тому радіус має
//    ВІДСТАВАТИ замолоду й доганяти під кінець;
//  * крона з'являється пізніше за стовбур: у ростка її немає взагалі, і
//    саме тому третій рік у власника — «є гілки», а не перший.
// ============================================================

/** Скільки років до дорослого дерева. Число власника. */
export const TREE_FULL_TERM_YEARS = 40;

const DAYS_PER_YEAR = 365.2425;

/**
 * Частка зросту стовбура, яку має пара цього віку.
 *
 * Показник 0.7, а не 1: приріст найбільший у перші роки й далі згасає.
 * Виміряно на самій кривій, у частках дорослого:
 *
 *   рік 1  — 0.08   росток
 *   рік 2  — 0.13   стовбур видно
 *   рік 3  — 0.17
 *   рік 5  — 0.24
 *   рік 10 — 0.40
 *   рік 20 — 0.65
 *   рік 40 — 1.00
 */
export function treeAgeProgress(daysTogether: number): number {
  const days = Number.isFinite(daysTogether) ? Math.max(0, daysTogether) : 0;
  const years = days / DAYS_PER_YEAR;
  return Math.min(1, years / TREE_FULL_TERM_YEARS) ** 0.7;
}

/** Найменша частка дорослої висоти — росток, а не порожній ґрунт. */
const TRUNK_SEED_SHARE = 0.07;

/**
 * Множник висоти стовбура.
 *
 * Не від нуля: дерева віком нуль на екрані не буває, а порожній горщик —
 * це не «наша історія щойно почалась», це поламаний екран.
 */
export function treeTrunkHeightScale(daysTogether: number): number {
  return TRUNK_SEED_SHARE + (1 - TRUNK_SEED_SHARE) * treeAgeProgress(daysTogether);
}

/**
 * Множник товщини стовбура.
 *
 * ВІДСТАЄ від висоти навмисно (показник 1.4 поверх прогресу): росток —
 * це тонкий прутик, а не мініатюрна копія дорослого дерева. Саме
 * відставання й дає власникову послідовність «третій рік стовбур грубшає,
 * четвертий грубшає ще» — товщина продовжує набиратись тоді, коли висота
 * вже сповільнилась.
 */
export function treeTrunkRadiusScale(daysTogether: number): number {
  // Нижче за насінину висоти (0.07) навмисно: інакше «росток» виходив
  // товщим за себе — виміряно, 0.183 проти 0.140 на першому році.
  const seed = 0.05;
  return seed + (1 - seed) * treeAgeProgress(daysTogether) ** 1.4;
}

/**
 * Множник крони — радіуса й висоти разом.
 *
 * Стартує ПІЗНІШЕ за стовбур: до третього року майже нуль, бо в ростка
 * крони немає. `max(0, progress − 0.12)`, віднормований назад, дає рівно
 * це: на першому році 0, на другому ледь помітно, на третьому крона вже
 * є — і далі росте разом із деревом.
 */
export function treeCrownScale(daysTogether: number): number {
  const progress = treeAgeProgress(daysTogether);
  const onset = 0.12;
  if (progress <= onset) return 0.06;
  return 0.06 + 0.94 * ((progress - onset) / (1 - onset));
}
