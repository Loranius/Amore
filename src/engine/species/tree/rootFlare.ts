// ============================================================
// Комель — потовщення стовбура там, де він входить у землю.
// ------------------------------------------------------------
// ТРЕТІЙ РОЗРИВ, ЯКИЙ ЗНАЙШОВ ЕТАЛОН (ADR-0104 §4, закрито в ADR-0106).
//
// Виміряно на сороковому році: радіус біля землі 0.0230 висоти проти
// еталонних 0.0380 — наш стовбур на 39% тонший там, де живе дерево
// найтовще. На знімку це читається жердиною, встромленою в ґрунт: стовбур
// однакової товщини від коріння до крони.
//
// ЧОМУ НЕ СТРУНКІСТЮ. Найпростіше було б зробити весь стовбур товщим —
// опустити `treeSlenderness`. Розгортка показала, що це не працює:
//
//   стрункість 29 -> радіус основи 0.0230
//   стрункість 25 -> 0.0255
//   стрункість 22 -> 0.0280
//   стрункість 19 -> 0.0312
//
// Навіть 19 не дотягує до 0.0380, а 19 — це вже поза межами живих дерев
// (20-60, `ageScale.ts`). Причина в тому, що стрункість описує СТОВБУР, а
// різниця сидить у КОМЕЛІ: еталон має стовбур 25 і окреме потовщення 1.9
// в найнижчій десятині. Тобто бракувало не товщини взагалі, а саме цієї
// однієї речі, і робити замість неї весь стовбур бочкою було б підміною.
//
// ЩО ЦЕ ЗА ФОРМА В ПРИРОДІ. Комель — не оздоба: дерево нарощує деревину
// там, де момент від вітру найбільший, а це основа стовбура. Тому спад
// квадратичний і короткий — десята частина зросту, — а не плавний по всій
// висоті.
// ============================================================
import type { OrganicSkeletonState } from '../../labs/organic';

/**
 * У скільки разів комель товщий за стовбур над ним.
 *
 * ЧИСЛО НЕ ВИВЕДЕНЕ, А ВИМІРЯНЕ, і причина в тому, що між законом і
 * намальованим стовбуром стоїть стиснення меша.
 *
 * Перша редакція рахувала його арифметикою: еталон оголошує комель 1.9,
 * намальований стовбур виходить у 1.33 раза товщим за скелет, отже закон
 * має додати 1.9 / 1.33 ≈ 1.43. На скелеті це справдилось точно — радіус
 * основи 0.0200 -> 0.0286 висоти, рівно ×1.43. А на МЕШІ вийшло 0.0230 ->
 * 0.0279, тобто ×1.09 замість ×1.43: сім восьмих потовщення просто
 * зникли.
 *
 * Причина — `TREE_TRUNK_MAX_AXIAL_STRIDE`. На сорока роках стовбур
 * малюється КОЖНИМ ВОСЬМИМ вузлом, а радіуси між збереженими вузлами
 * інтерполюються. Потовщення, яке сходить за десяту частину зросту,
 * потрапляє між двома збереженими вузлами й згладжується. Тобто короткий
 * різкий комель у цьому конвеєрі намалювати не можна взагалі, хоч би що
 * казав закон.
 *
 * Тому спад ширший (див. `TREE_ROOT_FLARE_SPAN`), а множник підібрано
 * виміром до еталонних 0.0380:
 *
 *   1.43 -> 0.0290    1.75 -> 0.0342    2.10 -> 0.0410
 *
 * 1.95 лягає на 0.0380 і є те, що стоїть тут.
 */
export const TREE_ROOT_FLARE = 1.95;

/**
 * Частка висоти, на якій комель сходить нанівець.
 *
 * П'ята, а не десята, як в еталона, і це поступка стисненню меша, названа
 * вголос: за десятої частки потовщення губиться між збереженими вузлами
 * стовбура (див. вище). Виміряно, що ширший спад доносить його до екрана:
 * за того самого множника 1.43 десята дає 0.0279, шоста 0.0290, п'ята —
 * стільки ж, і далі не росте.
 *
 * Ширше робити не можна: спад на чверть зросту зробив би стовбур конічним
 * по всій нижній третині — це вже інша порода й інша форма.
 */
export const TREE_ROOT_FLARE_SPAN = 0.20;

const round6 = (value: number): number => Math.round(value * 1e6) / 1e6;

/**
 * Потовщити стовбур біля землі.
 *
 * Застосовується ПІСЛЯ закону висоти й товщини (`scaleTreeSkeletonToAge`) і
 * ДО скелетних гілок: гілка бере товщину свого комірця з вузла, до якого
 * кріпиться, і мусить бачити вже готовий стовбур. Найнижча скелетна гілка
 * сидить на 0.27 висоти, тобто далеко за межами спаду, — але порядок має
 * бути названий, а не випадковий.
 *
 * Чіпає РАДІУСИ й нічого більше: жодна позиція не рухається, тож ані
 * висота, ані силует крони, ані бюджет вершин не змінюються.
 */
export function applyTreeRootFlare(skeleton: OrganicSkeletonState): OrganicSkeletonState {
  if (skeleton.nodes.length === 0) return skeleton;

  let top = Number.NEGATIVE_INFINITY;
  let bottom = Number.POSITIVE_INFINITY;
  for (const node of skeleton.nodes) {
    if (node.position.y > top) top = node.position.y;
    if (node.position.y < bottom) bottom = node.position.y;
  }
  const height = top - bottom;
  if (!Number.isFinite(height) || height <= 1e-6) return skeleton;

  const span = height * TREE_ROOT_FLARE_SPAN;
  return {
    ...skeleton,
    nodes: skeleton.nodes.map((node) => {
      const above = node.position.y - bottom;
      if (above >= span) return node;
      const share = 1 - above / span;
      return {
        ...node,
        radius: round6(node.radius * (1 + (TREE_ROOT_FLARE - 1) * share * share)),
      };
    }),
  };
}
