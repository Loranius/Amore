import { describe, expect, it } from 'vitest';
import { byCodePoint } from './index';

/*
 * ДОКАЗ, ЩО ЗАМІНА БУЛА ПОТРІБНА (ADR-0205).
 *
 * Цей файл — один із двох, яким сторож `lib/noLocaleCompare.test.ts`
 * дозволяє вживати заборонений виклик у коді, і причина рівно одна:
 * твердження «порядок залежить від мови телефона» не можна довести, не
 * спитавши двох мов. Сторож, який не показує, від чого стереже, доводить
 * менше, ніж здається.
 */

/** Назви міст пари — не вигадані, а такої ж форми, як у «Наш шлях». */
const PLACES = ['Їжаківка', 'Ізмаїл', 'Івано-Франківськ', 'Йосипівка'];

describe('порядок мусить бути однаковий в обох партнерів', () => {
  it('ICU розходиться сам із собою між `en-US` і `uk-UA`', () => {
    /*
     * Ось уся вада в трьох рядках. Пісочниця, у якій знімаються ВСІ
     * докази цього проєкту, рахує під `en-US`; телефон пари — під
     * `uk-UA`. А `features/home/artifact/growthEvents.ts` сортував місця
     * за назвою, і цей порядок задає ранг шпиля навколо монарха.
     */
    const en = [...PLACES].sort((left, right) => left.localeCompare(right, 'en-US'));
    const uk = [...PLACES].sort((left, right) => left.localeCompare(right, 'uk-UA'));
    expect(en).not.toEqual(uk);
    expect(en.slice(1, 3)).toEqual(['Їжаківка', 'Ізмаїл']);
    expect(uk.slice(1, 3)).toEqual(['Ізмаїл', 'Їжаківка']);
  });

  it('`byCodePoint` не питає в середовища нічого', () => {
    const ours = [...PLACES].sort(byCodePoint);
    expect(ours).toEqual(['Івано-Франківськ', 'Ізмаїл', 'Їжаківка', 'Йосипівка']);
    /*
     * І окремо — що наш порядок НЕ збігається з жодною з двох локалей
     * випадково: інакше цей тест був би зелений і на зламаному
     * компараторі, який просто кличе ICU.
     */
    const en = [...PLACES].sort((left, right) => left.localeCompare(right, 'en-US'));
    expect(ours).not.toEqual(en);
  });
});

describe('byCodePoint', () => {
  it('вважає рівними однакові рядки в різних формах Юнікоду', () => {
    /*
     * «Київ» у NFC і «Київ» у NFD виглядають однаково, а голі кодові
     * точки кажуть «різні» (1). §4 стандарту детермінізму вимагає саме
     * НОРМАЛІЗОВАНИХ рядків, і ось чому: інакше рівність залежала б від
     * того, яким шляхом рядок потрапив у базу, а не від написаного.
     */
    const nfc = 'Київ';
    const nfd = nfc.normalize('NFD');
    expect(nfc === nfd, 'форми мусять бути різними рядками').toBe(false);
    expect(byCodePoint(nfc, nfd)).toBe(0);
    // І без нормалізації порядок був би інший — тобто рядок робить роботу.
    expect(nfc > nfd).toBe(true);
  });

  it('дефіс іде перед підкресленням, як у кодових точках', () => {
    /*
     * Виміряно: ICU ставить `wishlist_item` ПЕРЕД `wishlist-item` в усіх
     * чотирьох перевірених локалях, а кодові точки — навпаки, бо `-`
     * (0x2D) менший за `_` (0x5F). Ключі порталу складені з обох знаків,
     * тож це не екзотика, а щоденна форма даних.
     */
    expect(byCodePoint('wishlist-item', 'wishlist_item')).toBe(-1);
    expect('wishlist_item'.localeCompare('wishlist-item', 'en-US')).toBeLessThan(0);
  });

  it('великі літери йдуть перед малими', () => {
    // ICU дає протилежне («e1» перед «E1») в усіх перевірених локалях.
    expect(byCodePoint('E1', 'e1')).toBe(-1);
    expect('E1'.localeCompare('e1', 'en-US')).toBeGreaterThan(0);
  });

  it('однакові рівні, різні впорядковані строго, порожній найменший', () => {
    expect(byCodePoint('a', 'a')).toBe(0);
    expect(byCodePoint('a', 'b')).toBe(-1);
    expect(byCodePoint('b', 'a')).toBe(1);
    expect(byCodePoint('', 'a')).toBe(-1);
  });

  it('годиться як компаратор для ISO-дат', () => {
    /*
     * Половина замінених місць сортувала саме дати. Порядок тут той
     * самий, що й був, — і це варто мати записаним, бо саме ця
     * незмінність дозволила замінити 53 виклики без жодної зміни
     * поведінки в тестах.
     */
    const days = ['2026-09-21', '2024-01-02', '2026-01-02', '2024-12-31'];
    expect([...days].sort(byCodePoint)).toEqual([
      '2024-01-02', '2024-12-31', '2026-01-02', '2026-09-21',
    ]);
  });
});
