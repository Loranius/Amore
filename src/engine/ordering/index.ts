// ============================================================
// Порядок рядків — одна адреса на весь портал.
// ------------------------------------------------------------
// `docs/01_CONTRACTS/DETERMINISM_STANDARD.md` §4 каже дослівно: «Canonical
// ordering uses an explicit comparator over normalized strings and numeric
// keys. Do not use `localeCompare`.» На момент появи цього файлу в `src/`
// було **49 викликів `localeCompare`** і жодного сторожа.
//
// ЦЕ НЕ БУЛА НЕДБАЛІСТЬ, А НЕРІВНІСТЬ. Одне місце правило виконувало й
// пояснювало чому (`features/onboarding/sweepEntries.ts`: «порядок мусить
// бути однаковий у всіх, а не залежати від мови телефона»), сорок дев'ять
// — ні. Заборона без адреси, куди піти натомість, не виконується: той
// самий урок, що `CLAUDE.md` уже записав про `Math.random()`.
//
// ЧОМУ ЦЕ НЕ ГІГІЄНА, А ВАДА. Виміряно тут-таки, на справжніх назвах міст:
//
//   кодові точки: Івано-Франківськ Ізмаїл Їжаківка Йосипівка …
//   en-US       : Івано-Франківськ Їжаківка Ізмаїл Йосипівка …
//   uk-UA       : Івано-Франківськ Ізмаїл Їжаківка Йосипівка …
//
// `Їжаківка` та `Ізмаїл` міняються місцями між локалями. Пісочниця, у якій
// знімаються всі докази, рахує під `en-US`; телефон пари — під `uk-UA`.
// А `features/home/artifact/growthEvents.ts` сортує місця саме за назвою, і
// цей порядок задає ранг шпиля в стрімі. Тобто кадр, на який дивиться той,
// хто робить зміну, міг відрізнятись від кадру, який бачить пара.
//
// ЧОМУ ВИХОДІВ ДВА, А НЕ ОДИН — І ЦЕ ВИПРАВЛЕННЯ ВЛАСНОЇ ПОМИЛКИ.
//
// Перша редакція цього файлу мала ОДИН експорт, який нормалізував у NFC на
// КОЖНОМУ порівнянні. Виглядало це як безкоштовна сумлінність, і перший
// замір (2000 довгих ключів) це підтвердив: 0.82 мс проти 1.01 у
// `localeCompare`. Число було праведне, а висновок — ні: набір ключів був
// нетиповий, і на справжній формі даних дерева все виявилось навпаки.
//
// Виміряно на 5000 ключів вигляду `branch-12-3400` (30 сортів, один процес):
//
//   голі кодові точки      1.64 мс
//   нормалізація завжди    7.12 мс   ← перша редакція
//   фільтр «чи є діакритика» 3.41 мс
//   localeCompare          1.58 мс
//
// Тобто нормалізація на кожному порівнянні коштує **вчетверо** проти голих
// кодових точок. І це не лишилось теорією: холодна збірка дерева на історії
// пари пішла з медіани 201.6 мс до 217.8 (A/B на одному стенді), а
// `tree-production-acceptance.spec.ts` тримає межу 220 — і в CI прогін 1193
// упав на 259.1 мс.
//
// ПРАВИЛЬНЕ ЧИТАННЯ §4 СТАНДАРТУ. Він каже «explicit comparator over
// NORMALIZED strings» — тобто нормалізація це властивість ВХОДУ, а не
// обов'язок кожного порівняння. Тому:
//
//   `byCodePoint`       — ключі, ідентифікатори, ISO-дати. Гаряча дорога.
//   `byNormalizedText`  — людський текст: назви місць, повідомлення.
//
// Кожне місце виклику тепер каже, що саме воно сортує, і платить рівно за
// це. Виходи обидва вживані — напівфабрикатів тут немає.
//
// НОРМАЛІЗАЦІЯ ТАМ, ДЕ ВОНА Є, НЕ ПЕДАНТИЗМ. «Київ» у NFC і «Київ» у NFD
// виглядають однаково, а голі кодові точки кажуть про них «різні» (1).
// Після NFC — «рівні» (0). Без цього рівність залежала б від того, яким
// шляхом рядок потрапив у базу, а не від того, що в ньому написано.
//
// ЧОМУ ТУТ НЕМАЄ ДРУГОГО ВИХОДУ — З ЛОКАЛЛЮ. Була спокуса одразу додати
// `byUkrainianName` «на майбутнє», для справді людських абеткових списків.
// Але жодного такого списку в порталі сьогодні немає: усі 49 місць
// сортували ключі, ISO-дати або текст, порядок якого мусить збігатись в
// обох партнерів. Експорт, якого ніхто не кличе, — це виробничий
// напівфабрикат, а їх `CLAUDE.md` забороняє прямо.
//
// ЧОМУ ЦЕЙ ФАЙЛ У РУШІЇ, А НЕ В `src/lib`. Порядок канонічного виходу —
// це контракт детермінізму, тобто рушійна річ. Плюс суто практичне: рушій
// сьогодні не імпортує з `@/lib` НІЧОГО (перевірено: нуль входжень), і
// заводити такий напрям заради компаратора означало б купити дешевий
// комфорт за нову залежність. Портал імпортує з рушія й так.
//
// Тому правило просте: **якщо колись знадобиться абетковий порядок для
// ОЧЕЙ — він з'являється ТУТ, поруч із цим абзацом, із явною локаллю та
// причиною, а не рядком `localeCompare` на місці виклику.** Сторож
// (`src/lib/noLocaleCompare.test.ts`) стежить рівно за цим.
// ============================================================

/**
 * Канонічний порядок: голі кодові точки.
 *
 * Явний компаратор, якого вимагає §4 стандарту детермінізму. Не питає в
 * середовища нічого — ані локалі, ані версії ICU.
 *
 * ДЛЯ КЛЮЧІВ, ІДЕНТИФІКАТОРІВ І ISO-ДАТ, тобто для рядків, які склав сам
 * портал і які за побудовою вже в NFC. Для людського тексту — сусідня
 * функція; різницю видно в §5 ADR-0205 числами.
 */
export function byCodePoint(left: string, right: string): number {
  if (left < right) return -1;
  if (left > right) return 1;
  return 0;
}

/**
 * Порядок людського тексту: NFC, потім кодові точки.
 *
 * Для назв місць, повідомлень діагностики й усього, що набрала людина або
 * віддала чужа система: той самий «Київ» приїжджає то в NFC, то в NFD, і
 * без зведення до однієї форми вони порівнюються як різні рядки.
 *
 * Дорожче за `byCodePoint` приблизно вчетверо (виміряно, див. шапку), тож
 * місце виклику мусить свідомо обрати саме це — і жодне з них не лежить на
 * гарячій дорозі збірки геометрії.
 */
export function byNormalizedText(left: string, right: string): number {
  return byCodePoint(left.normalize('NFC'), right.normalize('NFC'));
}
