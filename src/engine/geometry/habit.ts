// ============================================================
// Форми огранки: чим один габітус відрізняється від іншого.
// ------------------------------------------------------------
// Таблиця чисел, і нічого крім. ВИБІР габітусу належить видові —
// це риса пари, взята з дати початку (`species/crystal/habit.ts`);
// сюди він приходить рядком в атрибутах тіла, як приходив архетип.
//
// Межа тримається навмисно: том геометрії не читає виду. Інакше
// «яку форму носить ця пара» й «як ця форма ріжеться» жили б в
// одному файлі, і змінити одне, не зачепивши інше, стало б неможливо.
//
// Словник — стандартні habits мінералогії під тими іменами, які
// `CrystalArchetype` уже мав: `needle` це acicular, `massive` це той
// тупий стовп, який власник описав як «сталагміт».
// ============================================================

export interface CrystalHabitShape {
  /** Стиск перерізу по двох осях: 1 — коло. */
  scaleX: number;
  scaleZ: number;
  /**
   * Смуга кута корони, градуси.
   *
   * Більший кут — вища корона, тобто гостріший шпиль; менший — тупіша
   * шапка. Смуга, а не число: у межах форми кожна пара має свій нахил.
   */
  crownMinDeg: number;
  crownMaxDeg: number;
  /** Верхівка зрізана, а не зведена в точку. */
  blunt: boolean;
  /**
   * Множник обхвату.
   *
   * ВИСОТУ габітус не чіпає — вона належить закону росту (роки пари), і
   * форма не має права робити пару старшою. Різницю силуету дає саме
   * обхват: голка вужча за призму вдвічі, плита ширша за неї на чверть.
   */
  girth: number;
  /** Ті самі чотири величини, що й у `shapeTuning`. */
  asymmetry: number;
  twist: number;
  lean: number;
  phase: number;
}

const PRISMATIC: CrystalHabitShape = {
  scaleX: 0.94, scaleZ: 1.06,
  crownMinDeg: 49, crownMaxDeg: 56,
  blunt: false,
  girth: 1,
  asymmetry: 0.18, twist: 0.2, lean: 0.09, phase: 0.08,
};

const SHAPES: Readonly<Record<string, CrystalHabitShape>> = {
  prismatic: PRISMATIC,
  massive: {
    /*
     * Товстий і тупий: корона положиста, переріз майже круглий.
     *
     * 41–47, а не 33–40, як було в першій редакції. Причина виміряна, а
     * не вгадана: власний тест «жодна дрібна грань не спадає в
     * подряпину» показав, що при 33–40 разом зі зрізаною верхівкою
     * найменша грань корони виходила 0.0225 ширини тіла проти порога
     * 0.03 — тобто грань, яка коштує площину, нормаль і ребро, а
     * рендериться подряпиною. При 41–47 вона 0.069.
     *
     * Тупість від цього не зникла: її дає ЗРІЗ (`blunt`), а не кут, і
     * проти призматичних 49–56 корона все одно помітно положистіша.
     */
    scaleX: 1.04, scaleZ: 1.02,
    crownMinDeg: 41, crownMaxDeg: 47,
    blunt: true,
    girth: 1.22,
    asymmetry: 0.12, twist: 0.09, lean: 0.07, phase: 0.05,
  },
  needle: {
    // Голка: вузька, різка, з довгим шпилем і меншою кількістю граней.
    scaleX: 0.86, scaleZ: 0.9,
    crownMinDeg: 62, crownMaxDeg: 70,
    blunt: false,
    girth: 0.64,
    asymmetry: 0.08, twist: 0.16, lean: 0.13, phase: 0.055,
  },
  tabular: {
    /*
     * Плита: широка, присадкувата, з ясно вираженим стиском перерізу.
     *
     * 39–45 із тієї самої причини, і тут вада була вдвічі гірша: при
     * 30–38 найменша грань виходила 0.0084 ширини — утричі нижче за
     * поріг. Плита має найширший переріз, тож її корона найкоротша, і
     * пласкому куту тут просто немає де розвернутись.
     */
    scaleX: 0.72, scaleZ: 1.2,
    crownMinDeg: 39, crownMaxDeg: 45,
    blunt: true,
    girth: 1.3,
    asymmetry: 0.16, twist: 0.11, lean: 0.11, phase: 0.07,
  },
};

/*
 * Чого тут НЕМАЄ і не буде: кількості граней.
 *
 * У першій редакції таблиця мала `facetMin`/`facetMax` — і жоден рядок
 * коду їх не читав. Це рівно та «фальшива реалізація», яку забороняє
 * CLAUDE.md: поле, що виглядає як закон, а насправді не робить нічого.
 *
 * Прибрано, а не підключено, бо підключати не можна: за ADR-0004
 * кількість граней монарха ЗАРОБЛЕНА фотографіями пари
 * (`monarchFacetCount`). Якби її задавав габітус, дата початку стосунків
 * мовчки перебивала б те, що пара зробила своїми руками. Габітус володіє
 * обхватом, кутом корони й зрізом — не гранями.
 */

/** Форма за назвою. Незнайома назва дає призму — форму за замовчуванням. */
export function crystalHabitShape(habit: string): CrystalHabitShape {
  return SHAPES[habit] ?? PRISMATIC;
}
