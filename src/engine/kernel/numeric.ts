// ============================================================
// Детерміністичне ядро: числа, на яких тримаються всі томи.
// ------------------------------------------------------------
// `docs/00_GOVERNANCE/REPOSITORY_STRUCTURE.md` передбачає окремий пакет
// `deterministic-kernel` (канонізація, хеш, PRNG, порядок), від якого
// можуть залежати всі томи, а він сам — ні від кого. До ADR-0257 його не
// було, і `clamp01` з `round6` жили шістнадцятьма копіями в `growth`,
// `material`, `life`, `barkSurface`, `labs/organic` і видах.
//
// Сюди потрапило лише те, що в усіх копіях давало ОДНАКОВИЙ результат на
// будь-якому вході, зокрема NaN, ±Infinity і −0 (`Object.is`). Копії, які
// поводились інакше, сюди не зведено — зведення змінило б числа:
//   - `seededUnit` — три різні алгоритми (види, `growth`, `life`);
//   - `clamp01` у `species/shared/relationshipYear.ts` повертає −0 на −0.
//
// Ядро не імпортує нічого: ні томів, ні адаптерів.
// ============================================================

/** Обрізає до [0, 1]; NaN лишається NaN, −0 стає +0. */
export function clamp01(value: number): number {
  return Math.max(0, Math.min(1, value));
}

/** Округлює до шести знаків — канонічна точність опублікованих станів. */
export function round6(value: number): number {
  return Math.round(value * 1_000_000) / 1_000_000;
}
