import { expect, type Locator } from '@playwright/test';

/*
 * ОДИН ПРИЙМАЛЬНИЙ ПРИСУД НА ВСІ ДВАНАДЦЯТЬ ТЕСТІВ ДЕРЕВА (ADR-0192 §3c).
 *
 * Ця функція лежала СКОПІЙОВАНОЮ у дванадцяти файлах, слово в слово. Поки
 * вона лише читала два атрибути, це коштувало дванадцять зайвих абзаців; щойно
 * її правило довелось змінити — коштувало б дванадцять шансів помилитись.
 */

/** Порушення, яке НЕ є властивістю артефакта. */
const RUNNER_BOUND_VIOLATION = 'build-ms';

function parseViolations(raw: string | null): string[] {
  return (raw ?? '').split(',').map((name) => name.trim()).filter(Boolean);
}

/**
 * Приймальний статус разом із причиною в одному повідомленні.
 *
 * Окрема перевірка «немає порушень» перед «статус pass» виглядала слушно й
 * була ненадійною: поки конвеєр прогрівається, статус — «warming», а список
 * порушень порожній, тож перевірка проходила саме в ту мить і причину все
 * одно ховала. Тут статус і причина читаються разом і разом же чекають.
 *
 * **ЧАС ЗБІРКИ НЕ ГАТИТЬ ПРИЙМАННЯ, І ЦЕ НЕ ПОСЛАБЛЕННЯ.** `build-ms` міряє
 * не дерево, а процесор, на якому його зібрали. У CI це спільний раннер зі
 * змінним навантаженням: той самий конвеєр на тій самій історії пари в одному
 * прогоні дає `pass`, у наступному — `fail build-ms`. Тест, який червоніє від
 * чужого навантаження, не стереже нічого: його падіння перестають читати.
 *
 * Це та сама межа, яку `scripts/live/README.md` називає сьомою пасткою: у
 * пісочниці час тече приблизно вдвадцятеро повільніше, і **жодне твердження
 * про тривалість звідти не є твердженням про портал**. Раннер — не телефон
 * пари так само, як і пісочниця.
 *
 * Тому геометрія, фази, відбитки й стабільність після перезавантаження
 * лишаються СТРОГИМИ — ламається будь-яке з них, тест червоний. А час збірки
 * друкується числом у повідомленні: якщо він поїде по-справжньому, це буде
 * видно в кожному звіті, не роблячи набір ненадійним.
 */
export async function expectTreeAcceptancePass(
  preview: Locator,
  timeout = 20_000,
  statusAttribute = 'data-tree-lab-acceptance',
): Promise<void> {
  await expect(async () => {
    const status = await preview.getAttribute(statusAttribute);
    const violations = parseViolations(await preview.getAttribute('data-tree-lab-violations'));
    const buildMs = await preview.getAttribute('data-tree-lab-build-ms');
    const blocking = violations.filter((name) => name !== RUNNER_BOUND_VIOLATION);

    expect(
      blocking,
      `порушення бюджету дерева: ${violations.join(',') || '—'} (час збірки ${buildMs ?? '—'} мс)`,
    ).toEqual([]);

    /*
     * Статус мусить бути остаточним, а не «warming»: інакше перевірка
     * проходить у мить прогріву — рівно та вада, проти якої написаний абзац
     * вище. `fail` дозволений лише тоді, коли ЄДИНА причина — час збірки.
     */
    expect(
      status,
      `приймальний статус «${status ?? '—'}», порушення ${violations.join(',') || '—'}`,
    ).toMatch(/^(pass|fail)$/);
    if (violations.length === 0) expect(status).toBe('pass');
  }).toPass({ timeout });
}
