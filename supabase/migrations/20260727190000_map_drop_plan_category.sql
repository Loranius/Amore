-- ============================================================
-- Карта: прибрати категорію «Плануємо».
-- ------------------------------------------------------------
-- Вона існувала з першого дня модуля й не набрала ЖОДНОЇ мітки: 26
-- збережених місць це 13 ресторанів, 9 «були» і 4 «улюблене». Половина
-- обіцянки модуля («карта спогадів і планів») насправді ніколи не
-- працювала, і чотири кнопки в сітці категорій замість трьох були
-- податком на кожне додавання місця.
--
-- Планування нікуди не дівається — воно живе в календарі, де в події є
-- дата, нагадування й статус. Мітка на карті нічого з цього не має.
--
-- Безпечно: перевірено перед застосуванням, рядків із 'plan' немає.
-- Якщо колись знадобиться повернути — це один ALTER назад.
-- ============================================================

do $$
declare
  stragglers int;
begin
  select count(*) into stragglers from public.map_pins where category = 'plan';
  if stragglers > 0 then
    raise exception 'map_pins містить % міток категорії plan — міграція зупинена', stragglers;
  end if;
end $$;

alter table public.map_pins drop constraint map_pins_category_check;

alter table public.map_pins add constraint map_pins_category_check
  check (category = any (array['visited'::text, 'restaurant'::text, 'favorite'::text]));
