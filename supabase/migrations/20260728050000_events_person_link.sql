-- ============================================================
-- Події: чий це день народження.
-- ------------------------------------------------------------
-- Досі людина існувала лише всередині назви («День народження мами»), і
-- застосунок не міг відрізнити день народження партнера від дня
-- народження тещі. Наслідок видно в нагадуваннях: крон шле «СЬОГОДНІ —
-- День народження Лєни» ОБОМ, зокрема й самій Лєні.
--
-- Колонка нічого не вимагає: null означає «людина не з застосунку»
-- (батьки, діти, друзі) — саме так і лишиться для більшості подій.
-- Прив'язка потрібна рівно для двох людей у парі.
-- ============================================================

alter table public.events
  add column if not exists person_user_id integer references public.users(id);

comment on column public.events.person_user_id is
  'Кого стосується подія, якщо це користувач застосунку (день народження партнера). null — людина поза застосунком.';

-- Часткового індексу вистачить: заповнених рядків одиниці, і читають їх
-- разом з усією таблицею подій, а не окремим запитом.
create index if not exists events_person_idx
  on public.events (person_user_id)
  where person_user_id is not null;
