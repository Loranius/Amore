-- Медіа нарешті знає, КОЛИ його закінчили.
--
-- `adapters/media.ts` датував переглянуте днем СТВОРЕННЯ рядка й чесно
-- писав про це в коментарі: «The honest fix is a `finished_at` column on
-- `media_items`, written when the status moves to `done`». Ціна цієї
-- заміни виміряна на робочій базі: усі 194 переглянуті позиції лежать у
-- ЧЕТВЕРТОМУ році стосунків, бо саме тоді вотчліст завели в порталі, —
-- а роки 1–3 не дістають від медіа нічого.
--
--   рік 1 (з 26.12.2022)   медіа 0
--   рік 2                  медіа 0
--   рік 3                  медіа 0
--   рік 4 (іде)            медіа 194
--
-- ЗАСІВ РІВНО ЗІ `created_at`, і лише для `status = 'done'`. Тобто
-- сьогоднішній артефакт не змінюється ні на одиницю: адаптер бачить ті
-- самі дати, що й бачив. Нове поле починає означати щось інше від
-- сьогодні — коли портал писатиме в нього справжній момент завершення.
--
-- Позиції, які ще не переглянуті, лишаються з порожнім `finished_at`:
-- дати завершення в них немає, і вигадувати її не можна.
--
-- Колонка nullable і незруйнівна; відкат — `drop column finished_at`.
--
-- Застосовано на робочій базі Amore 2026-09-01 за прямим рішенням
-- власника (вибір: «Так, застосуй сам» + «Лишити як є, правильно
-- датувати лише нові»).
alter table public.media_items
  add column if not exists finished_at timestamptz;

update public.media_items
   set finished_at = created_at
 where finished_at is null
   and status = 'done';

comment on column public.media_items.finished_at is
  'Коли пару закінчили дивитись/читати. Пише портал при переході в done. '
  'Рядки до 2026-09-01 засіяні з created_at — для них це оцінка, а не факт.';
