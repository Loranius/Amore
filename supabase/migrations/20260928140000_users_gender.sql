-- ============================================================
-- Стать місця в парі (ADR-0228, поправка).
-- ------------------------------------------------------------
-- Після пароля людина, чия пошта ще не прив'язана, бачила «Хто ви в цій
-- парі?» з іменами пари. Власник: незнайомця це загнало б у ступор, а
-- імена до входу показувати не варто. Тепер питання — стать («Чоловік» /
-- «Жінка»), а місце шукається за нею; старий PIN підтверджує, що місце
-- твоє. Стать не секрет і не впливає на доступ: брама членства (ADR-0228)
-- дивиться лише на пошту.
--
-- Позначки для наявних місць ставляться окремо, за словом власника
-- («чоловік чи жінка відповідно до Діма і Лєна»), а не цим файлом: схема
-- не знає, хто в якій парі.
-- ============================================================

alter table public.users
  add column if not exists gender text
  check (gender in ('male', 'female'));

comment on column public.users.gender is
  'Стать місця в парі: male | female. Нею знаходять місце при першому вході поштою (ADR-0228).';
