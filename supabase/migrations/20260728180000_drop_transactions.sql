-- ============================================================
-- Прибирання: мертва таблиця transactions.
-- ------------------------------------------------------------
-- Облік доходів і витрат був у першій версії застосунку й не пережив
-- переїзду: у React-версії до `transactions` НЕ звертається жоден
-- екран, жоден хук і жоден тип. Аудит модуля «Фінанси» показав, що він
-- складається рівно з двох речей — спільних цілей накопичення й
-- вільного ліміту, — а щоденного обліку витрат не існує взагалі.
--
-- У таблиці лишалось 9 рядків від 17–19 червня 2026: дводенна спроба
-- вести доходи/витрати, після якої до неї не повертались. Жодна інша
-- таблиця на неї не посилається (єдиний зовнішній ключ — її власний
-- transactions.created_by → users), тригерів немає, тож видалення
-- нічого за собою не тягне.
--
-- Гілка `table === "transactions"` в edge-функції db-notify лишається
-- мертвою вже зараз: тригера на таблиці немає, і після DROP до неї
-- нічого не дійде. Прибрати її можна при наступному деплої цієї
-- функції — окремо, щоб не тягнути деплой заради коментаря.
-- ============================================================

-- Публікацію realtime чистимо ПЕРЕД drop: інакше в ній лишиться
-- посилання на неіснуючу таблицю.
do $$
begin
  if exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'transactions'
  ) then
    alter publication supabase_realtime drop table public.transactions;
  end if;
end $$;

drop table if exists public.transactions;
